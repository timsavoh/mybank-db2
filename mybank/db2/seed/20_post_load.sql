-- After the bulk load: refresh MQTs and statistics, then check the ledger.
REFRESH TABLE RPT.MQT_DAILY_LIQUIDITY@
REFRESH TABLE RPT.MQT_MERCHANT_SPEND@
CALL SYSPROC.ADMIN_CMD('RUNSTATS ON TABLE TXN.POSTED_TXN WITH DISTRIBUTION AND DETAILED INDEXES ALL')@
CALL SYSPROC.ADMIN_CMD('RUNSTATS ON TABLE GL.GL_ENTRY WITH DISTRIBUTION AND DETAILED INDEXES ALL')@
CALL SYSPROC.ADMIN_CMD('RUNSTATS ON TABLE ACCT.ACCOUNT WITH DISTRIBUTION AND DETAILED INDEXES ALL')@
CALL SYSPROC.ADMIN_CMD('RUNSTATS ON TABLE CUST.CUSTOMER WITH DISTRIBUTION AND DETAILED INDEXES ALL')@

-- Ledger checks: every row should show DIFFERENCE 0.00
SELECT 'ALL GL' AS CHECK_NAME, SUM(AMOUNT) AS DIFFERENCE FROM GL.GL_ENTRY
UNION ALL
SELECT 'CONTROL ' || P.CONTROL_GL_CODE,
       SUM(A.LEDGER_BALANCE) + (SELECT COALESCE(SUM(E.AMOUNT), 0) FROM GL.GL_ENTRY E WHERE E.GL_CODE = P.CONTROL_GL_CODE)
  FROM ACCT.ACCOUNT A JOIN REF.PRODUCT P ON P.PRODUCT_CODE = A.PRODUCT_CODE
 GROUP BY P.CONTROL_GL_CODE
UNION ALL
SELECT 'SUSPENSE 1900', COALESCE(SUM(AMOUNT), 0) FROM GL.GL_ENTRY WHERE GL_CODE = '1900'@
