-- BACKUP COPY of RPT.MONTHLY_SUMMARY loader taken before the 2018 MQT changes - DO NOT DEPLOY
-- (DP 14/02/2018). Reloads RPT.MONTHLY_SUMMARY for a month end and returns it. The live
-- version was dropped with the table; this copy was not.
CREATE OR REPLACE PROCEDURE RPT.MONTHLY_SUMMARY_BAK (
    IN P_MONTH_END DATE
)
    LANGUAGE SQL
    SPECIFIC RPT_MONTHLY_SUMMARY_BAK
    DYNAMIC RESULT SETS 1
    MODIFIES SQL DATA
BEGIN
    DECLARE V_MONTH_END   DATE;
    DECLARE V_MONTH_START DATE;
    DECLARE V_ROWS        INTEGER DEFAULT 0;

    DECLARE C_SUMMARY CURSOR WITH RETURN FOR
        SELECT MONTH_END, PRODUCT_CODE, ACCOUNTS, TOTAL_BALANCE, TXN_COUNT, TOTAL_IN, TOTAL_OUT
          FROM RPT.MONTHLY_SUMMARY
         WHERE MONTH_END = V_MONTH_END
         ORDER BY PRODUCT_CODE;

    -- default: last month
    SET V_MONTH_END = VALUE(P_MONTH_END, LAST_DAY(CURRENT DATE - 1 MONTH));
    SET V_MONTH_END = LAST_DAY(V_MONTH_END);
    SET V_MONTH_START = V_MONTH_END - (DAY(V_MONTH_END) - 1) DAYS;

    DELETE FROM RPT.MONTHLY_SUMMARY WHERE MONTH_END = V_MONTH_END;

    INSERT INTO RPT.MONTHLY_SUMMARY (MONTH_END, PRODUCT_CODE, ACCOUNTS, TOTAL_BALANCE, TXN_COUNT, TOTAL_IN, TOTAL_OUT)
    SELECT V_MONTH_END,
           A.PRODUCT_CODE,
           COUNT(DISTINCT A.ACCOUNT_ID),
           SUM(A.LEDGER_BALANCE),               -- NB current balance, not month-end (DP: fix?)
           VALUE(SUM(T.TXN_COUNT), 0),
           VALUE(SUM(T.TOTAL_IN), 0),
           VALUE(SUM(T.TOTAL_OUT), 0)
      FROM MYBANK.ACCOUNTS A
      LEFT OUTER JOIN (SELECT ACCOUNT_ID,
                              COUNT(*) AS TXN_COUNT,
                              SUM(CASE WHEN AMOUNT > 0 THEN AMOUNT ELSE 0 END) AS TOTAL_IN,
                              SUM(CASE WHEN AMOUNT < 0 THEN 0 - AMOUNT ELSE 0 END) AS TOTAL_OUT
                         FROM MYBANK.TRANSACTIONS
                        WHERE BUSINESS_DATE BETWEEN V_MONTH_START AND V_MONTH_END
                        GROUP BY ACCOUNT_ID) T
        ON T.ACCOUNT_ID = A.ACCOUNT_ID
     WHERE A.STATUS <> 'C'
     GROUP BY A.PRODUCT_CODE;

    GET DIAGNOSTICS V_ROWS = ROW_COUNT;

    /* 2017 version split savings by branch - removed, too many rows for the MI pack
    INSERT INTO RPT.MONTHLY_SUMMARY_BRANCH ...
    SELECT V_MONTH_END, A.BRANCH_ID, A.PRODUCT_CODE, ...
    */

    COMMIT;

    OPEN C_SUMMARY;
END@
