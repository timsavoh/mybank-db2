-- Inbound Faster Payment from the scheme gateway (loadgen). Idempotent on the scheme reference:
-- MERGE on IDEMPOTENCY_KEY 'IN:' || scheme ref, a replay returns the original payment and status.
-- Unknown / closed / loan beneficiary accounts are recorded as rejected (status R), not raised. Raises 75008.
CREATE OR REPLACE PROCEDURE PAY.RECEIVE_INBOUND_PAYMENT (
    IN  P_SORT_CODE     CHAR(6),
    IN  P_ACCOUNT_NO    CHAR(8),
    IN  P_AMOUNT        DECIMAL(15,2),
    IN  P_REMITTER_NAME VARCHAR(60),
    IN  P_REMITTER_SORT CHAR(6),
    IN  P_REMITTER_ACCT CHAR(8),
    IN  P_REFERENCE     VARCHAR(18),
    IN  P_SCHEME_REF    VARCHAR(40),
    OUT P_PAYMENT_ID    BIGINT,
    OUT P_STATUS        CHAR(1)
)
    LANGUAGE SQL
    SPECIFIC PAY_RECEIVE_INBOUND_PAYMENT
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);

    DECLARE V_KEY          VARCHAR(64);
    DECLARE V_DATE         DATE;
    DECLARE V_ACCOUNT_ID   BIGINT;
    DECLARE V_ACCT_STATUS  CHAR(1);
    DECLARE V_PRODUCT_TYPE CHAR(3);
    DECLARE V_CUSTOMER_ID  BIGINT;
    DECLARE V_STATUS       CHAR(1);
    DECLARE V_FAIL_REASON  VARCHAR(100);
    DECLARE V_ROWS         INTEGER DEFAULT 0;
    DECLARE V_REMITTER     VARCHAR(60);
    DECLARE V_TXN_ID       BIGINT;
    DECLARE V_BALANCE      DECIMAL(15,2);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.LOG_ERROR('PAY.RECEIVE_INBOUND_PAYMENT', V_SQLSTATE, V_SQLCODE, V_MSG,
             'SCHEME_REF=' || COALESCE(P_SCHEME_REF, 'NULL') ||
             ' TO=' || COALESCE(P_SORT_CODE, '?') || '/' || COALESCE(P_ACCOUNT_NO, '?') ||
             ' AMOUNT=' || COALESCE(VARCHAR(P_AMOUNT), 'NULL'));
        RESIGNAL;
    END;

    SET P_PAYMENT_ID = NULL;
    SET P_STATUS = NULL;

    IF P_SCHEME_REF IS NULL OR P_AMOUNT IS NULL OR P_AMOUNT <= 0 THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Scheme reference and positive amount required';
    END IF;

    SET V_KEY = 'IN:' || P_SCHEME_REF;
    SET V_DATE = UTIL.POSTING_DATE();
    SET V_REMITTER = UPPER(COALESCE(P_REMITTER_NAME, 'UNKNOWN REMITTER'));

    SELECT A.ACCOUNT_ID, A.STATUS, A.PRIMARY_CUSTOMER_ID, P.PRODUCT_TYPE
      INTO V_ACCOUNT_ID, V_ACCT_STATUS, V_CUSTOMER_ID, V_PRODUCT_TYPE
      FROM ACCT.ACCOUNT A
      JOIN REF.PRODUCT P ON P.PRODUCT_CODE = A.PRODUCT_CODE
     WHERE A.SORT_CODE = P_SORT_CODE
       AND A.ACCOUNT_NO = P_ACCOUNT_NO
      WITH UR;

    IF V_ACCOUNT_ID IS NULL THEN
        -- PAYMENT.ACCOUNT_ID is NOT NULL: 0 means "no such account"
        SET V_ACCOUNT_ID = 0;
        SET V_STATUS = 'R';
        SET V_FAIL_REASON = 'AC01 Beneficiary account not found';
    ELSEIF V_ACCT_STATUS = 'C' THEN
        SET V_STATUS = 'R';
        SET V_FAIL_REASON = 'AC04 Beneficiary account closed';
    ELSEIF V_PRODUCT_TYPE = 'LON' THEN
        SET V_STATUS = 'R';
        SET V_FAIL_REASON = 'AG01 Account cannot receive payments';
    ELSE
        SET V_STATUS = 'C';
    END IF;

    BEGIN
        -- Concurrent replay of the same scheme ref: the loser falls through to the lookup
        DECLARE CONTINUE HANDLER FOR SQLSTATE '23505' SET V_ROWS = 0;

        MERGE INTO PAY.PAYMENT T
        USING (VALUES (V_KEY)) AS S (IDEMPOTENCY_KEY)
           ON T.IDEMPOTENCY_KEY = S.IDEMPOTENCY_KEY
         WHEN NOT MATCHED THEN
            INSERT (DIRECTION, SCHEME, ACCOUNT_ID, AMOUNT, COUNTERPARTY_NAME, COUNTERPARTY_SORT,
                    COUNTERPARTY_ACCT, REFERENCE, STATUS, IDEMPOTENCY_KEY, SCHEME_REF,
                    BUSINESS_DATE, COMPLETED_TS, FAIL_REASON)
            VALUES ('I', 'FPS', V_ACCOUNT_ID, P_AMOUNT, V_REMITTER,
                    COALESCE(P_REMITTER_SORT, '000000'), COALESCE(P_REMITTER_ACCT, '00000000'),
                    P_REFERENCE, V_STATUS, S.IDEMPOTENCY_KEY, P_SCHEME_REF,
                    V_DATE, CASE WHEN V_STATUS = 'C' THEN CURRENT TIMESTAMP END, V_FAIL_REASON);

        GET DIAGNOSTICS V_ROWS = ROW_COUNT;
    END;

    SELECT PAYMENT_ID, STATUS INTO P_PAYMENT_ID, P_STATUS
      FROM PAY.PAYMENT
     WHERE IDEMPOTENCY_KEY = V_KEY;

    -- Replay, or a rejection: nothing to post
    IF V_ROWS = 0 OR V_STATUS <> 'C' THEN
        RETURN;
    END IF;

    CALL UTIL.POST_LEDGER_ENTRY(V_ACCOUNT_ID, P_AMOUNT, 'FPI', 'FPS from ' || V_REMITTER,
         P_REFERENCE, '1510', NULL, NULL, 'N', V_REMITTER, P_REMITTER_SORT, P_REMITTER_ACCT,
         NULL, NULL, V_TXN_ID, V_BALANCE);

    CALL UTIL.ENQUEUE_NOTIFICATION(V_CUSTOMER_ID, 'PAYMENT_RECEIVED',
         '{"payment":' || RTRIM(CHAR(P_PAYMENT_ID)) || ',"amount":' || VARCHAR(P_AMOUNT) ||
         ',"from":"' || V_REMITTER || '"}');
END@
