-- DO NOT USE - see PAY.TRANSFER_FUNDS.
-- Original internal transfer (2013). Superseded 2019: no GL posting, no holds check, no lock
-- ordering, commits its own work. Returns P_RESULT 0 ok / 1 funds / 2 not found / 3 status / -n SQLCODE.
--
--   14/05/2013  JB   Created for IVR transfers
--   02/09/2014  JB   Overdraft limit included in funds check
--   21/11/2016  RK   GL posting moved to overnight GLFEED01 job (see below)
--   08/04/2019  RK   Replaced by PAY.TRANSFER_FUNDS. Left in case IVR still calls it.
CREATE OR REPLACE PROCEDURE PAY.TRANSFER_FUNDS_V1 (
    IN  P_FROM_ACCOUNT BIGINT,
    IN  P_TO_ACCOUNT   BIGINT,
    IN  P_AMOUNT       DECIMAL(15,2),
    IN  P_REFERENCE    VARCHAR(18),
    OUT P_RESULT       INTEGER,
    OUT P_MESSAGE      VARCHAR(100)
)
    LANGUAGE SQL
    SPECIFIC PAY_TRANSFER_FUNDS_V1
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLCODE INTEGER DEFAULT 0;
    DECLARE V_FROM_BAL    DECIMAL(15,2);
    DECLARE V_FROM_OD     DECIMAL(15,2);
    DECLARE V_FROM_STATUS CHAR(1);
    DECLARE V_TO_BAL      DECIMAL(15,2);
    DECLARE V_TO_STATUS   CHAR(1);
    DECLARE V_BDATE       DATE;
    DECLARE V_CORR        BIGINT;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        SET P_RESULT = SQLCODE;
        SET P_MESSAGE = 'TRANSFER FAILED';
        ROLLBACK;
    END;

    SET P_RESULT = 0;
    SET P_MESSAGE = 'OK';

    IF P_AMOUNT <= 0 THEN
        SET P_RESULT = 3;
        SET P_MESSAGE = 'INVALID AMOUNT';
        RETURN;
    END IF;

    SELECT BUSINESS_DATE INTO V_BDATE FROM REF.BANK_CONTROL WHERE CONTROL_ID = 1;

    SELECT LEDGER_BALANCE, OVERDRAFT_LIMIT, STATUS
      INTO V_FROM_BAL, V_FROM_OD, V_FROM_STATUS
      FROM ACCT.ACCOUNT
     WHERE ACCOUNT_ID = P_FROM_ACCOUNT;
    IF SQLCODE = 100 THEN
        SET P_RESULT = 2;
        SET P_MESSAGE = 'FROM ACCOUNT NOT FOUND';
        RETURN;
    END IF;

    SELECT LEDGER_BALANCE, STATUS
      INTO V_TO_BAL, V_TO_STATUS
      FROM ACCT.ACCOUNT
     WHERE ACCOUNT_ID = P_TO_ACCOUNT;
    IF SQLCODE = 100 THEN
        SET P_RESULT = 2;
        SET P_MESSAGE = 'TO ACCOUNT NOT FOUND';
        RETURN;
    END IF;

    IF V_FROM_STATUS <> 'A' OR V_TO_STATUS = 'C' THEN
        SET P_RESULT = 3;
        SET P_MESSAGE = 'ACCOUNT NOT ACTIVE';
        RETURN;
    END IF;

    -- TODO: holds are not taken into account (JB 2014)
    IF V_FROM_BAL + V_FROM_OD < P_AMOUNT THEN
        SET P_RESULT = 1;
        SET P_MESSAGE = 'INSUFFICIENT FUNDS';
        RETURN;
    END IF;

    UPDATE ACCT.ACCOUNT
       SET LEDGER_BALANCE = LEDGER_BALANCE - P_AMOUNT
     WHERE ACCOUNT_ID = P_FROM_ACCOUNT;

    UPDATE ACCT.ACCOUNT
       SET LEDGER_BALANCE = LEDGER_BALANCE + P_AMOUNT
     WHERE ACCOUNT_ID = P_TO_ACCOUNT;

    SET V_CORR = NEXT VALUE FOR TXN.SEQ_CORRELATION;

    INSERT INTO TXN.POSTED_TXN (ACCOUNT_ID, BUSINESS_DATE, TXN_TYPE, AMOUNT, BALANCE_AFTER,
                                DESCRIPTION, REFERENCE, CORRELATION_ID, CHANNEL)
    VALUES (P_FROM_ACCOUNT, V_BDATE, 'XFR', -P_AMOUNT, V_FROM_BAL - P_AMOUNT,
            'TRANSFER TO ' || RTRIM(CHAR(P_TO_ACCOUNT)), P_REFERENCE, V_CORR, 'IVR'),
           (P_TO_ACCOUNT, V_BDATE, 'XFR', P_AMOUNT, V_TO_BAL + P_AMOUNT,
            'TRANSFER FROM ' || RTRIM(CHAR(P_FROM_ACCOUNT)), P_REFERENCE, V_CORR, 'IVR');

    -- GL now picked up overnight by GLFEED01 (RK 2016)
    /*
    INSERT INTO GL.GL_ENTRY (BUSINESS_DATE, GL_CODE, AMOUNT, CORRELATION_ID, DESCRIPTION)
    VALUES (V_BDATE, '2110',  P_AMOUNT, V_CORR, 'IVR TRANSFER'),
           (V_BDATE, '2110', -P_AMOUNT, V_CORR, 'IVR TRANSFER');
    */

    COMMIT;
END@
