-- Cancels a Direct Debit mandate (customer request or ADDACS from the originator). Called by the app.
-- Cancelling an already cancelled mandate is a no-op. Raises 75012 mandate not found.
CREATE OR REPLACE PROCEDURE PAY.CANCEL_DD_MANDATE (
    IN P_MANDATE_ID BIGINT
)
    LANGUAGE SQL
    SPECIFIC PAY_CANCEL_DD_MANDATE
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);

    DECLARE V_ROWS   INTEGER DEFAULT 0;
    DECLARE V_EXISTS INTEGER DEFAULT 0;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.LOG_ERROR('PAY.CANCEL_DD_MANDATE', V_SQLSTATE, V_SQLCODE, V_MSG,
             'MANDATE_ID=' || COALESCE(RTRIM(CHAR(P_MANDATE_ID)), 'NULL'));
        RESIGNAL;
    END;

    UPDATE PAY.DD_MANDATE
       SET STATUS = 'C',
           CANCELLED_DATE = UTIL.CURRENT_BUSINESS_DATE()
     WHERE MANDATE_ID = P_MANDATE_ID
       AND STATUS = 'A';

    GET DIAGNOSTICS V_ROWS = ROW_COUNT;

    IF V_ROWS = 0 THEN
        SELECT COUNT(*) INTO V_EXISTS FROM PAY.DD_MANDATE WHERE MANDATE_ID = P_MANDATE_ID;
        IF V_EXISTS = 0 THEN
            SIGNAL SQLSTATE '75012' SET MESSAGE_TEXT = 'Direct Debit mandate not found';
        END IF;
        RETURN;
    END IF;

    CALL UTIL.WRITE_AUDIT('PAY.DD_MANDATE', RTRIM(CHAR(P_MANDATE_ID)), 'U', 'STATUS A->C');
END@
