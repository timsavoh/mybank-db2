-- Internal transfer between two MyBank accounts. Called by the app (web, mobile, teller).
-- Both legs share one correlation id against suspense GL 1900; rows are locked in ACCOUNT_ID order.
-- Raises 75001 insufficient funds, 75002/75003 account, 75008 bad amount or same account, 75009 loan account.
CREATE OR REPLACE PROCEDURE PAY.TRANSFER_FUNDS (
    IN  P_FROM_ACCOUNT_ID BIGINT,
    IN  P_TO_ACCOUNT_ID   BIGINT,
    IN  P_AMOUNT          DECIMAL(15,2),
    IN  P_REFERENCE       VARCHAR(18),
    OUT P_CORRELATION_ID  BIGINT,
    OUT P_FROM_BALANCE    DECIMAL(15,2)
)
    LANGUAGE SQL
    SPECIFIC PAY_TRANSFER_FUNDS
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);

    DECLARE V_LOCK_ID    BIGINT;
    DECLARE V_FROM_SORT  CHAR(6);
    DECLARE V_FROM_ACCT  CHAR(8);
    DECLARE V_FROM_NAME  VARCHAR(60);
    DECLARE V_FROM_TYPE  CHAR(3);
    DECLARE V_TO_SORT    CHAR(6);
    DECLARE V_TO_ACCT    CHAR(8);
    DECLARE V_TO_NAME    VARCHAR(60);
    DECLARE V_TO_TYPE    CHAR(3);
    DECLARE V_TXN_ID     BIGINT;
    DECLARE V_TO_BALANCE DECIMAL(15,2);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.LOG_ERROR('PAY.TRANSFER_FUNDS', V_SQLSTATE, V_SQLCODE, V_MSG,
             'FROM=' || COALESCE(RTRIM(CHAR(P_FROM_ACCOUNT_ID)), 'NULL') ||
             ' TO=' || COALESCE(RTRIM(CHAR(P_TO_ACCOUNT_ID)), 'NULL') ||
             ' AMOUNT=' || COALESCE(VARCHAR(P_AMOUNT), 'NULL'));
        RESIGNAL;
    END;

    IF P_AMOUNT IS NULL OR P_AMOUNT <= 0 THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Transfer amount must be greater than zero';
    END IF;

    IF P_FROM_ACCOUNT_ID IS NULL OR P_TO_ACCOUNT_ID IS NULL
       OR P_FROM_ACCOUNT_ID = P_TO_ACCOUNT_ID THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'From and to accounts must be different';
    END IF;

    -- Lock both rows lowest ACCOUNT_ID first. Two opposing transfers between the
    -- same pair of accounts then queue instead of deadlocking (SQL0911N rc 2).
    SELECT ACCOUNT_ID INTO V_LOCK_ID
      FROM ACCT.ACCOUNT
     WHERE ACCOUNT_ID = MIN(P_FROM_ACCOUNT_ID, P_TO_ACCOUNT_ID)
      WITH RS USE AND KEEP UPDATE LOCKS;

    SELECT ACCOUNT_ID INTO V_LOCK_ID
      FROM ACCT.ACCOUNT
     WHERE ACCOUNT_ID = MAX(P_FROM_ACCOUNT_ID, P_TO_ACCOUNT_ID)
      WITH RS USE AND KEEP UPDATE LOCKS;

    CALL UTIL.CHECK_ACCOUNT_STATUS(P_FROM_ACCOUNT_ID, 'Y');
    CALL UTIL.CHECK_ACCOUNT_STATUS(P_TO_ACCOUNT_ID, 'N');

    SELECT A.SORT_CODE, A.ACCOUNT_NO, A.ACCOUNT_NAME, P.PRODUCT_TYPE
      INTO V_FROM_SORT, V_FROM_ACCT, V_FROM_NAME, V_FROM_TYPE
      FROM ACCT.ACCOUNT A
      JOIN REF.PRODUCT P ON P.PRODUCT_CODE = A.PRODUCT_CODE
     WHERE A.ACCOUNT_ID = P_FROM_ACCOUNT_ID;

    SELECT A.SORT_CODE, A.ACCOUNT_NO, A.ACCOUNT_NAME, P.PRODUCT_TYPE
      INTO V_TO_SORT, V_TO_ACCT, V_TO_NAME, V_TO_TYPE
      FROM ACCT.ACCOUNT A
      JOIN REF.PRODUCT P ON P.PRODUCT_CODE = A.PRODUCT_CODE
     WHERE A.ACCOUNT_ID = P_TO_ACCOUNT_ID;

    -- Loan accounts move only through LOAN.ORIGINATE_LOAN / LOAN.MAKE_REPAYMENT
    IF V_FROM_TYPE = 'LON' OR V_TO_TYPE = 'LON' THEN
        SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'Use LOAN.MAKE_REPAYMENT for loan accounts';
    END IF;

    SET P_CORRELATION_ID = NEXT VALUE FOR TXN.SEQ_CORRELATION;

    CALL UTIL.POST_LEDGER_ENTRY(P_FROM_ACCOUNT_ID, -P_AMOUNT, 'XFR',
         'Transfer to ' || V_TO_SORT || ' ' || V_TO_ACCT, P_REFERENCE, '1900',
         P_CORRELATION_ID, NULL, 'N', V_TO_NAME, V_TO_SORT, V_TO_ACCT, NULL, NULL,
         V_TXN_ID, P_FROM_BALANCE);

    CALL UTIL.POST_LEDGER_ENTRY(P_TO_ACCOUNT_ID, P_AMOUNT, 'XFR',
         'Transfer from ' || V_FROM_SORT || ' ' || V_FROM_ACCT, P_REFERENCE, '1900',
         P_CORRELATION_ID, NULL, 'N', V_FROM_NAME, V_FROM_SORT, V_FROM_ACCT, NULL, NULL,
         V_TXN_ID, V_TO_BALANCE);
END@
