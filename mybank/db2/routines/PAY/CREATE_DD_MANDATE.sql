-- Registers a Direct Debit mandate (AUDDIS instruction from an originator). Called by the app / loadgen.
-- First collection is at least 10 calendar days out (advance notice), rolled to a business day.
-- Raises 75002/75003 account, 75007 duplicate mandate, 75008 bad argument, 75009 not a current account.
CREATE OR REPLACE PROCEDURE PAY.CREATE_DD_MANDATE (
    IN  P_ACCOUNT_ID      BIGINT,
    IN  P_ORIGINATOR_ID   CHAR(6),
    IN  P_ORIGINATOR_NAME VARCHAR(60),
    IN  P_MANDATE_REF     VARCHAR(18),
    IN  P_REGULAR_AMOUNT  DECIMAL(15,2),
    IN  P_COLLECTION_DAY  SMALLINT,
    OUT P_MANDATE_ID      BIGINT
)
    LANGUAGE SQL
    SPECIFIC PAY_CREATE_DD_MANDATE
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);

    DECLARE V_PRODUCT_TYPE CHAR(3);
    DECLARE V_CUSTOMER_ID  BIGINT;
    DECLARE V_EXISTING     BIGINT;
    DECLARE V_EARLIEST     DATE;
    DECLARE V_FIRST        DATE;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.LOG_ERROR('PAY.CREATE_DD_MANDATE', V_SQLSTATE, V_SQLCODE, V_MSG,
             'ACCOUNT=' || COALESCE(RTRIM(CHAR(P_ACCOUNT_ID)), 'NULL') ||
             ' SUN=' || COALESCE(P_ORIGINATOR_ID, 'NULL') || ' REF=' || COALESCE(P_MANDATE_REF, 'NULL'));
        RESIGNAL;
    END;

    SET P_MANDATE_ID = NULL;

    IF P_ORIGINATOR_ID IS NULL OR P_ORIGINATOR_NAME IS NULL OR P_MANDATE_REF IS NULL THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Originator id, name and mandate reference required';
    END IF;
    IF P_REGULAR_AMOUNT IS NULL OR P_REGULAR_AMOUNT <= 0 THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Regular amount must be greater than zero';
    END IF;
    IF P_COLLECTION_DAY IS NULL OR P_COLLECTION_DAY NOT BETWEEN 1 AND 28 THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Collection day must be between 1 and 28';
    END IF;

    CALL UTIL.CHECK_ACCOUNT_STATUS(P_ACCOUNT_ID, 'N');

    SELECT P.PRODUCT_TYPE, A.PRIMARY_CUSTOMER_ID
      INTO V_PRODUCT_TYPE, V_CUSTOMER_ID
      FROM ACCT.ACCOUNT A
      JOIN REF.PRODUCT P ON P.PRODUCT_CODE = A.PRODUCT_CODE
     WHERE A.ACCOUNT_ID = P_ACCOUNT_ID;

    IF V_PRODUCT_TYPE <> 'CUR' THEN
        SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'Direct Debits are only accepted on current accounts';
    END IF;

    SELECT MANDATE_ID INTO V_EXISTING
      FROM PAY.DD_MANDATE
     WHERE ACCOUNT_ID = P_ACCOUNT_ID
       AND ORIGINATOR_ID = P_ORIGINATOR_ID
       AND MANDATE_REF = P_MANDATE_REF
       AND STATUS = 'A'
     FETCH FIRST 1 ROW ONLY;

    IF V_EXISTING IS NOT NULL THEN
        SIGNAL SQLSTATE '75007' SET MESSAGE_TEXT = 'An active mandate with this reference exists';
    END IF;

    -- Next occurrence of the collection day at least 10 days out, then off weekends/holidays
    SET V_EARLIEST = UTIL.POSTING_DATE() + 10 DAYS;
    SET V_FIRST = V_EARLIEST - (DAY(V_EARLIEST) - 1) DAYS + (P_COLLECTION_DAY - 1) DAYS;
    IF V_FIRST < V_EARLIEST THEN
        SET V_FIRST = ADD_MONTHS(V_FIRST, 1);
    END IF;
    SET V_FIRST = UTIL.NEXT_BUSINESS_DAY(V_FIRST - 1 DAY);

    SELECT MANDATE_ID INTO P_MANDATE_ID
      FROM FINAL TABLE (INSERT INTO PAY.DD_MANDATE
                            (ACCOUNT_ID, ORIGINATOR_ID, ORIGINATOR_NAME, MANDATE_REF, REGULAR_AMOUNT,
                             COLLECTION_DAY, NEXT_COLLECTION_DATE, STATUS, CREATED_DATE)
                        VALUES (P_ACCOUNT_ID, P_ORIGINATOR_ID, UPPER(P_ORIGINATOR_NAME), P_MANDATE_REF,
                                P_REGULAR_AMOUNT, P_COLLECTION_DAY, V_FIRST, 'A',
                                UTIL.CURRENT_BUSINESS_DATE()));

    CALL UTIL.ENQUEUE_NOTIFICATION(V_CUSTOMER_ID, 'DD_MANDATE_SETUP',
         '{"originator":"' || UPPER(P_ORIGINATOR_NAME) || '","amount":' || VARCHAR(P_REGULAR_AMOUNT) ||
         ',"first":"' || VARCHAR_FORMAT(V_FIRST, 'YYYY-MM-DD') || '"}');
END@
