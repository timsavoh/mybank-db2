-- Cancels a live or suspended standing order. Called by the app (web, mobile, teller).
-- Cancelling one that is already cancelled is a no-op. Raises 75012 not found or already ended.
CREATE OR REPLACE PROCEDURE PAY.CANCEL_STANDING_ORDER (
    IN P_SO_ID BIGINT
)
    LANGUAGE SQL
    SPECIFIC PAY_CANCEL_STANDING_ORDER
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);

    DECLARE V_STATUS CHAR(1);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.LOG_ERROR('PAY.CANCEL_STANDING_ORDER', V_SQLSTATE, V_SQLCODE, V_MSG,
             'SO_ID=' || COALESCE(RTRIM(CHAR(P_SO_ID)), 'NULL'));
        RESIGNAL;
    END;

    SELECT STATUS INTO V_STATUS
      FROM PAY.STANDING_ORDER
     WHERE SO_ID = P_SO_ID
      WITH RS USE AND KEEP UPDATE LOCKS;

    IF V_STATUS IS NULL OR V_STATUS = 'E' THEN
        SIGNAL SQLSTATE '75012' SET MESSAGE_TEXT = 'Standing order not found';
    END IF;

    IF V_STATUS = 'C' THEN
        RETURN;
    END IF;

    UPDATE PAY.STANDING_ORDER
       SET STATUS = 'C'
     WHERE SO_ID = P_SO_ID;

    CALL UTIL.WRITE_AUDIT('PAY.STANDING_ORDER', RTRIM(CHAR(P_SO_ID)), 'U',
         'STATUS ' || V_STATUS || '->C');
END@
