-- Cash withdrawal at an ATM (P_ATM_ID given) or over the counter (P_ATM_ID NULL, P_BRANCH_ID given).
-- ATM: multiples of 10, 500 per business day across ATM withdrawals. Posts CASH against GL 1100.
-- Raises 75001 insufficient funds, 75002/75003 account, 75006 ATM daily limit, 75008 bad amount, 75009.
CREATE OR REPLACE PROCEDURE PAY.WITHDRAW_CASH (
    IN  P_ACCOUNT_ID    BIGINT,
    IN  P_AMOUNT        DECIMAL(15,2),
    IN  P_BRANCH_ID     SMALLINT,
    IN  P_ATM_ID        VARCHAR(8),
    OUT P_TXN_ID        BIGINT,
    OUT P_BALANCE_AFTER DECIMAL(15,2)
)
    LANGUAGE SQL
    SPECIFIC PAY_WITHDRAW_CASH
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);

    DECLARE V_ATM_DAILY_LIMIT DECIMAL(15,2) DEFAULT 500.00;

    DECLARE V_DATE         DATE;
    DECLARE V_PRODUCT_TYPE CHAR(3);
    DECLARE V_AVAILABLE    DECIMAL(15,2);
    DECLARE V_ATM_TODAY    DECIMAL(15,2);
    DECLARE V_DESC         VARCHAR(100);
    DECLARE V_REF          VARCHAR(40);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.LOG_ERROR('PAY.WITHDRAW_CASH', V_SQLSTATE, V_SQLCODE, V_MSG,
             'ACCOUNT=' || COALESCE(RTRIM(CHAR(P_ACCOUNT_ID)), 'NULL') ||
             ' AMOUNT=' || COALESCE(VARCHAR(P_AMOUNT), 'NULL') ||
             ' ATM=' || COALESCE(P_ATM_ID, '-') || ' BRANCH=' || COALESCE(RTRIM(CHAR(P_BRANCH_ID)), '-'));
        RESIGNAL;
    END;

    IF P_AMOUNT IS NULL OR P_AMOUNT <= 0 THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Withdrawal amount must be greater than zero';
    END IF;

    IF P_ATM_ID IS NOT NULL THEN
        IF MOD(INTEGER(P_AMOUNT * 100), 1000) <> 0 THEN
            SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'ATM withdrawals must be a multiple of 10';
        END IF;
        SET V_DESC = 'ATM ' || P_ATM_ID;
        SET V_REF = 'ATM:' || P_ATM_ID;
    ELSE
        SELECT 'Cash withdrawal ' || NAME INTO V_DESC
          FROM REF.BRANCH
         WHERE BRANCH_ID = P_BRANCH_ID
           AND CLOSED_DATE IS NULL
          WITH UR;
        IF V_DESC IS NULL THEN
            SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'Unknown or closed branch';
        END IF;
        SET V_REF = 'BRN:' || RTRIM(CHAR(P_BRANCH_ID));
    END IF;

    CALL UTIL.CHECK_ACCOUNT_STATUS(P_ACCOUNT_ID, 'Y');

    -- Lock first so the available balance cannot move between the check and the posting
    SELECT P.PRODUCT_TYPE, A.LEDGER_BALANCE - A.HOLD_AMOUNT + A.OVERDRAFT_LIMIT
      INTO V_PRODUCT_TYPE, V_AVAILABLE
      FROM ACCT.ACCOUNT A
      JOIN REF.PRODUCT P ON P.PRODUCT_CODE = A.PRODUCT_CODE
     WHERE A.ACCOUNT_ID = P_ACCOUNT_ID
      WITH RS USE AND KEEP UPDATE LOCKS;

    IF V_PRODUCT_TYPE = 'LON' THEN
        SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'Cash cannot be drawn from a loan account';
    END IF;
    IF V_PRODUCT_TYPE = 'SAV' AND P_ATM_ID IS NOT NULL THEN
        SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'Savings accounts have no ATM access';
    END IF;

    IF P_ATM_ID IS NOT NULL THEN
        SET V_DATE = UTIL.POSTING_DATE();
        SELECT COALESCE(-SUM(AMOUNT), 0) INTO V_ATM_TODAY
          FROM TXN.POSTED_TXN
         WHERE ACCOUNT_ID = P_ACCOUNT_ID
           AND BUSINESS_DATE = V_DATE
           AND TXN_TYPE = 'CASH'
           AND AMOUNT < 0
           AND REFERENCE LIKE 'ATM:%';
        IF V_ATM_TODAY + P_AMOUNT > V_ATM_DAILY_LIMIT THEN
            SIGNAL SQLSTATE '75006' SET MESSAGE_TEXT = 'Daily ATM withdrawal limit of 500 exceeded';
        END IF;
    END IF;

    IF V_AVAILABLE < P_AMOUNT THEN
        SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'Insufficient funds';
    END IF;

    CALL UTIL.POST_LEDGER_ENTRY(P_ACCOUNT_ID, -P_AMOUNT, 'CASH', V_DESC, V_REF, '1100',
         NULL, NULL, 'N', NULL, NULL, NULL, NULL, NULL, P_TXN_ID, P_BALANCE_AFTER);
END@
