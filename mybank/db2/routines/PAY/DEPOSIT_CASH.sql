-- Cash paid in over the branch counter. Called by the teller screen.
-- Posts CASH against GL 1100 (branch cash). Raises 75002/75003 account, 75008 bad amount,
-- 75009 unknown branch or loan account.
CREATE OR REPLACE PROCEDURE PAY.DEPOSIT_CASH (
    IN  P_ACCOUNT_ID    BIGINT,
    IN  P_AMOUNT        DECIMAL(15,2),
    IN  P_BRANCH_ID     SMALLINT,
    IN  P_REFERENCE     VARCHAR(40),
    OUT P_TXN_ID        BIGINT,
    OUT P_BALANCE_AFTER DECIMAL(15,2)
)
    LANGUAGE SQL
    SPECIFIC PAY_DEPOSIT_CASH
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);

    DECLARE V_BRANCH_NAME  VARCHAR(60);
    DECLARE V_PRODUCT_TYPE CHAR(3);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.LOG_ERROR('PAY.DEPOSIT_CASH', V_SQLSTATE, V_SQLCODE, V_MSG,
             'ACCOUNT=' || COALESCE(RTRIM(CHAR(P_ACCOUNT_ID)), 'NULL') ||
             ' AMOUNT=' || COALESCE(VARCHAR(P_AMOUNT), 'NULL') ||
             ' BRANCH=' || COALESCE(RTRIM(CHAR(P_BRANCH_ID)), 'NULL'));
        RESIGNAL;
    END;

    IF P_AMOUNT IS NULL OR P_AMOUNT <= 0 THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Deposit amount must be greater than zero';
    END IF;

    SELECT NAME INTO V_BRANCH_NAME
      FROM REF.BRANCH
     WHERE BRANCH_ID = P_BRANCH_ID
       AND CLOSED_DATE IS NULL
      WITH UR;

    IF V_BRANCH_NAME IS NULL THEN
        SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'Unknown or closed branch';
    END IF;

    CALL UTIL.CHECK_ACCOUNT_STATUS(P_ACCOUNT_ID, 'N');

    SELECT P.PRODUCT_TYPE INTO V_PRODUCT_TYPE
      FROM ACCT.ACCOUNT A
      JOIN REF.PRODUCT P ON P.PRODUCT_CODE = A.PRODUCT_CODE
     WHERE A.ACCOUNT_ID = P_ACCOUNT_ID
      WITH UR;

    IF V_PRODUCT_TYPE = 'LON' THEN
        SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'Cash cannot be paid into a loan account';
    END IF;

    CALL UTIL.POST_LEDGER_ENTRY(P_ACCOUNT_ID, P_AMOUNT, 'CASH',
         'Cash deposit ' || V_BRANCH_NAME, P_REFERENCE, '1100', NULL, NULL, 'N',
         NULL, NULL, NULL, NULL, NULL, P_TXN_ID, P_BALANCE_AFTER);
END@
