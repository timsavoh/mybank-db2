-- Cheques discontinued 2021 - kept for reference, not called.
-- Stops a range of unused cheques on an account and charges the stop fee straight to the
-- balance (hard-coded 10.00, no GL). P_STOPPED returns how many cheques were stopped.
CREATE OR REPLACE PROCEDURE CHQ.STOP_CHEQUE (
    IN  P_ACCOUNT_ID  BIGINT,
    IN  P_SERIAL_FROM INTEGER,
    IN  P_SERIAL_TO   INTEGER,
    OUT P_STOPPED     INTEGER
)
    LANGUAGE SQL
    SPECIFIC CHQ_STOP_CHEQUE
    MODIFIES SQL DATA
BEGIN
    DECLARE V_FEE     DECIMAL(15,2) DEFAULT 10.00;
    DECLARE V_BALANCE DECIMAL(15,2);
    DECLARE V_PRODUCT CHAR(6);

    SET P_STOPPED = 0;

    UPDATE CHQ.CHEQUE C
       SET C.STATUS = 'S'
     WHERE C.STATUS = 'U'
       AND C.SERIAL_NO BETWEEN P_SERIAL_FROM AND VALUE(P_SERIAL_TO, P_SERIAL_FROM)
       AND C.BOOK_ID IN (SELECT B.BOOK_ID FROM CHQ.CHEQUE_BOOK B WHERE B.ACCOUNT_ID = P_ACCOUNT_ID);

    GET DIAGNOSTICS P_STOPPED = ROW_COUNT;

    IF P_STOPPED = 0 THEN
        RETURN;
    END IF;

    SELECT PRODUCT_CODE INTO V_PRODUCT FROM ACCT.ACCOUNT WHERE ACCOUNT_ID = P_ACCOUNT_ID;

    -- fee waived for Premier? TODO check with Product (KH)
    -- IF V_PRODUCT = 'CUR002' THEN SET V_FEE = 0; END IF;

    -- one fee per request, not per cheque (complaint 2017)
    UPDATE ACCT.ACCOUNT
       SET LEDGER_BALANCE = LEDGER_BALANCE - V_FEE
     WHERE ACCOUNT_ID = P_ACCOUNT_ID;

    SELECT LEDGER_BALANCE INTO V_BALANCE FROM ACCT.ACCOUNT WHERE ACCOUNT_ID = P_ACCOUNT_ID;

    INSERT INTO TXN.POSTED_TXN (ACCOUNT_ID, BUSINESS_DATE, TXN_TYPE, AMOUNT, BALANCE_AFTER,
                                DESCRIPTION, CORRELATION_ID, CHANNEL)
    VALUES (P_ACCOUNT_ID, (SELECT BUSINESS_DATE FROM REF.BANK_CONTROL WHERE CONTROL_ID = 1),
            'FEE', -V_FEE, V_BALANCE, 'CHEQUE STOP FEE', 0, 'BRN');
END@
