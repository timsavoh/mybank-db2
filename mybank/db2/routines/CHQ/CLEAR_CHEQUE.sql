-- Cheques discontinued 2021 - kept for reference, not called.
-- Clears one presented cheque inside an open CHQ.CLEARING_BATCH: debits the drawer's account
-- directly (no GL - clearing GL was posted from the batch totals), marks the cheque presented.
-- P_RETURN_CODE: '00' paid, 'RD' refer to drawer, 'ST' stopped, 'NF' not found, 'BC' batch closed.
CREATE OR REPLACE PROCEDURE CHQ.CLEAR_CHEQUE (
    IN  P_BATCH_ID    INTEGER,
    IN  P_SORT_CODE   CHAR(6),
    IN  P_ACCOUNT_NO  CHAR(8),
    IN  P_SERIAL_NO   INTEGER,
    IN  P_AMOUNT      DECIMAL(15,2),
    IN  P_PAYEE_NAME  VARCHAR(60),
    OUT P_RETURN_CODE CHAR(2)
)
    LANGUAGE SQL
    SPECIFIC CHQ_CLEAR_CHEQUE
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLCODE INTEGER DEFAULT 0;
    DECLARE V_BATCH_STATUS CHAR(1);
    DECLARE V_BDATE        DATE;
    DECLARE V_ACCOUNT_ID   BIGINT;
    DECLARE V_BALANCE      DECIMAL(15,2);
    DECLARE V_OD_LIMIT     DECIMAL(15,2);
    DECLARE V_BOOK_ID      BIGINT;
    DECLARE V_CHQ_STATUS   CHAR(1);

    SET P_RETURN_CODE = '00';

    SELECT STATUS, BUSINESS_DATE
      INTO V_BATCH_STATUS, V_BDATE
      FROM CHQ.CLEARING_BATCH
     WHERE BATCH_ID = P_BATCH_ID;

    IF SQLCODE = 100 OR V_BATCH_STATUS <> 'O' THEN
        SET P_RETURN_CODE = 'BC';
        RETURN;
    END IF;

    SELECT ACCOUNT_ID, LEDGER_BALANCE, OVERDRAFT_LIMIT
      INTO V_ACCOUNT_ID, V_BALANCE, V_OD_LIMIT
      FROM ACCT.ACCOUNT
     WHERE SORT_CODE = P_SORT_CODE
       AND ACCOUNT_NO = P_ACCOUNT_NO
       AND STATUS = 'A';

    IF SQLCODE = 100 THEN
        SET P_RETURN_CODE = 'NF';
        RETURN;
    END IF;

    SELECT B.BOOK_ID, C.STATUS
      INTO V_BOOK_ID, V_CHQ_STATUS
      FROM CHQ.CHEQUE_BOOK B
      JOIN CHQ.CHEQUE C ON C.BOOK_ID = B.BOOK_ID
     WHERE B.ACCOUNT_ID = V_ACCOUNT_ID
       AND C.SERIAL_NO = P_SERIAL_NO;

    IF SQLCODE = 100 THEN
        SET P_RETURN_CODE = 'NF';
    ELSEIF V_CHQ_STATUS = 'S' THEN
        SET P_RETURN_CODE = 'ST';
    ELSEIF V_CHQ_STATUS <> 'U' THEN
        SET P_RETURN_CODE = 'NF';           -- already presented. TODO: separate code for dup (MB)
    ELSEIF V_BALANCE + V_OD_LIMIT < P_AMOUNT THEN
        SET P_RETURN_CODE = 'RD';
    END IF;

    IF P_RETURN_CODE <> '00' THEN
        UPDATE CHQ.CLEARING_BATCH
           SET RETURNED_COUNT = RETURNED_COUNT + 1
         WHERE BATCH_ID = P_BATCH_ID;
        RETURN;
    END IF;

    UPDATE ACCT.ACCOUNT
       SET LEDGER_BALANCE = LEDGER_BALANCE - P_AMOUNT
     WHERE ACCOUNT_ID = V_ACCOUNT_ID;

    -- TODO correlation id - 0 until the GL feed carries one (MB 2016)
    INSERT INTO TXN.POSTED_TXN (ACCOUNT_ID, BUSINESS_DATE, TXN_TYPE, AMOUNT, BALANCE_AFTER,
                                DESCRIPTION, REFERENCE, COUNTERPARTY_NAME, CORRELATION_ID, CHANNEL)
    VALUES (V_ACCOUNT_ID, V_BDATE, 'CHQ', -P_AMOUNT, V_BALANCE - P_AMOUNT,
            'CHEQUE ' || DIGITS(P_SERIAL_NO), CHAR(P_BATCH_ID), P_PAYEE_NAME, 0, 'SYS');

    UPDATE CHQ.CHEQUE
       SET STATUS = 'P',
           AMOUNT = P_AMOUNT,
           PAYEE_NAME = P_PAYEE_NAME,
           PRESENTED_DATE = V_BDATE
     WHERE BOOK_ID = V_BOOK_ID
       AND SERIAL_NO = P_SERIAL_NO;

    UPDATE CHQ.CLEARING_BATCH
       SET ITEM_COUNT = ITEM_COUNT + 1,
           TOTAL_AMOUNT = TOTAL_AMOUNT + P_AMOUNT
     WHERE BATCH_ID = P_BATCH_ID;
END@
