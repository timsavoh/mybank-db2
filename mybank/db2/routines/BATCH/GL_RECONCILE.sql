-- EOD: ledger invariants as at today's business date. Checks: all GL nets to zero; for each
-- product control GL (2110, 2120, 1310) accounts + GL = 0; suspense 1900 = 0; interest accrual
-- GLs 2210/1210 = rounded sub-ledger. Failures go to GL.RECON_BREAK (the job still succeeds,
-- ops chase breaks). Also writes GL.GL_DAILY_BALANCE for today. Re-run replaces today's rows.
CREATE OR REPLACE PROCEDURE BATCH.GL_RECONCILE (OUT P_ROWS_PROCESSED INTEGER)
    LANGUAGE SQL
    SPECIFIC BATCH_GL_RECONCILE
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);
    DECLARE V_RUN_ID   BIGINT;
    DECLARE V_ROWS     INTEGER DEFAULT 0;
    DECLARE V_BREAKS   INTEGER DEFAULT 0;
    DECLARE V_GL_ROWS  INTEGER DEFAULT 0;
    DECLARE V_TODAY    DATE;
    DECLARE V_BREAK_LIST VARCHAR(500) DEFAULT '';

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.END_JOB_RUN(V_RUN_ID, 'F', V_ROWS, V_MSG);
        CALL UTIL.LOG_ERROR('BATCH.GL_RECONCILE', V_SQLSTATE, V_SQLCODE, V_MSG, NULL);
        RESIGNAL;
    END;

    CALL UTIL.START_JOB_RUN('GL_RECONCILE', V_RUN_ID);
    SET V_TODAY = UTIL.CURRENT_BUSINESS_DATE();

    DECLARE GLOBAL TEMPORARY TABLE SESSION.RECON_CHECK (
        CHECK_NAME VARCHAR(40)   NOT NULL,
        EXPECTED   DECIMAL(17,2) NOT NULL,
        ACTUAL     DECIMAL(17,2) NOT NULL
    ) WITH REPLACE ON COMMIT PRESERVE ROWS NOT LOGGED;

    -- As at today: GL rows dated <= today; account balances less anything value-dated later
    -- (after EOD cut-off, online activity is already posting to tomorrow)
    INSERT INTO SESSION.RECON_CHECK (CHECK_NAME, EXPECTED, ACTUAL)
    SELECT 'GL_NETS_TO_ZERO', 0, COALESCE(SUM(E.AMOUNT), 0)
      FROM GL.GL_ENTRY E
     WHERE E.BUSINESS_DATE <= V_TODAY
    UNION ALL
    SELECT 'CONTROL_' || C.CONTROL_GL_CODE,
           -COALESCE(B.ACCOUNT_TOTAL, 0),
           COALESCE((SELECT SUM(E.AMOUNT)
                       FROM GL.GL_ENTRY E
                      WHERE E.GL_CODE = C.CONTROL_GL_CODE
                        AND E.BUSINESS_DATE <= V_TODAY), 0)
      FROM (SELECT DISTINCT CONTROL_GL_CODE FROM REF.PRODUCT) C
      LEFT OUTER JOIN (SELECT P.CONTROL_GL_CODE,
                              SUM(A.LEDGER_BALANCE - COALESCE(F.FUTURE_AMOUNT, 0)) AS ACCOUNT_TOTAL
                         FROM ACCT.ACCOUNT A
                         JOIN REF.PRODUCT P
                           ON P.PRODUCT_CODE = A.PRODUCT_CODE
                         LEFT OUTER JOIN (SELECT T.ACCOUNT_ID, SUM(T.AMOUNT) AS FUTURE_AMOUNT
                                            FROM TXN.POSTED_TXN T
                                           WHERE T.BUSINESS_DATE > V_TODAY
                                           GROUP BY T.ACCOUNT_ID) F
                           ON F.ACCOUNT_ID = A.ACCOUNT_ID
                        GROUP BY P.CONTROL_GL_CODE) B
        ON B.CONTROL_GL_CODE = C.CONTROL_GL_CODE
    UNION ALL
    SELECT 'SUSPENSE_1900', 0, COALESCE(SUM(E.AMOUNT), 0)
      FROM GL.GL_ENTRY E
     WHERE E.GL_CODE = '1900'
       AND E.BUSINESS_DATE <= V_TODAY
    UNION ALL
    SELECT 'ACCRUAL_' || X.GL_CODE, X.EXPECTED,
           COALESCE((SELECT SUM(E.AMOUNT) FROM GL.GL_ENTRY E WHERE E.GL_CODE = X.GL_CODE), 0)
      FROM (SELECT '2210' AS GL_CODE,
                   -ROUND(COALESCE(SUM(CASE WHEN A.ACCRUED_INTEREST > 0 THEN A.ACCRUED_INTEREST END), 0), 2) AS EXPECTED
              FROM ACCT.ACCOUNT A
              JOIN REF.PRODUCT P ON P.PRODUCT_CODE = A.PRODUCT_CODE AND P.PRODUCT_TYPE <> 'LON'
            UNION ALL
            SELECT '1210',
                   -ROUND(COALESCE(SUM(CASE WHEN A.ACCRUED_INTEREST < 0 THEN A.ACCRUED_INTEREST END), 0), 2)
              FROM ACCT.ACCOUNT A
              JOIN REF.PRODUCT P ON P.PRODUCT_CODE = A.PRODUCT_CODE AND P.PRODUCT_TYPE <> 'LON') X;
    GET DIAGNOSTICS V_ROWS = ROW_COUNT;

    DELETE FROM GL.RECON_BREAK
     WHERE BUSINESS_DATE = V_TODAY;

    INSERT INTO GL.RECON_BREAK (BUSINESS_DATE, CHECK_NAME, EXPECTED, ACTUAL)
    SELECT V_TODAY, CHECK_NAME, EXPECTED, ACTUAL
      FROM SESSION.RECON_CHECK
     WHERE EXPECTED <> ACTUAL;
    GET DIAGNOSTICS V_BREAKS = ROW_COUNT;

    IF V_BREAKS > 0 THEN
        FOR B AS C_BREAKS CURSOR FOR
            SELECT CHECK_NAME, EXPECTED, ACTUAL FROM SESSION.RECON_CHECK WHERE EXPECTED <> ACTUAL
        DO
            SET V_BREAK_LIST = SUBSTR(V_BREAK_LIST || ' ' || RTRIM(B.CHECK_NAME) || ' expected '
                                      || VARCHAR(B.EXPECTED) || ' actual ' || VARCHAR(B.ACTUAL) || ';', 1, 400);
        END FOR;
    END IF;

    -- Closing GL balances for today (MONTH_END_GL_CLOSE adds the parent codes at month-end)
    MERGE INTO GL.GL_DAILY_BALANCE D
    USING (SELECT G.GL_CODE, COALESCE(SUM(E.AMOUNT), 0) AS BALANCE
             FROM REF.GL_ACCOUNT G
             LEFT OUTER JOIN GL.GL_ENTRY E
               ON E.GL_CODE = G.GL_CODE
              AND E.BUSINESS_DATE <= V_TODAY
            WHERE G.POSTABLE = 'Y'
            GROUP BY G.GL_CODE) B
       ON D.GL_CODE = B.GL_CODE
      AND D.BUSINESS_DATE = V_TODAY
     WHEN MATCHED THEN
          UPDATE SET D.BALANCE = B.BALANCE
     WHEN NOT MATCHED THEN
          INSERT (GL_CODE, BUSINESS_DATE, BALANCE) VALUES (B.GL_CODE, V_TODAY, B.BALANCE);
    GET DIAGNOSTICS V_GL_ROWS = ROW_COUNT;

    COMMIT;

    SET P_ROWS_PROCESSED = V_ROWS;
    CALL UTIL.END_JOB_RUN(V_RUN_ID, 'S', V_ROWS,
         RTRIM(CHAR(V_ROWS)) || ' checks, ' || RTRIM(CHAR(V_BREAKS)) || ' breaks'
         || CASE WHEN V_BREAKS > 0 THEN ':' || V_BREAK_LIST ELSE '' END
         || '; ' || RTRIM(CHAR(V_GL_ROWS)) || ' GL balances for ' || CHAR(V_TODAY, ISO));
END@
