-- Db2 admin task (SYSPROC.ADMIN_TASK_ADD, hourly; see db2/tasks/admin_tasks.sql): purges
-- OPS.AUDIT_LOG and OPS.ERROR_LOG rows older than the retention period, converted to wall-clock
-- time (RETENTION_BUSINESS_DAYS x MINUTES_PER_BUSINESS_DAY minutes). No parameters (ATS).
CREATE OR REPLACE PROCEDURE BATCH.PURGE_AUDIT_LOG ()
    LANGUAGE SQL
    SPECIFIC BATCH_PURGE_AUDIT_LOG
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);
    DECLARE V_RUN_ID   BIGINT;
    DECLARE V_ROWS     INTEGER DEFAULT 0;
    DECLARE V_COUNT    INTEGER;
    DECLARE V_AUDIT    INTEGER DEFAULT 0;
    DECLARE V_ERRORS   INTEGER DEFAULT 0;
    DECLARE V_KEEP_TS  TIMESTAMP;
    DECLARE V_CHUNK    INTEGER DEFAULT 5000;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.END_JOB_RUN(V_RUN_ID, 'F', V_ROWS, V_MSG);
        CALL UTIL.LOG_ERROR('BATCH.PURGE_AUDIT_LOG', V_SQLSTATE, V_SQLCODE, V_MSG, NULL);
        RESIGNAL;
    END;

    CALL UTIL.START_JOB_RUN('PURGE_AUDIT_LOG', V_RUN_ID);

    SELECT CURRENT TIMESTAMP - (RETENTION_BUSINESS_DAYS * MINUTES_PER_BUSINESS_DAY) MINUTES
      INTO V_KEEP_TS
      FROM REF.BANK_CONTROL
     WHERE CONTROL_ID = 1;

    AUDIT_LOOP:
    LOOP
        DELETE FROM (SELECT 1
                       FROM OPS.AUDIT_LOG
                      WHERE CHANGED_TS < V_KEEP_TS
                      FETCH FIRST 5000 ROWS ONLY);
        GET DIAGNOSTICS V_COUNT = ROW_COUNT;
        COMMIT;
        SET V_AUDIT = V_AUDIT + V_COUNT;
        IF V_COUNT < V_CHUNK THEN
            LEAVE AUDIT_LOOP;
        END IF;
    END LOOP AUDIT_LOOP;

    ERROR_LOOP:
    LOOP
        DELETE FROM (SELECT 1
                       FROM OPS.ERROR_LOG
                      WHERE LOGGED_TS < V_KEEP_TS
                      FETCH FIRST 5000 ROWS ONLY);
        GET DIAGNOSTICS V_COUNT = ROW_COUNT;
        COMMIT;
        SET V_ERRORS = V_ERRORS + V_COUNT;
        IF V_COUNT < V_CHUNK THEN
            LEAVE ERROR_LOOP;
        END IF;
    END LOOP ERROR_LOOP;

    SET V_ROWS = V_AUDIT + V_ERRORS;
    CALL UTIL.END_JOB_RUN(V_RUN_ID, 'S', V_ROWS,
         RTRIM(CHAR(V_AUDIT)) || ' audit rows, ' || RTRIM(CHAR(V_ERRORS)) || ' error rows older than '
         || VARCHAR_FORMAT(V_KEEP_TS, 'YYYY-MM-DD HH24:MI:SS') || ' purged');
END@
