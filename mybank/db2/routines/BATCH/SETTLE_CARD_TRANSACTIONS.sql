-- EOD: settles approved card authorisations up to today's business date. Per auth: settle the
-- hold (ACCOUNT_HOLD 'S'), post the CARD debit (contra 1520, bank-initiated so may overdraw),
-- then MERGE the settled auths back to CARD.AUTHORISATION ('S' + SETTLED_TXN_ID) each commit.
CREATE OR REPLACE PROCEDURE BATCH.SETTLE_CARD_TRANSACTIONS (OUT P_ROWS_PROCESSED INTEGER)
    LANGUAGE SQL
    SPECIFIC BATCH_SETTLE_CARD_TRANSACTIONS
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);
    DECLARE V_RUN_ID   BIGINT;
    DECLARE V_ROWS     INTEGER DEFAULT 0;
    DECLARE V_SETTLED  INTEGER DEFAULT 0;
    DECLARE V_FAILED   INTEGER DEFAULT 0;
    DECLARE V_SKIPPED  INTEGER DEFAULT 0;
    DECLARE V_TOTAL    DECIMAL(17,2) DEFAULT 0;
    DECLARE V_EOF      SMALLINT DEFAULT 0;
    DECLARE V_TODAY    DATE;
    DECLARE V_COMMIT_EVERY INTEGER DEFAULT 500;

    DECLARE V_AUTH_ID      BIGINT;
    DECLARE V_ACCOUNT_ID   BIGINT;
    DECLARE V_AMOUNT       DECIMAL(15,2);
    DECLARE V_HOLD_ID      BIGINT;
    DECLARE V_EXTERNAL_REF VARCHAR(40);
    DECLARE V_MERCHANT_ID  INTEGER;
    DECLARE V_MERCHANT     VARCHAR(60);
    DECLARE V_MCC          CHAR(4);
    DECLARE V_TOWN         VARCHAR(40);
    DECLARE V_AUTH_STATUS  CHAR(1);
    DECLARE V_DESCRIPTION  VARCHAR(100);
    DECLARE V_TXN_ID       BIGINT;
    DECLARE V_BALANCE      DECIMAL(15,2);
    DECLARE V_ROW_STATE    CHAR(5);
    DECLARE V_ROW_CODE     INTEGER;
    DECLARE V_ROW_MSG      VARCHAR(1000);
    DECLARE V_ROW_SKIP     SMALLINT;

    DECLARE C_AUTHS CURSOR WITH HOLD FOR
        SELECT A.AUTH_ID, A.ACCOUNT_ID, A.AMOUNT, A.HOLD_ID, A.EXTERNAL_REF, A.MERCHANT_ID,
               COALESCE(M.NAME, 'MERCHANT ' || RTRIM(CHAR(A.MERCHANT_ID))), M.MCC, M.TOWN
          FROM CARD.AUTHORISATION A
          LEFT OUTER JOIN CARD.MERCHANT M
            ON M.MERCHANT_ID = A.MERCHANT_ID
         WHERE A.STATUS = 'A'
           AND A.BUSINESS_DATE <= V_TODAY
         ORDER BY A.AUTH_ID
          WITH CS;

    DECLARE CONTINUE HANDLER FOR NOT FOUND SET V_EOF = 1;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.END_JOB_RUN(V_RUN_ID, 'F', V_ROWS, V_MSG);
        CALL UTIL.LOG_ERROR('BATCH.SETTLE_CARD_TRANSACTIONS', V_SQLSTATE, V_SQLCODE, V_MSG,
                            'AUTH_ID=' || COALESCE(RTRIM(CHAR(V_AUTH_ID)), '-'));
        RESIGNAL;
    END;

    CALL UTIL.START_JOB_RUN('SETTLE_CARD_TRANSACTIONS', V_RUN_ID);
    SET V_TODAY = UTIL.CURRENT_BUSINESS_DATE();

    -- Settled auths for the current commit interval; emptied by each COMMIT
    DECLARE GLOBAL TEMPORARY TABLE SESSION.CARD_SETTLED (
        AUTH_ID BIGINT NOT NULL,
        TXN_ID  BIGINT NOT NULL
    ) WITH REPLACE ON COMMIT DELETE ROWS LOGGED;

    OPEN C_AUTHS;
    AUTH_LOOP:
    LOOP
        SET V_EOF = 0;
        FETCH C_AUTHS INTO V_AUTH_ID, V_ACCOUNT_ID, V_AMOUNT, V_HOLD_ID, V_EXTERNAL_REF,
                           V_MERCHANT_ID, V_MERCHANT, V_MCC, V_TOWN;
        IF V_EOF = 1 THEN
            LEAVE AUTH_LOOP;
        END IF;

        SET V_ROW_STATE = '00000';
        SET V_ROW_SKIP = 0;
        SAVEPOINT SP_AUTH ON ROLLBACK RETAIN CURSORS;

        ROW_BLOCK:
        BEGIN
            DECLARE EXIT HANDLER FOR SQLEXCEPTION
            BEGIN
                GET DIAGNOSTICS EXCEPTION 1 V_ROW_MSG = MESSAGE_TEXT;
                VALUES (SQLSTATE, SQLCODE) INTO V_ROW_STATE, V_ROW_CODE;
            END;

            -- Lock the auth so a reversal cannot slip in between here and the MERGE
            SET V_AUTH_STATUS = NULL;
            SELECT STATUS
              INTO V_AUTH_STATUS
              FROM CARD.AUTHORISATION
             WHERE AUTH_ID = V_AUTH_ID
              WITH RS USE AND KEEP UPDATE LOCKS;
            IF COALESCE(V_AUTH_STATUS, ' ') <> 'A' THEN
                SET V_ROW_SKIP = 1;
                LEAVE ROW_BLOCK;
            END IF;

            IF V_HOLD_ID IS NOT NULL THEN
                UPDATE ACCT.ACCOUNT_HOLD
                   SET STATUS = 'S',
                       RELEASED_TS = CURRENT TIMESTAMP
                 WHERE HOLD_ID = V_HOLD_ID
                   AND STATUS = 'A';
            END IF;

            SET V_DESCRIPTION = SUBSTR('CARD ' || V_MERCHANT || COALESCE(' ' || V_TOWN, ''), 1, 100);

            CALL UTIL.POST_LEDGER_ENTRY(V_ACCOUNT_ID, -V_AMOUNT, 'CARD', V_DESCRIPTION, V_EXTERNAL_REF,
                                        '1520', NULL, V_TODAY, 'Y',
                                        V_MERCHANT, NULL, NULL, V_MERCHANT_ID, V_MCC,
                                        V_TXN_ID, V_BALANCE);

            INSERT INTO SESSION.CARD_SETTLED (AUTH_ID, TXN_ID) VALUES (V_AUTH_ID, V_TXN_ID);
        END ROW_BLOCK;

        IF V_ROW_STATE <> '00000' THEN
            -- e.g. account closed or frozen: leave the auth open, the hold will expire it
            ROLLBACK TO SAVEPOINT SP_AUTH;
            CALL UTIL.LOG_ERROR('BATCH.SETTLE_CARD_TRANSACTIONS', V_ROW_STATE, V_ROW_CODE, V_ROW_MSG,
                                'AUTH_ID=' || RTRIM(CHAR(V_AUTH_ID)));
            SET V_FAILED = V_FAILED + 1;
        ELSEIF V_ROW_SKIP = 1 THEN
            RELEASE SAVEPOINT SP_AUTH;
            SET V_SKIPPED = V_SKIPPED + 1;
        ELSE
            RELEASE SAVEPOINT SP_AUTH;
            SET V_SETTLED = V_SETTLED + 1;
            SET V_TOTAL = V_TOTAL + V_AMOUNT;
        END IF;

        SET V_ROWS = V_ROWS + 1;
        IF MOD(V_ROWS, V_COMMIT_EVERY) = 0 THEN
            MERGE INTO CARD.AUTHORISATION A
            USING SESSION.CARD_SETTLED S
               ON A.AUTH_ID = S.AUTH_ID
             WHEN MATCHED AND A.STATUS = 'A' THEN
                  UPDATE SET A.STATUS = 'S',
                             A.SETTLED_TXN_ID = S.TXN_ID;
            COMMIT;
        END IF;
    END LOOP AUTH_LOOP;
    CLOSE C_AUTHS;

    MERGE INTO CARD.AUTHORISATION A
    USING SESSION.CARD_SETTLED S
       ON A.AUTH_ID = S.AUTH_ID
     WHEN MATCHED AND A.STATUS = 'A' THEN
          UPDATE SET A.STATUS = 'S',
                     A.SETTLED_TXN_ID = S.TXN_ID;
    COMMIT;

    SET P_ROWS_PROCESSED = V_SETTLED;
    CALL UTIL.END_JOB_RUN(V_RUN_ID, 'S', V_SETTLED,
         RTRIM(CHAR(V_SETTLED)) || ' auths settled for ' || VARCHAR(V_TOTAL) || ', '
         || RTRIM(CHAR(V_FAILED)) || ' failed, ' || RTRIM(CHAR(V_SKIPPED)) || ' skipped');
END@
