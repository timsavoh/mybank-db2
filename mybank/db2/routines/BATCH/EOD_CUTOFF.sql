-- EOD step 1: cuts off the business day (DAY_STATUS 'O' -> 'C'). From here on online
-- postings are value-dated to the next business day by UTIL.POSTING_DATE().
-- Scheduler, EOD chain. Re-running on a day already cut off is a no-op.
CREATE OR REPLACE PROCEDURE BATCH.EOD_CUTOFF (OUT P_ROWS_PROCESSED INTEGER)
    LANGUAGE SQL
    SPECIFIC BATCH_EOD_CUTOFF
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);
    DECLARE V_RUN_ID   BIGINT;
    DECLARE V_ROWS     INTEGER DEFAULT 0;
    DECLARE V_TODAY    DATE;
    DECLARE V_STATUS   CHAR(1);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.END_JOB_RUN(V_RUN_ID, 'F', V_ROWS, V_MSG);
        CALL UTIL.LOG_ERROR('BATCH.EOD_CUTOFF', V_SQLSTATE, V_SQLCODE, V_MSG, NULL);
        RESIGNAL;
    END;

    CALL UTIL.START_JOB_RUN('EOD_CUTOFF', V_RUN_ID);

    SELECT BUSINESS_DATE, DAY_STATUS
      INTO V_TODAY, V_STATUS
      FROM REF.BANK_CONTROL
     WHERE CONTROL_ID = 1
      WITH RS USE AND KEEP UPDATE LOCKS;

    IF V_STATUS = 'C' THEN
        COMMIT;
        SET P_ROWS_PROCESSED = 0;
        CALL UTIL.END_JOB_RUN(V_RUN_ID, 'S', 0, 'Business date ' || CHAR(V_TODAY, ISO) || ' already cut off');
        RETURN;
    END IF;

    UPDATE REF.BANK_CONTROL
       SET DAY_STATUS = 'C'
     WHERE CONTROL_ID = 1;
    GET DIAGNOSTICS V_ROWS = ROW_COUNT;

    -- Commit straight away: every online posting reads BANK_CONTROL
    COMMIT;

    SET P_ROWS_PROCESSED = V_ROWS;
    CALL UTIL.END_JOB_RUN(V_RUN_ID, 'S', V_ROWS,
         'Cut-off for ' || CHAR(V_TODAY, ISO) || '; online now value-dated '
         || CHAR(UTIL.NEXT_BUSINESS_DAY(V_TODAY), ISO));
END@
