-- EOD final step: moves the bank to the next business day and reopens it.
-- Scheduler, last step of the EOD chain. Raises 75015 if EOD_CUTOFF has not run
-- (which also stops an accidental re-run from rolling the date twice).
CREATE OR REPLACE PROCEDURE BATCH.ROLL_BUSINESS_DATE (OUT P_ROWS_PROCESSED INTEGER)
    LANGUAGE SQL
    SPECIFIC BATCH_ROLL_BUSINESS_DATE
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);
    DECLARE V_RUN_ID   BIGINT;
    DECLARE V_ROWS     INTEGER DEFAULT 0;
    DECLARE V_TODAY    DATE;
    DECLARE V_NEXT     DATE;
    DECLARE V_STATUS   CHAR(1);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.END_JOB_RUN(V_RUN_ID, 'F', V_ROWS, V_MSG);
        CALL UTIL.LOG_ERROR('BATCH.ROLL_BUSINESS_DATE', V_SQLSTATE, V_SQLCODE, V_MSG, NULL);
        RESIGNAL;
    END;

    CALL UTIL.START_JOB_RUN('ROLL_BUSINESS_DATE', V_RUN_ID);

    SELECT BUSINESS_DATE, DAY_STATUS
      INTO V_TODAY, V_STATUS
      FROM REF.BANK_CONTROL
     WHERE CONTROL_ID = 1
      WITH RS USE AND KEEP UPDATE LOCKS;

    IF V_STATUS <> 'C' THEN
        SIGNAL SQLSTATE '75015' SET MESSAGE_TEXT = 'Business day is open: EOD_CUTOFF has not run';
    END IF;

    SET V_NEXT = UTIL.NEXT_BUSINESS_DAY(V_TODAY);

    UPDATE REF.BANK_CONTROL
       SET PREV_BUSINESS_DATE = BUSINESS_DATE,
           BUSINESS_DATE      = V_NEXT,
           DAY_STATUS         = 'O',
           DAY_OPENED_TS      = CURRENT TIMESTAMP,
           LAST_EOD_TS        = CURRENT TIMESTAMP,
           FORCE_MONTH_END    = 'N'
     WHERE CONTROL_ID = 1;
    GET DIAGNOSTICS V_ROWS = ROW_COUNT;

    COMMIT;

    SET P_ROWS_PROCESSED = V_ROWS;
    CALL UTIL.END_JOB_RUN(V_RUN_ID, 'S', V_ROWS,
         'Rolled ' || CHAR(V_TODAY, ISO) || ' -> ' || CHAR(V_NEXT, ISO) || ' ('
         || RTRIM(CHAR(DAYS(V_NEXT) - DAYS(V_TODAY))) || ' calendar days)');
END@
