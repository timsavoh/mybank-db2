-- Savings interest accrual on the pre-2019 banded rate model (REF.INTEREST_RATE_2019). On the
-- last day of the month it also capitalises by updating LEDGER_BALANCE directly (no GL pair).
--
--   30/01/2016  DM   Created from ACCRINT (COBOL) spec
--   14/07/2017  DM   Commit every 1000 rows; month-end capitalisation added
--   01/05/2019  SG   Switched off - new rate model, see BATCH.ACCRUE_INTEREST
CREATE OR REPLACE PROCEDURE BATCH.ACCRUE_INTEREST_2019 (
    IN  P_RUN_DATE DATE,
    OUT P_ROWS     INTEGER
)
    LANGUAGE SQL
    SPECIFIC BATCH_ACCRUE_INTEREST_2019
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLCODE INTEGER DEFAULT 0;
    DECLARE AT_END      SMALLINT DEFAULT 0;
    DECLARE V_ACCOUNT_ID BIGINT;
    DECLARE V_BALANCE    DECIMAL(15,2);
    DECLARE V_LAST_DATE  DATE;
    DECLARE V_RATE       DECIMAL(7,4);
    DECLARE V_DAYS       INTEGER;
    DECLARE V_INTEREST   DECIMAL(15,6);
    DECLARE V_CAP        DECIMAL(15,2);
    DECLARE V_RUN_DATE   DATE;
    DECLARE V_COUNT      INTEGER DEFAULT 0;

    DECLARE C_ACCOUNTS CURSOR WITH HOLD FOR
        SELECT A.ACCOUNT_ID, A.LEDGER_BALANCE, A.LAST_ACCRUAL_DATE, R.GROSS_RATE
          FROM ACCT.ACCOUNT A,
               REF.INTEREST_RATE_2019 R
         WHERE R.PRODUCT_CODE = A.PRODUCT_CODE
           AND A.LEDGER_BALANCE >= R.BAND_FROM
           AND (R.BAND_TO IS NULL OR A.LEDGER_BALANCE < R.BAND_TO)
           AND A.STATUS IN ('A', 'D')
           AND A.PRODUCT_CODE LIKE 'SAV%'
           AND VALUE(A.LAST_ACCRUAL_DATE, '1900-01-01') < V_RUN_DATE
         ORDER BY A.ACCOUNT_ID;

    DECLARE CONTINUE HANDLER FOR NOT FOUND SET AT_END = 1;

    SET P_ROWS = 0;
    SET V_RUN_DATE = VALUE(P_RUN_DATE, CURRENT DATE);

    OPEN C_ACCOUNTS;
    FETCH C_ACCOUNTS INTO V_ACCOUNT_ID, V_BALANCE, V_LAST_DATE, V_RATE;

    WHILE AT_END = 0 DO
        SET V_DAYS = DAYS(V_RUN_DATE) - DAYS(VALUE(V_LAST_DATE, V_RUN_DATE - 1 DAY));
        -- TODO: 366 in leap years (DM)
        SET V_INTEREST = V_BALANCE * V_RATE / 100 / 365 * V_DAYS;

        UPDATE ACCT.ACCOUNT
           SET ACCRUED_INTEREST  = ACCRUED_INTEREST + V_INTEREST,
               LAST_ACCRUAL_DATE = V_RUN_DATE
         WHERE ACCOUNT_ID = V_ACCOUNT_ID;

        INSERT INTO ACCT.INTEREST_ACCRUAL (ACCOUNT_ID, BUSINESS_DATE, DAYS, BALANCE, ANNUAL_RATE, AMOUNT)
        VALUES (V_ACCOUNT_ID, V_RUN_DATE, V_DAYS, V_BALANCE, V_RATE, V_INTEREST);

        SET V_COUNT = V_COUNT + 1;
        SET P_ROWS = P_ROWS + 1;
        IF V_COUNT >= 1000 THEN
            COMMIT;
            SET V_COUNT = 0;
        END IF;

        FETCH C_ACCOUNTS INTO V_ACCOUNT_ID, V_BALANCE, V_LAST_DATE, V_RATE;
    END WHILE;

    CLOSE C_ACCOUNTS;

    -- month end: capitalise. Straight onto the balance - finance post the GL journal by hand
    IF V_RUN_DATE = LAST_DAY(V_RUN_DATE) THEN
        INSERT INTO TXN.POSTED_TXN (ACCOUNT_ID, BUSINESS_DATE, TXN_TYPE, AMOUNT, BALANCE_AFTER,
                                    DESCRIPTION, CORRELATION_ID, CHANNEL)
        SELECT A.ACCOUNT_ID, V_RUN_DATE, 'INT', ROUND(A.ACCRUED_INTEREST, 2),
               A.LEDGER_BALANCE + ROUND(A.ACCRUED_INTEREST, 2),
               'INTEREST ' || VARCHAR_FORMAT(V_RUN_DATE, 'MON YYYY'), 0, 'SYS'
          FROM ACCT.ACCOUNT A
         WHERE A.PRODUCT_CODE LIKE 'SAV%'
           AND ROUND(A.ACCRUED_INTEREST, 2) > 0;

        UPDATE ACCT.ACCOUNT
           SET LEDGER_BALANCE   = LEDGER_BALANCE + ROUND(ACCRUED_INTEREST, 2),
               ACCRUED_INTEREST = ACCRUED_INTEREST - ROUND(ACCRUED_INTEREST, 2)
         WHERE PRODUCT_CODE LIKE 'SAV%'
           AND ROUND(ACCRUED_INTEREST, 2) > 0;

        -- SG: old tax deduction at source, gone since April 2016
        -- UPDATE ACCT.ACCOUNT SET LEDGER_BALANCE = LEDGER_BALANCE - ROUND(V_CAP * 0.20, 2) ...
    END IF;

    COMMIT;
END@
