-- EOD: end-of-day balance snapshot of every open account into ACCT.DAILY_BALANCE, as at today's
-- business date (postings already value-dated to tomorrow are backed out). Delete-and-reload
-- for the date, so re-running is safe.
CREATE OR REPLACE PROCEDURE BATCH.SNAPSHOT_DAILY_BALANCES (OUT P_ROWS_PROCESSED INTEGER)
    LANGUAGE SQL
    SPECIFIC BATCH_SNAPSHOT_DAILY_BALANCES
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);
    DECLARE V_RUN_ID   BIGINT;
    DECLARE V_ROWS     INTEGER DEFAULT 0;
    DECLARE V_TODAY    DATE;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.END_JOB_RUN(V_RUN_ID, 'F', V_ROWS, V_MSG);
        CALL UTIL.LOG_ERROR('BATCH.SNAPSHOT_DAILY_BALANCES', V_SQLSTATE, V_SQLCODE, V_MSG, NULL);
        RESIGNAL;
    END;

    CALL UTIL.START_JOB_RUN('SNAPSHOT_DAILY_BALANCES', V_RUN_ID);
    SET V_TODAY = UTIL.CURRENT_BUSINESS_DATE();

    DELETE FROM ACCT.DAILY_BALANCE
     WHERE BUSINESS_DATE = V_TODAY;

    INSERT INTO ACCT.DAILY_BALANCE (ACCOUNT_ID, BUSINESS_DATE, LEDGER_BALANCE, AVAILABLE_BALANCE)
    SELECT A.ACCOUNT_ID,
           V_TODAY,
           A.LEDGER_BALANCE - COALESCE(F.FUTURE_AMOUNT, 0),
           A.LEDGER_BALANCE - COALESCE(F.FUTURE_AMOUNT, 0) - A.HOLD_AMOUNT + A.OVERDRAFT_LIMIT
      FROM ACCT.ACCOUNT A
      LEFT OUTER JOIN (SELECT T.ACCOUNT_ID, SUM(T.AMOUNT) AS FUTURE_AMOUNT
                         FROM TXN.POSTED_TXN T
                        WHERE T.BUSINESS_DATE > V_TODAY
                        GROUP BY T.ACCOUNT_ID) F
        ON F.ACCOUNT_ID = A.ACCOUNT_ID
     WHERE A.STATUS <> 'C';
    GET DIAGNOSTICS V_ROWS = ROW_COUNT;

    COMMIT;

    SET P_ROWS_PROCESSED = V_ROWS;
    CALL UTIL.END_JOB_RUN(V_RUN_ID, 'S', V_ROWS,
         RTRIM(CHAR(V_ROWS)) || ' balances snapshotted for ' || CHAR(V_TODAY, ISO));
END@
