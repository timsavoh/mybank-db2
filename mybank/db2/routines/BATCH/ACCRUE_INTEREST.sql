-- EOD: accrues a day's (or since the last accrual, so Monday covers the weekend) interest on
-- every open non-loan account into ACCT.INTEREST_ACCRUAL and ACCOUNT.ACCRUED_INTEREST (6dp;
-- positive = owed to the customer, negative = owed by them), then trues up the 2dp GL (2210/1210).
CREATE OR REPLACE PROCEDURE BATCH.ACCRUE_INTEREST (OUT P_ROWS_PROCESSED INTEGER)
    LANGUAGE SQL
    SPECIFIC BATCH_ACCRUE_INTEREST
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);
    DECLARE V_RUN_ID   BIGINT;
    DECLARE V_ROWS     INTEGER DEFAULT 0;
    DECLARE V_ACCRUED  INTEGER DEFAULT 0;
    DECLARE V_EOF      SMALLINT DEFAULT 0;
    DECLARE V_TODAY    DATE;
    DECLARE V_COMMIT_EVERY INTEGER DEFAULT 500;
    DECLARE V_CREDIT_TOTAL DECIMAL(17,6) DEFAULT 0;
    DECLARE V_DEBIT_TOTAL  DECIMAL(17,6) DEFAULT 0;
    DECLARE V_PAYABLE_ADJ    DECIMAL(15,2);
    DECLARE V_RECEIVABLE_ADJ DECIMAL(15,2);

    DECLARE V_ACCOUNT_ID BIGINT;
    DECLARE V_PRODUCT    CHAR(6);
    DECLARE V_LEDGER     DECIMAL(15,2);
    DECLARE V_LAST       DATE;
    DECLARE V_FUTURE     DECIMAL(15,2);
    DECLARE V_BALANCE    DECIMAL(15,2);
    DECLARE V_DAYS       SMALLINT;
    DECLARE V_RATE       DECIMAL(7,4);
    DECLARE V_AMOUNT     DECIMAL(15,6);

    DECLARE C_ACCOUNTS CURSOR WITH HOLD FOR
        SELECT A.ACCOUNT_ID, A.PRODUCT_CODE, A.LEDGER_BALANCE, A.LAST_ACCRUAL_DATE
          FROM ACCT.ACCOUNT A
         WHERE A.STATUS <> 'C'
           AND (A.LAST_ACCRUAL_DATE IS NULL OR A.LAST_ACCRUAL_DATE < V_TODAY)
           AND A.PRODUCT_CODE IN (SELECT P.PRODUCT_CODE
                                    FROM REF.PRODUCT P
                                   WHERE P.PRODUCT_TYPE <> 'LON')
         ORDER BY A.ACCOUNT_ID
          WITH CS;

    DECLARE CONTINUE HANDLER FOR NOT FOUND SET V_EOF = 1;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.END_JOB_RUN(V_RUN_ID, 'F', V_ROWS, V_MSG);
        CALL UTIL.LOG_ERROR('BATCH.ACCRUE_INTEREST', V_SQLSTATE, V_SQLCODE, V_MSG,
                            'ACCOUNT_ID=' || COALESCE(RTRIM(CHAR(V_ACCOUNT_ID)), '-'));
        RESIGNAL;
    END;

    CALL UTIL.START_JOB_RUN('ACCRUE_INTEREST', V_RUN_ID);
    SET V_TODAY = UTIL.CURRENT_BUSINESS_DATE();

    OPEN C_ACCOUNTS;
    ACCRUAL_LOOP:
    LOOP
        SET V_EOF = 0;
        FETCH C_ACCOUNTS INTO V_ACCOUNT_ID, V_PRODUCT, V_LEDGER, V_LAST;
        IF V_EOF = 1 THEN
            LEAVE ACCRUAL_LOOP;
        END IF;

        -- End-of-day balance: exclude anything already value-dated after today (post cut-off)
        SELECT COALESCE(SUM(AMOUNT), 0)
          INTO V_FUTURE
          FROM TXN.POSTED_TXN
         WHERE ACCOUNT_ID = V_ACCOUNT_ID
           AND BUSINESS_DATE > V_TODAY;
        SET V_BALANCE = V_LEDGER - V_FUTURE;

        -- Calendar days since the last accrual: Monday picks up Saturday and Sunday
        SET V_DAYS = DAYS(V_TODAY) - DAYS(COALESCE(V_LAST, V_TODAY - 1 DAY));
        SET V_RATE = UTIL.INTEREST_RATE(V_PRODUCT, V_BALANCE, V_TODAY);
        SET V_AMOUNT = ROUND(DECIMAL(V_BALANCE * V_RATE * V_DAYS, 31, 8) / 36500, 6);

        IF V_AMOUNT <> 0 THEN
            INSERT INTO ACCT.INTEREST_ACCRUAL (ACCOUNT_ID, BUSINESS_DATE, DAYS, BALANCE, ANNUAL_RATE, AMOUNT)
            VALUES (V_ACCOUNT_ID, V_TODAY, V_DAYS, V_BALANCE, V_RATE, V_AMOUNT);

            UPDATE ACCT.ACCOUNT
               SET ACCRUED_INTEREST = ACCRUED_INTEREST + V_AMOUNT,
                   LAST_ACCRUAL_DATE = V_TODAY
             WHERE ACCOUNT_ID = V_ACCOUNT_ID;

            SET V_ACCRUED = V_ACCRUED + 1;
            IF V_AMOUNT > 0 THEN
                SET V_CREDIT_TOTAL = V_CREDIT_TOTAL + V_AMOUNT;
            ELSE
                SET V_DEBIT_TOTAL = V_DEBIT_TOTAL + V_AMOUNT;
            END IF;
        ELSE
            UPDATE ACCT.ACCOUNT
               SET LAST_ACCRUAL_DATE = V_TODAY
             WHERE ACCOUNT_ID = V_ACCOUNT_ID;
        END IF;

        SET V_ROWS = V_ROWS + 1;
        IF MOD(V_ROWS, V_COMMIT_EVERY) = 0 THEN
            COMMIT;
        END IF;
    END LOOP ACCRUAL_LOOP;
    CLOSE C_ACCOUNTS;

    -- One balanced GL pair per direction for the whole run (see TRUE_UP_ACCRUAL_GL)
    CALL BATCH.TRUE_UP_ACCRUAL_GL(V_TODAY, 'ACCRUE_INTEREST', V_PAYABLE_ADJ, V_RECEIVABLE_ADJ);
    COMMIT;

    SET P_ROWS_PROCESSED = V_ROWS;
    CALL UTIL.END_JOB_RUN(V_RUN_ID, 'S', V_ROWS,
         RTRIM(CHAR(V_ROWS)) || ' accounts, ' || RTRIM(CHAR(V_ACCRUED)) || ' accrued: credit '
         || VARCHAR(V_CREDIT_TOTAL) || ', debit ' || VARCHAR(V_DEBIT_TOTAL)
         || '; GL 2210 adj ' || VARCHAR(V_PAYABLE_ADJ) || ', 1210 adj ' || VARCHAR(V_RECEIVABLE_ADJ));
END@
