-- Intraday (every minute): "sends" queued customer notifications (STATUS 'P' -> 'S').
-- Uses SKIP LOCKED DATA so several dispatchers - or a slow online transaction still holding
-- a new outbox row - never block each other. No contact for the channel: retried, 'F' after 3.
CREATE OR REPLACE PROCEDURE BATCH.DISPATCH_NOTIFICATIONS (OUT P_ROWS_PROCESSED INTEGER)
    LANGUAGE SQL
    SPECIFIC BATCH_DISPATCH_NOTIFICATIONS
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);
    DECLARE V_RUN_ID   BIGINT;
    DECLARE V_ROWS     INTEGER DEFAULT 0;
    DECLARE V_SENT     INTEGER DEFAULT 0;
    DECLARE V_FAILED   INTEGER DEFAULT 0;
    DECLARE V_EOF      SMALLINT DEFAULT 0;
    DECLARE V_HAS_CONTACT INTEGER;
    DECLARE V_MAX_ATTEMPTS SMALLINT DEFAULT 3;

    DECLARE V_NOTIFICATION_ID BIGINT;
    DECLARE V_CUSTOMER_ID     BIGINT;
    DECLARE V_CHANNEL         CHAR(5);
    DECLARE V_ATTEMPTS        SMALLINT;

    -- Capped per run; ordering is not guaranteed (an ORDER BY would make the cursor read-only)
    DECLARE C_OUTBOX CURSOR WITH HOLD FOR
        SELECT NOTIFICATION_ID, CUSTOMER_ID, CHANNEL, ATTEMPTS
          FROM OPS.NOTIFICATION_OUTBOX
         WHERE STATUS = 'P'
         FETCH FIRST 1000 ROWS ONLY
           FOR UPDATE OF STATUS, ATTEMPTS, SENT_TS
          WITH CS SKIP LOCKED DATA;

    DECLARE CONTINUE HANDLER FOR NOT FOUND SET V_EOF = 1;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.END_JOB_RUN(V_RUN_ID, 'F', V_ROWS, V_MSG);
        CALL UTIL.LOG_ERROR('BATCH.DISPATCH_NOTIFICATIONS', V_SQLSTATE, V_SQLCODE, V_MSG, NULL);
        RESIGNAL;
    END;

    CALL UTIL.START_JOB_RUN('DISPATCH_NOTIFICATIONS', V_RUN_ID);

    OPEN C_OUTBOX;
    SEND_LOOP:
    LOOP
        SET V_EOF = 0;
        FETCH C_OUTBOX INTO V_NOTIFICATION_ID, V_CUSTOMER_ID, V_CHANNEL, V_ATTEMPTS;
        IF V_EOF = 1 THEN
            LEAVE SEND_LOOP;
        END IF;

        -- The "gateway": we can deliver if the customer has a contact for the channel
        SELECT COUNT(*)
          INTO V_HAS_CONTACT
          FROM CUST.CONTACT
         WHERE CUSTOMER_ID = V_CUSTOMER_ID
           AND CONTACT_TYPE = CASE RTRIM(V_CHANNEL) WHEN 'SMS' THEN 'MOBIL' ELSE 'EMAIL' END
          WITH UR;

        IF V_HAS_CONTACT > 0 THEN
            UPDATE OPS.NOTIFICATION_OUTBOX
               SET STATUS = 'S',
                   ATTEMPTS = ATTEMPTS + 1,
                   SENT_TS = CURRENT TIMESTAMP
             WHERE CURRENT OF C_OUTBOX;
            SET V_SENT = V_SENT + 1;
        ELSE
            UPDATE OPS.NOTIFICATION_OUTBOX
               SET STATUS = CASE WHEN ATTEMPTS + 1 >= V_MAX_ATTEMPTS THEN 'F' ELSE 'P' END,
                   ATTEMPTS = ATTEMPTS + 1
             WHERE CURRENT OF C_OUTBOX;
            SET V_FAILED = V_FAILED + 1;
        END IF;

        SET V_ROWS = V_ROWS + 1;
        IF MOD(V_ROWS, 200) = 0 THEN
            COMMIT;
        END IF;
    END LOOP SEND_LOOP;
    CLOSE C_OUTBOX;

    COMMIT;

    SET P_ROWS_PROCESSED = V_ROWS;
    CALL UTIL.END_JOB_RUN(V_RUN_ID, 'S', V_ROWS,
         RTRIM(CHAR(V_SENT)) || ' sent, ' || RTRIM(CHAR(V_FAILED)) || ' undeliverable');
END@
