-- Month-end: closing snapshot of the whole chart of accounts. Leaf GL balances as at today are
-- rolled up the REF.GL_ACCOUNT parent hierarchy with a recursive common table expression and
-- stored in GL.GL_DAILY_BALANCE for every code, parents included. The five roots (1000..5000)
-- must net to zero; if not a MONTH_END_TRIAL_BALANCE break is written.
CREATE OR REPLACE PROCEDURE BATCH.MONTH_END_GL_CLOSE (OUT P_ROWS_PROCESSED INTEGER)
    LANGUAGE SQL
    SPECIFIC BATCH_MONTH_END_GL_CLOSE
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);
    DECLARE V_RUN_ID   BIGINT;
    DECLARE V_ROWS     INTEGER DEFAULT 0;
    DECLARE V_TODAY    DATE;
    DECLARE V_TRIAL    DECIMAL(17,2);
    DECLARE V_ASSETS   DECIMAL(17,2);
    DECLARE V_LIABS    DECIMAL(17,2);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.END_JOB_RUN(V_RUN_ID, 'F', V_ROWS, V_MSG);
        CALL UTIL.LOG_ERROR('BATCH.MONTH_END_GL_CLOSE', V_SQLSTATE, V_SQLCODE, V_MSG, NULL);
        RESIGNAL;
    END;

    CALL UTIL.START_JOB_RUN('MONTH_END_GL_CLOSE', V_RUN_ID);
    SET V_TODAY = UTIL.CURRENT_BUSINESS_DATE();

    DELETE FROM GL.GL_DAILY_BALANCE
     WHERE BUSINESS_DATE = V_TODAY;

    -- TREE pairs every GL code with itself and all its descendants; summing the leaf balances
    -- of the descendants gives the rolled-up balance of each code.
    INSERT INTO GL.GL_DAILY_BALANCE (GL_CODE, BUSINESS_DATE, BALANCE)
    WITH LEAF_BALANCE (GL_CODE, BALANCE) AS (
        SELECT E.GL_CODE, SUM(E.AMOUNT)
          FROM GL.GL_ENTRY E
         WHERE E.BUSINESS_DATE <= V_TODAY
         GROUP BY E.GL_CODE
    ),
    TREE (ANCESTOR_CODE, GL_CODE, DEPTH) AS (
        SELECT G.GL_CODE, G.GL_CODE, 0
          FROM REF.GL_ACCOUNT G
        UNION ALL
        SELECT T.ANCESTOR_CODE, C.GL_CODE, T.DEPTH + 1
          FROM TREE T, REF.GL_ACCOUNT C
         WHERE C.PARENT_GL_CODE = T.GL_CODE
           AND T.DEPTH < 10
    )
    SELECT T.ANCESTOR_CODE, V_TODAY, COALESCE(SUM(L.BALANCE), 0)
      FROM TREE T
      LEFT OUTER JOIN LEAF_BALANCE L
        ON L.GL_CODE = T.GL_CODE
     GROUP BY T.ANCESTOR_CODE;
    GET DIAGNOSTICS V_ROWS = ROW_COUNT;

    SELECT SUM(D.BALANCE),
           SUM(CASE WHEN G.GL_TYPE = 'A' THEN D.BALANCE ELSE 0 END),
           SUM(CASE WHEN G.GL_TYPE = 'L' THEN -D.BALANCE ELSE 0 END)
      INTO V_TRIAL, V_ASSETS, V_LIABS
      FROM GL.GL_DAILY_BALANCE D
      JOIN REF.GL_ACCOUNT G
        ON G.GL_CODE = D.GL_CODE
     WHERE D.BUSINESS_DATE = V_TODAY
       AND G.PARENT_GL_CODE IS NULL;

    DELETE FROM GL.RECON_BREAK
     WHERE BUSINESS_DATE = V_TODAY
       AND CHECK_NAME = 'MONTH_END_TRIAL_BALANCE';

    IF COALESCE(V_TRIAL, 0) <> 0 THEN
        INSERT INTO GL.RECON_BREAK (BUSINESS_DATE, CHECK_NAME, EXPECTED, ACTUAL)
        VALUES (V_TODAY, 'MONTH_END_TRIAL_BALANCE', 0, V_TRIAL);
    END IF;

    COMMIT;

    SET P_ROWS_PROCESSED = V_ROWS;
    CALL UTIL.END_JOB_RUN(V_RUN_ID, 'S', V_ROWS,
         'Month-end close ' || VARCHAR_FORMAT(V_TODAY, 'Mon YYYY') || ': ' || RTRIM(CHAR(V_ROWS))
         || ' GL codes; assets ' || VARCHAR(COALESCE(V_ASSETS, 0)) || ', liabilities '
         || VARCHAR(COALESCE(V_LIABS, 0)) || ', trial balance ' || VARCHAR(COALESCE(V_TRIAL, 0)));
END@
