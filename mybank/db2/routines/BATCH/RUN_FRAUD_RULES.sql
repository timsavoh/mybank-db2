-- EOD: runs every active RISK.FRAUD_RULE. Each rule is a SELECT stored as text (returning
-- ACCOUNT_ID, CARD_ID, SCORE, DETAIL, with :BDATE for the business date); it is executed
-- dynamically into a session temp table and each hit raised via UTIL.RAISE_FRAUD_ALERT.
-- A broken rule is logged to OPS.ERROR_LOG and skipped; it never stops the chain.
CREATE OR REPLACE PROCEDURE BATCH.RUN_FRAUD_RULES (OUT P_ROWS_PROCESSED INTEGER)
    LANGUAGE SQL
    SPECIFIC BATCH_RUN_FRAUD_RULES
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);
    DECLARE V_RUN_ID   BIGINT;
    DECLARE V_ROWS     INTEGER DEFAULT 0;
    DECLARE V_TODAY    DATE;
    DECLARE V_DATE_LITERAL VARCHAR(20);
    DECLARE V_SQL      VARCHAR(5000);
    DECLARE V_RULES    INTEGER DEFAULT 0;
    DECLARE V_BAD_RULES INTEGER DEFAULT 0;
    DECLARE V_NEW_ALERTS INTEGER DEFAULT 0;
    DECLARE V_RULE_OK  SMALLINT;
    DECLARE V_ALERT_ID BIGINT;
    DECLARE V_MAX_ALERT_ID BIGINT;
    DECLARE V_RULE_STATE CHAR(5);
    DECLARE V_RULE_CODE  INTEGER;
    DECLARE V_RULE_MSG   VARCHAR(1000);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.END_JOB_RUN(V_RUN_ID, 'F', V_ROWS, V_MSG);
        CALL UTIL.LOG_ERROR('BATCH.RUN_FRAUD_RULES', V_SQLSTATE, V_SQLCODE, V_MSG, NULL);
        RESIGNAL;
    END;

    CALL UTIL.START_JOB_RUN('RUN_FRAUD_RULES', V_RUN_ID);
    SET V_TODAY = UTIL.CURRENT_BUSINESS_DATE();
    SET V_DATE_LITERAL = 'DATE(''' || CHAR(V_TODAY, ISO) || ''')';

    DECLARE GLOBAL TEMPORARY TABLE SESSION.FRAUD_HITS (
        ACCOUNT_ID BIGINT,
        CARD_ID    BIGINT,
        SCORE      SMALLINT,
        DETAIL     VARCHAR(500)
    ) WITH REPLACE ON COMMIT PRESERVE ROWS NOT LOGGED;

    FOR R AS C_RULES CURSOR WITH HOLD FOR
        SELECT RULE_ID, NAME, RULE_SQL
          FROM RISK.FRAUD_RULE
         WHERE ACTIVE = 'Y'
         ORDER BY RULE_ID
    DO
        SET V_RULES = V_RULES + 1;
        SET V_RULE_OK = 1;
        DELETE FROM SESSION.FRAUD_HITS;

        SET V_SQL = 'INSERT INTO SESSION.FRAUD_HITS (ACCOUNT_ID, CARD_ID, SCORE, DETAIL) '
                    || REPLACE(R.RULE_SQL, ':BDATE', V_DATE_LITERAL);

        RULE_BLOCK:
        BEGIN
            DECLARE EXIT HANDLER FOR SQLEXCEPTION
            BEGIN
                GET DIAGNOSTICS EXCEPTION 1 V_RULE_MSG = MESSAGE_TEXT;
                VALUES (SQLSTATE, SQLCODE) INTO V_RULE_STATE, V_RULE_CODE;
                SET V_RULE_OK = 0;
            END;

            EXECUTE IMMEDIATE V_SQL;
        END RULE_BLOCK;

        IF V_RULE_OK = 0 THEN
            CALL UTIL.LOG_ERROR('BATCH.RUN_FRAUD_RULES', V_RULE_STATE, V_RULE_CODE, V_RULE_MSG,
                                'RULE_ID=' || RTRIM(CHAR(R.RULE_ID)) || ' ' || R.NAME);
            SET V_BAD_RULES = V_BAD_RULES + 1;
        ELSE
            SELECT COALESCE(MAX(ALERT_ID), 0) INTO V_MAX_ALERT_ID FROM RISK.FRAUD_ALERT;

            FOR H AS C_HITS CURSOR FOR
                SELECT ACCOUNT_ID, CARD_ID, SCORE, DETAIL
                  FROM SESSION.FRAUD_HITS
                 WHERE ACCOUNT_ID IS NOT NULL
            DO
                -- Raises nothing if the account already has an open alert for this rule
                CALL UTIL.RAISE_FRAUD_ALERT(H.ACCOUNT_ID, H.CARD_ID, R.RULE_ID,
                                            COALESCE(H.SCORE, 0), COALESCE(H.DETAIL, R.NAME), V_ALERT_ID);
                IF V_ALERT_ID > V_MAX_ALERT_ID THEN
                    SET V_NEW_ALERTS = V_NEW_ALERTS + 1;
                END IF;
                SET V_ROWS = V_ROWS + 1;
            END FOR;
        END IF;

        COMMIT;
    END FOR;

    COMMIT;

    SET P_ROWS_PROCESSED = V_ROWS;
    CALL UTIL.END_JOB_RUN(V_RUN_ID, 'S', V_ROWS,
         RTRIM(CHAR(V_RULES)) || ' rules run for ' || CHAR(V_TODAY, ISO) || ', ' || RTRIM(CHAR(V_ROWS))
         || ' hits, ' || RTRIM(CHAR(V_NEW_ALERTS)) || ' new alerts, ' || RTRIM(CHAR(V_BAD_RULES)) || ' rules failed');
END@
