-- Db2 admin task (SYSPROC.ADMIN_TASK_ADD, every 15 minutes; see db2/tasks/admin_tasks.sql):
-- full refresh of the REFRESH DEFERRED reporting MQTs the optimizer routes report queries to.
-- No parameters (ATS). A failure on one MQT is logged and the other is still refreshed.
CREATE OR REPLACE PROCEDURE BATCH.REFRESH_REPORTING_MQTS ()
    LANGUAGE SQL
    SPECIFIC BATCH_REFRESH_REPORTING_MQTS
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);
    DECLARE V_RUN_ID   BIGINT;
    DECLARE V_ROWS     INTEGER DEFAULT 0;
    DECLARE V_FAILED   INTEGER DEFAULT 0;
    DECLARE V_ROW_STATE CHAR(5);
    DECLARE V_ROW_CODE INTEGER;
    DECLARE V_ROW_MSG  VARCHAR(1000);
    DECLARE V_DETAIL   VARCHAR(500) DEFAULT '';

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.END_JOB_RUN(V_RUN_ID, 'F', V_ROWS, V_MSG);
        CALL UTIL.LOG_ERROR('BATCH.REFRESH_REPORTING_MQTS', V_SQLSTATE, V_SQLCODE, V_MSG, NULL);
        RESIGNAL;
    END;

    CALL UTIL.START_JOB_RUN('REFRESH_REPORTING_MQTS', V_RUN_ID);

    FOR M AS C_MQTS CURSOR WITH HOLD FOR
        SELECT RTRIM(TABSCHEMA) || '.' || RTRIM(TABNAME) AS MQT_NAME
          FROM SYSCAT.TABLES
         WHERE TYPE = 'S'
           AND TABSCHEMA = 'RPT'
           AND TABNAME IN ('MQT_DAILY_LIQUIDITY', 'MQT_MERCHANT_SPEND')
         ORDER BY TABNAME
    DO
        SET V_ROW_STATE = '00000';
        REFRESH_BLOCK:
        BEGIN
            DECLARE EXIT HANDLER FOR SQLEXCEPTION
            BEGIN
                GET DIAGNOSTICS EXCEPTION 1 V_ROW_MSG = MESSAGE_TEXT;
                VALUES (SQLSTATE, SQLCODE) INTO V_ROW_STATE, V_ROW_CODE;
            END;
            EXECUTE IMMEDIATE 'REFRESH TABLE ' || M.MQT_NAME;
        END REFRESH_BLOCK;

        IF V_ROW_STATE = '00000' THEN
            COMMIT;
            SET V_ROWS = V_ROWS + 1;
            SET V_DETAIL = V_DETAIL || ' ' || M.MQT_NAME;
        ELSE
            ROLLBACK;
            CALL UTIL.LOG_ERROR('BATCH.REFRESH_REPORTING_MQTS', V_ROW_STATE, V_ROW_CODE, V_ROW_MSG, M.MQT_NAME);
            SET V_FAILED = V_FAILED + 1;
        END IF;
    END FOR;

    CALL UTIL.END_JOB_RUN(V_RUN_ID, CASE WHEN V_FAILED > 0 THEN 'F' ELSE 'S' END, V_ROWS,
         RTRIM(CHAR(V_ROWS)) || ' MQTs refreshed:' || V_DETAIL
         || CASE WHEN V_FAILED > 0 THEN '; ' || RTRIM(CHAR(V_FAILED)) || ' failed (see OPS.ERROR_LOG)' ELSE '' END);
END@
