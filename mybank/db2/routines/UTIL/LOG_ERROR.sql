-- Error logger. AUTONOMOUS: the log row commits even when the caller rolls back.
-- Typical use inside an EXIT HANDLER before RESIGNAL.
CREATE OR REPLACE PROCEDURE UTIL.LOG_ERROR (
    IN P_PROC_NAME VARCHAR(80),
    IN P_SQLSTATE  CHAR(5),
    IN P_SQLCODE   INTEGER,
    IN P_MESSAGE   VARCHAR(1000),
    IN P_CONTEXT   VARCHAR(1000)
)
    LANGUAGE SQL
    SPECIFIC UTIL_LOG_ERROR
    AUTONOMOUS
    MODIFIES SQL DATA
BEGIN
    INSERT INTO OPS.ERROR_LOG (PROC_NAME, SQL_STATE, SQL_CODE, MESSAGE, CONTEXT)
    VALUES (P_PROC_NAME, P_SQLSTATE, P_SQLCODE, P_MESSAGE, P_CONTEXT);
END@
