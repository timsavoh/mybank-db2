-- Check digit for a 7-digit account number base: weights 7..1, modulus 10.
CREATE OR REPLACE FUNCTION UTIL.ACCOUNT_CHECK_DIGIT (P_BASE CHAR(7))
    RETURNS CHAR(1)
    LANGUAGE SQL
    SPECIFIC UTIL_ACCOUNT_CHECK_DIGIT
    DETERMINISTIC
    NO EXTERNAL ACTION
    CONTAINS SQL
BEGIN
    DECLARE V_SUM INTEGER DEFAULT 0;
    DECLARE V_I   INTEGER DEFAULT 1;

    WHILE V_I <= 7 DO
        SET V_SUM = V_SUM + INTEGER(SUBSTR(P_BASE, V_I, 1)) * (8 - V_I);
        SET V_I = V_I + 1;
    END WHILE;
    RETURN CHAR(MOD(V_SUM, 10));
END@
