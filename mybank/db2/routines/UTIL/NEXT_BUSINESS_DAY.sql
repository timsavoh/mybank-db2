-- First business day strictly after P_DATE (skips weekends and REF.HOLIDAY).
-- Callers wanting "this day or the next business day" pass P_DATE - 1 DAY.
CREATE OR REPLACE FUNCTION UTIL.NEXT_BUSINESS_DAY (P_DATE DATE)
    RETURNS DATE
    LANGUAGE SQL
    SPECIFIC UTIL_NEXT_BUSINESS_DAY
    READS SQL DATA
    NOT DETERMINISTIC
    NO EXTERNAL ACTION
BEGIN
    DECLARE V_DATE DATE;
    DECLARE V_HOLIDAYS INTEGER DEFAULT 0;

    SET V_DATE = P_DATE + 1 DAY;
    LOOP
        SELECT COUNT(*) INTO V_HOLIDAYS FROM REF.HOLIDAY WHERE HOLIDAY_DATE = V_DATE;
        IF DAYOFWEEK_ISO(V_DATE) < 6 AND V_HOLIDAYS = 0 THEN
            RETURN V_DATE;
        END IF;
        SET V_DATE = V_DATE + 1 DAY;
    END LOOP;
END@
