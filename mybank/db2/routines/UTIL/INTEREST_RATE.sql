-- Annual rate (percent) for a product at a balance on a date.
-- Credit balances use the tier table; debit balances use the product overdraft rate.
CREATE OR REPLACE FUNCTION UTIL.INTEREST_RATE (P_PRODUCT_CODE CHAR(6), P_BALANCE DECIMAL(15,2), P_AS_OF DATE)
    RETURNS DECIMAL(7,4)
    LANGUAGE SQL
    SPECIFIC UTIL_INTEREST_RATE
    READS SQL DATA
    NOT DETERMINISTIC
    NO EXTERNAL ACTION
BEGIN
    DECLARE V_RATE DECIMAL(7,4);

    IF P_BALANCE < 0 THEN
        SELECT OD_RATE INTO V_RATE FROM REF.PRODUCT WHERE PRODUCT_CODE = P_PRODUCT_CODE;
        RETURN COALESCE(V_RATE, 0);
    END IF;

    SELECT T.ANNUAL_RATE
      INTO V_RATE
      FROM REF.INTEREST_RATE_TIER T
     WHERE T.PRODUCT_CODE = P_PRODUCT_CODE
       AND T.EFFECTIVE_FROM = (SELECT MAX(EFFECTIVE_FROM)
                                 FROM REF.INTEREST_RATE_TIER
                                WHERE PRODUCT_CODE = P_PRODUCT_CODE
                                  AND EFFECTIVE_FROM <= P_AS_OF)
       AND P_BALANCE >= T.TIER_FROM
       AND (T.TIER_TO IS NULL OR P_BALANCE < T.TIER_TO)
     FETCH FIRST 1 ROW ONLY;

    RETURN COALESCE(V_RATE, 0);
END@
