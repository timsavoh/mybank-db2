-- Opens a fraud alert unless an open alert already exists for the same account and rule.
CREATE OR REPLACE PROCEDURE UTIL.RAISE_FRAUD_ALERT (
    IN  P_ACCOUNT_ID BIGINT,
    IN  P_CARD_ID    BIGINT,
    IN  P_RULE_ID    SMALLINT,
    IN  P_SCORE      SMALLINT,
    IN  P_DETAIL     VARCHAR(500),
    OUT P_ALERT_ID   BIGINT
)
    LANGUAGE SQL
    SPECIFIC UTIL_RAISE_FRAUD_ALERT
    MODIFIES SQL DATA
BEGIN
    SET P_ALERT_ID = NULL;

    SELECT ALERT_ID
      INTO P_ALERT_ID
      FROM RISK.FRAUD_ALERT
     WHERE ACCOUNT_ID = P_ACCOUNT_ID
       AND STATUS = 'O'
       AND (RULE_ID = P_RULE_ID OR (RULE_ID IS NULL AND P_RULE_ID IS NULL))
     FETCH FIRST 1 ROW ONLY
      WITH UR;

    IF P_ALERT_ID IS NOT NULL THEN
        RETURN;
    END IF;

    SELECT ALERT_ID
      INTO P_ALERT_ID
      FROM FINAL TABLE (INSERT INTO RISK.FRAUD_ALERT
                            (ACCOUNT_ID, CARD_ID, RULE_ID, SCORE, DETAIL, BUSINESS_DATE)
                        VALUES (P_ACCOUNT_ID, P_CARD_ID, P_RULE_ID, P_SCORE, P_DETAIL,
                                UTIL.CURRENT_BUSINESS_DATE()));
END@
