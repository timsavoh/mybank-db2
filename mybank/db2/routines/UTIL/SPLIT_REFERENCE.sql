-- Splits a delimited payment reference into tokens, e.g.
--   SELECT * FROM TABLE(UTIL.SPLIT_REFERENCE('INV/2024/0042', '/'))
CREATE OR REPLACE FUNCTION UTIL.SPLIT_REFERENCE (P_TEXT VARCHAR(200), P_DELIM CHAR(1))
    RETURNS TABLE (TOKEN_NO INTEGER, TOKEN VARCHAR(200))
    LANGUAGE SQL
    SPECIFIC UTIL_SPLIT_REFERENCE
    DETERMINISTIC
    NO EXTERNAL ACTION
    CONTAINS SQL
BEGIN
    DECLARE V_START INTEGER DEFAULT 1;
    DECLARE V_IDX   INTEGER;
    DECLARE V_N     INTEGER DEFAULT 0;

    IF P_TEXT IS NULL THEN
        RETURN;
    END IF;

    LOOP
        SET V_IDX = LOCATE(P_DELIM, P_TEXT, V_START);
        SET V_N = V_N + 1;
        IF V_IDX = 0 THEN
            PIPE (V_N, SUBSTR(P_TEXT, V_START));
            RETURN;
        END IF;
        PIPE (V_N, SUBSTR(P_TEXT, V_START, V_IDX - V_START));
        SET V_START = V_IDX + 1;
    END LOOP;
END@
