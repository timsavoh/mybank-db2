-- Queues a customer notification on their preferred channel (mobile if held, else email).
CREATE OR REPLACE PROCEDURE UTIL.ENQUEUE_NOTIFICATION (
    IN P_CUSTOMER_ID BIGINT,
    IN P_TEMPLATE    VARCHAR(30),
    IN P_PAYLOAD     VARCHAR(2000)
)
    LANGUAGE SQL
    SPECIFIC UTIL_ENQUEUE_NOTIFICATION
    MODIFIES SQL DATA
BEGIN
    DECLARE V_CHANNEL CHAR(5);

    SELECT CASE WHEN SUM(CASE WHEN CONTACT_TYPE = 'MOBIL' THEN 1 ELSE 0 END) > 0
                THEN 'SMS' ELSE 'EMAIL' END
      INTO V_CHANNEL
      FROM CUST.CONTACT
     WHERE CUSTOMER_ID = P_CUSTOMER_ID;

    INSERT INTO OPS.NOTIFICATION_OUTBOX (CUSTOMER_ID, CHANNEL, TEMPLATE, PAYLOAD)
    VALUES (P_CUSTOMER_ID, V_CHANNEL, P_TEMPLATE, P_PAYLOAD);
END@
