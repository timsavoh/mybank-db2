-- Business date for online postings. Once end-of-day cut-off has started,
-- online activity is value-dated to the next business day.
CREATE OR REPLACE FUNCTION UTIL.POSTING_DATE ()
    RETURNS DATE
    LANGUAGE SQL
    SPECIFIC UTIL_POSTING_DATE
    READS SQL DATA
    NOT DETERMINISTIC
    NO EXTERNAL ACTION
BEGIN
    DECLARE V_BUSINESS_DATE DATE;
    DECLARE V_DAY_STATUS CHAR(1);

    SELECT BUSINESS_DATE, DAY_STATUS
      INTO V_BUSINESS_DATE, V_DAY_STATUS
      FROM REF.BANK_CONTROL
     WHERE CONTROL_ID = 1;

    IF V_DAY_STATUS = 'C' THEN
        RETURN UTIL.NEXT_BUSINESS_DAY(V_BUSINESS_DATE);
    END IF;
    RETURN V_BUSINESS_DATE;
END@
