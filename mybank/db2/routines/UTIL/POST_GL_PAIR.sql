-- Balanced GL posting: +amount to the debit GL, -amount to the credit GL.
CREATE OR REPLACE PROCEDURE UTIL.POST_GL_PAIR (
    IN P_DEBIT_GL       CHAR(4),
    IN P_CREDIT_GL      CHAR(4),
    IN P_AMOUNT         DECIMAL(15,2),
    IN P_BUSINESS_DATE  DATE,
    IN P_CORRELATION_ID BIGINT,
    IN P_TXN_ID         BIGINT,
    IN P_DESCRIPTION    VARCHAR(100)
)
    LANGUAGE SQL
    SPECIFIC UTIL_POST_GL_PAIR
    MODIFIES SQL DATA
BEGIN
    IF P_DEBIT_GL = P_CREDIT_GL THEN
        RETURN;
    END IF;

    INSERT INTO GL.GL_ENTRY (BUSINESS_DATE, GL_CODE, AMOUNT, CORRELATION_ID, TXN_ID, DESCRIPTION)
    VALUES (P_BUSINESS_DATE, P_DEBIT_GL,   P_AMOUNT, P_CORRELATION_ID, P_TXN_ID, P_DESCRIPTION),
           (P_BUSINESS_DATE, P_CREDIT_GL, -P_AMOUNT, P_CORRELATION_ID, P_TXN_ID, P_DESCRIPTION);
END@
