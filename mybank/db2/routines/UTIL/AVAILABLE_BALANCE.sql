-- Ledger balance less active holds plus arranged overdraft.
CREATE OR REPLACE FUNCTION UTIL.AVAILABLE_BALANCE (P_ACCOUNT_ID BIGINT)
    RETURNS DECIMAL(15,2)
    LANGUAGE SQL
    SPECIFIC UTIL_AVAILABLE_BALANCE
    READS SQL DATA
    NOT DETERMINISTIC
    NO EXTERNAL ACTION
    RETURN (SELECT LEDGER_BALANCE - HOLD_AMOUNT + OVERDRAFT_LIMIT
              FROM ACCT.ACCOUNT
             WHERE ACCOUNT_ID = P_ACCOUNT_ID)@
