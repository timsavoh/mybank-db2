-- Records the end of a batch job run. P_STATUS: S success, F failure.
CREATE OR REPLACE PROCEDURE UTIL.END_JOB_RUN (
    IN P_RUN_ID  BIGINT,
    IN P_STATUS  CHAR(1),
    IN P_ROWS    INTEGER,
    IN P_MESSAGE VARCHAR(1000)
)
    LANGUAGE SQL
    SPECIFIC UTIL_END_JOB_RUN
    AUTONOMOUS
    MODIFIES SQL DATA
BEGIN
    UPDATE OPS.BATCH_JOB_RUN
       SET ENDED_TS = CURRENT TIMESTAMP,
           STATUS = P_STATUS,
           ROWS_PROCESSED = COALESCE(P_ROWS, 0),
           MESSAGE = P_MESSAGE
     WHERE RUN_ID = P_RUN_ID;
END@
