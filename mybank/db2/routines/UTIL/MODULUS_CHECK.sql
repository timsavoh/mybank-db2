-- 1 if the sort code / account number pair is well formed and the check digit matches.
CREATE OR REPLACE FUNCTION UTIL.MODULUS_CHECK (P_SORT_CODE CHAR(6), P_ACCOUNT_NO CHAR(8))
    RETURNS SMALLINT
    LANGUAGE SQL
    SPECIFIC UTIL_MODULUS_CHECK
    DETERMINISTIC
    NO EXTERNAL ACTION
    CONTAINS SQL
BEGIN
    IF P_SORT_CODE IS NULL OR P_ACCOUNT_NO IS NULL
       OR TRANSLATE(P_SORT_CODE, '', '0123456789') <> ''
       OR TRANSLATE(P_ACCOUNT_NO, '', '0123456789') <> '' THEN
        RETURN 0;
    END IF;
    IF UTIL.ACCOUNT_CHECK_DIGIT(SUBSTR(P_ACCOUNT_NO, 1, 7)) = SUBSTR(P_ACCOUNT_NO, 8, 1) THEN
        RETURN 1;
    END IF;
    RETURN 0;
END@
