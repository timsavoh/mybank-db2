-- Fee for a fee code applied to a base amount, bounded by the schedule's min/max.
CREATE OR REPLACE FUNCTION UTIL.CALC_FEE (P_FEE_CODE CHAR(8), P_BASE_AMOUNT DECIMAL(15,2))
    RETURNS DECIMAL(9,2)
    LANGUAGE SQL
    SPECIFIC UTIL_CALC_FEE
    READS SQL DATA
    NOT DETERMINISTIC
    NO EXTERNAL ACTION
BEGIN
    DECLARE V_FLAT DECIMAL(9,2);
    DECLARE V_PCT  DECIMAL(7,4);
    DECLARE V_MIN  DECIMAL(9,2);
    DECLARE V_MAX  DECIMAL(9,2);
    DECLARE V_FEE  DECIMAL(9,2);

    SELECT FLAT_AMOUNT, PCT_RATE, MIN_AMOUNT, MAX_AMOUNT
      INTO V_FLAT, V_PCT, V_MIN, V_MAX
      FROM REF.FEE_SCHEDULE
     WHERE FEE_CODE = P_FEE_CODE;

    IF V_FLAT IS NULL THEN
        RETURN 0;
    END IF;

    -- DECIMAL() truncates; ROUND() then DECIMAL() is the house style for money
    SET V_FEE = DECIMAL(ROUND(V_FLAT + ABS(COALESCE(P_BASE_AMOUNT, 0)) * V_PCT / 100, 2), 9, 2);
    IF V_FEE < V_MIN THEN
        SET V_FEE = V_MIN;
    END IF;
    IF V_MAX IS NOT NULL AND V_FEE > V_MAX THEN
        SET V_FEE = V_MAX;
    END IF;
    RETURN V_FEE;
END@
