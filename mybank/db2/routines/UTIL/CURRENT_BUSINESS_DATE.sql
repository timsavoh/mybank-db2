-- Current business date from the bank control record.
CREATE OR REPLACE FUNCTION UTIL.CURRENT_BUSINESS_DATE ()
    RETURNS DATE
    LANGUAGE SQL
    SPECIFIC UTIL_CURRENT_BUSINESS_DATE
    READS SQL DATA
    NOT DETERMINISTIC
    NO EXTERNAL ACTION
    RETURN (SELECT BUSINESS_DATE FROM REF.BANK_CONTROL WHERE CONTROL_ID = 1)@
