-- 123456 -> 12-34-56. Accepts unpadded input (e.g. 90127 -> 09-01-27).
CREATE OR REPLACE FUNCTION UTIL.FORMAT_SORT_CODE (P_SORT_CODE VARCHAR(8))
    RETURNS CHAR(8)
    LANGUAGE SQL
    SPECIFIC UTIL_FORMAT_SORT_CODE
    DETERMINISTIC
    NO EXTERNAL ACTION
    CONTAINS SQL
BEGIN
    DECLARE V_S CHAR(6);
    SET V_S = LPAD(RTRIM(P_SORT_CODE), 6, '0');
    RETURN SUBSTR(V_S, 1, 2) || '-' || SUBSTR(V_S, 3, 2) || '-' || SUBSTR(V_S, 5, 2);
END@
