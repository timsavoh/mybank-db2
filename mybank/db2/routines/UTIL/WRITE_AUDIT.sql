-- Audit record stamped with the session's operator and channel global variables.
CREATE OR REPLACE PROCEDURE UTIL.WRITE_AUDIT (
    IN P_TABLE_NAME VARCHAR(40),
    IN P_KEY_VALUE  VARCHAR(60),
    IN P_ACTION     CHAR(1),
    IN P_DETAIL     VARCHAR(2000)
)
    LANGUAGE SQL
    SPECIFIC UTIL_WRITE_AUDIT
    MODIFIES SQL DATA
BEGIN
    INSERT INTO OPS.AUDIT_LOG (TABLE_NAME, KEY_VALUE, ACTION, DETAIL, CHANGED_BY, CHANNEL)
    VALUES (P_TABLE_NAME, P_KEY_VALUE, P_ACTION, P_DETAIL, UTIL.GV_OPERATOR, UTIL.GV_CHANNEL);
END@
