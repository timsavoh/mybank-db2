-- Developer debugging aid - NOT FOR PRODUCTION (SG 2018). Dumps everything about one account:
-- the account, holders, cards (PANs in clear!), holds and last 50 transactions with their GL
-- legs. Leaves a row in OPS.DEBUG_TRACE. e.g. CALL UTIL.DEBUG_DUMP_ACCOUNT(10432)
CREATE OR REPLACE PROCEDURE UTIL.DEBUG_DUMP_ACCOUNT (
    IN P_ACCOUNT_ID BIGINT
)
    LANGUAGE SQL
    SPECIFIC UTIL_DEBUG_DUMP_ACCOUNT
    DYNAMIC RESULT SETS 5
    MODIFIES SQL DATA
BEGIN
    DECLARE C_ACCOUNT CURSOR WITH RETURN FOR
        SELECT A.*, A.ROW_CHANGED_TS
          FROM ACCT.ACCOUNT A
         WHERE A.ACCOUNT_ID = P_ACCOUNT_ID;

    DECLARE C_HOLDERS CURSOR WITH RETURN FOR
        SELECT H.HOLDER_ROLE, C.*
          FROM ACCT.ACCOUNT_HOLDER H
          JOIN CUST.CUSTOMER C ON C.CUSTOMER_ID = H.CUSTOMER_ID
         WHERE H.ACCOUNT_ID = P_ACCOUNT_ID;

    DECLARE C_CARDS CURSOR WITH RETURN FOR
        SELECT * FROM CARD.CARD WHERE ACCOUNT_ID = P_ACCOUNT_ID;

    DECLARE C_HOLDS CURSOR WITH RETURN FOR
        SELECT * FROM ACCT.ACCOUNT_HOLD WHERE ACCOUNT_ID = P_ACCOUNT_ID ORDER BY HOLD_ID DESC;

    DECLARE C_TXNS CURSOR WITH RETURN FOR
        SELECT T.TXN_ID, T.BUSINESS_DATE, T.POSTED_TS, T.TXN_TYPE, T.AMOUNT, T.BALANCE_AFTER,
               T.DESCRIPTION, T.CORRELATION_ID, T.CHANNEL,
               G.GL_CODE, G.AMOUNT AS GL_AMOUNT
          FROM (SELECT * FROM TXN.POSTED_TXN
                 WHERE ACCOUNT_ID = P_ACCOUNT_ID
                 ORDER BY TXN_ID DESC
                 FETCH FIRST 50 ROWS ONLY) T
          LEFT JOIN GL.GL_ENTRY G ON G.TXN_ID = T.TXN_ID
         ORDER BY T.TXN_ID DESC, G.GL_ENTRY_ID
          WITH UR;

    INSERT INTO OPS.DEBUG_TRACE (SOURCE, KEY_VALUE, DETAIL)
    VALUES ('DEBUG_DUMP_ACCOUNT', RTRIM(CHAR(P_ACCOUNT_ID)),
            'channel=' || UTIL.GV_CHANNEL || ' operator=' || UTIL.GV_OPERATOR);

    -- SG: was useful for the 2018 hold mismatch - holds vs HOLD_AMOUNT
    -- SELECT A.HOLD_AMOUNT, (SELECT SUM(AMOUNT) FROM ACCT.ACCOUNT_HOLD WHERE ACCOUNT_ID = A.ACCOUNT_ID AND STATUS = 'A')
    --   FROM ACCT.ACCOUNT A WHERE A.ACCOUNT_ID = P_ACCOUNT_ID;

    OPEN C_ACCOUNT;
    OPEN C_HOLDERS;
    OPEN C_CARDS;
    OPEN C_HOLDS;
    OPEN C_TXNS;
END@
