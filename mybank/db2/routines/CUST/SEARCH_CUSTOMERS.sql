-- Customer search for the teller screen: any combination of filters, paged.
-- Built as dynamic SQL; unused filters bind a NULL marker so the USING list stays fixed.
-- Returns 1 result set; OUT total matching rows. Raises 75008 no filters / bad paging.
CREATE OR REPLACE PROCEDURE CUST.SEARCH_CUSTOMERS (
    IN  P_LAST_NAME     VARCHAR(50),
    IN  P_FIRST_NAME    VARCHAR(50),
    IN  P_POSTCODE      VARCHAR(8),
    IN  P_CUSTOMER_NO   CHAR(8),
    IN  P_DATE_OF_BIRTH DATE,
    IN  P_STATUS        CHAR(1),
    IN  P_PAGE_NO       INTEGER,
    IN  P_PAGE_SIZE     INTEGER,
    OUT P_TOTAL_ROWS    INTEGER
)
    LANGUAGE SQL
    SPECIFIC CUST_SEARCH_CUSTOMERS
    DYNAMIC RESULT SETS 1
    READS SQL DATA
BEGIN
    DECLARE V_WHERE     VARCHAR(2000) DEFAULT ' WHERE 1 = 1';
    DECLARE V_SQL       VARCHAR(4000);
    DECLARE V_COUNT_SQL VARCHAR(4000);
    DECLARE V_PAGE_NO   INTEGER;
    DECLARE V_PAGE_SIZE INTEGER;
    DECLARE V_FIRST_ROW INTEGER;
    DECLARE V_LAST_ROW  INTEGER;
    DECLARE V_LAST      VARCHAR(51);
    DECLARE V_FIRST     VARCHAR(51);
    DECLARE V_POSTCODE  VARCHAR(8);
    DECLARE V_CUST_NO   CHAR(8);
    DECLARE V_STATUS    CHAR(1);

    DECLARE S_SEARCH STATEMENT;
    DECLARE S_COUNT  STATEMENT;
    DECLARE C_SEARCH CURSOR WITH RETURN TO CLIENT FOR S_SEARCH;
    DECLARE C_COUNT  CURSOR FOR S_COUNT;

    SET V_PAGE_NO   = COALESCE(P_PAGE_NO, 1);
    SET V_PAGE_SIZE = COALESCE(P_PAGE_SIZE, 20);
    IF V_PAGE_NO < 1 OR V_PAGE_SIZE < 1 OR V_PAGE_SIZE > 100 THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Page number >= 1, page size 1 to 100';
    END IF;

    IF COALESCE(P_LAST_NAME, '') = '' AND COALESCE(P_FIRST_NAME, '') = ''
       AND COALESCE(P_POSTCODE, '') = '' AND COALESCE(P_CUSTOMER_NO, '') = ''
       AND P_DATE_OF_BIRTH IS NULL THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'At least one search filter is required';
    END IF;

    SET V_FIRST_ROW = (V_PAGE_NO - 1) * V_PAGE_SIZE + 1;
    SET V_LAST_ROW  = V_PAGE_NO * V_PAGE_SIZE;

    -- Name filters are "starts with", case-insensitive; postcode ignores spaces
    SET V_LAST     = CASE WHEN COALESCE(P_LAST_NAME, '') <> '' THEN UPPER(RTRIM(P_LAST_NAME)) || '%' END;
    SET V_FIRST    = CASE WHEN COALESCE(P_FIRST_NAME, '') <> '' THEN UPPER(RTRIM(P_FIRST_NAME)) || '%' END;
    SET V_POSTCODE = CASE WHEN COALESCE(P_POSTCODE, '') <> '' THEN UPPER(REPLACE(P_POSTCODE, ' ', '')) END;
    SET V_CUST_NO  = CASE WHEN COALESCE(P_CUSTOMER_NO, '') <> '' THEN UPPER(P_CUSTOMER_NO) END;
    SET V_STATUS   = CASE WHEN COALESCE(P_STATUS, '') <> '' THEN P_STATUS END;

    SET V_WHERE = V_WHERE ||
        CASE WHEN V_LAST IS NOT NULL
             THEN ' AND UPPER(C.LAST_NAME) LIKE ?'
             ELSE ' AND CAST(? AS VARCHAR(51)) IS NULL' END ||
        CASE WHEN V_FIRST IS NOT NULL
             THEN ' AND UPPER(C.FIRST_NAME) LIKE ?'
             ELSE ' AND CAST(? AS VARCHAR(51)) IS NULL' END ||
        CASE WHEN V_POSTCODE IS NOT NULL
             THEN ' AND EXISTS (SELECT 1 FROM CUST.ADDRESS A WHERE A.CUSTOMER_ID = C.CUSTOMER_ID' ||
                  ' AND A.VALID_TO IS NULL AND REPLACE(A.POSTCODE, '' '', '''') = ?)'
             ELSE ' AND CAST(? AS VARCHAR(8)) IS NULL' END ||
        CASE WHEN V_CUST_NO IS NOT NULL
             THEN ' AND C.CUSTOMER_NO = ?'
             ELSE ' AND CAST(? AS CHAR(8)) IS NULL' END ||
        CASE WHEN P_DATE_OF_BIRTH IS NOT NULL
             THEN ' AND C.DATE_OF_BIRTH = ?'
             ELSE ' AND CAST(? AS DATE) IS NULL' END ||
        CASE WHEN V_STATUS IS NOT NULL
             THEN ' AND C.STATUS = ?'
             ELSE ' AND CAST(? AS CHAR(1)) IS NULL' END;

    SET V_COUNT_SQL = 'SELECT COUNT(*) FROM CUST.CUSTOMER C' || V_WHERE || ' WITH UR';

    SET V_SQL =
        'SELECT CUSTOMER_ID, CUSTOMER_NO, TITLE, FIRST_NAME, LAST_NAME, DATE_OF_BIRTH, ' ||
        '       POSTCODE, STATUS, KYC_STATUS, SEGMENT, HOME_BRANCH_ID, ROW_NO ' ||
        '  FROM (SELECT C.CUSTOMER_ID, C.CUSTOMER_NO, C.TITLE, C.FIRST_NAME, C.LAST_NAME, ' ||
        '               C.DATE_OF_BIRTH, ' ||
        '               (SELECT MAX(A.POSTCODE) FROM CUST.ADDRESS A ' ||
        '                 WHERE A.CUSTOMER_ID = C.CUSTOMER_ID AND A.ADDRESS_TYPE = ''H'' ' ||
        '                   AND A.VALID_TO IS NULL) AS POSTCODE, ' ||
        '               C.STATUS, C.KYC_STATUS, C.SEGMENT, C.HOME_BRANCH_ID, ' ||
        '               ROW_NUMBER() OVER (ORDER BY C.LAST_NAME, C.FIRST_NAME, C.CUSTOMER_ID) AS ROW_NO ' ||
        '          FROM CUST.CUSTOMER C' || V_WHERE || ') X ' ||
        ' WHERE ROW_NO BETWEEN ? AND ? ' ||
        ' ORDER BY ROW_NO ' ||
        ' FETCH FIRST ' || RTRIM(CHAR(V_PAGE_SIZE)) || ' ROWS ONLY ' ||
        ' WITH UR';

    PREPARE S_COUNT FROM V_COUNT_SQL;
    OPEN C_COUNT USING V_LAST, V_FIRST, V_POSTCODE, V_CUST_NO, P_DATE_OF_BIRTH, V_STATUS;
    FETCH C_COUNT INTO P_TOTAL_ROWS;
    CLOSE C_COUNT;

    PREPARE S_SEARCH FROM V_SQL;
    OPEN C_SEARCH USING V_LAST, V_FIRST, V_POSTCODE, V_CUST_NO, P_DATE_OF_BIRTH, V_STATUS,
                        V_FIRST_ROW, V_LAST_ROW;
END@
