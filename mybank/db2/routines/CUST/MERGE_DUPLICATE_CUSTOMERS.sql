-- ONE-OFF DATA FIX INC0048213 (duplicate customers from the 2017 branch system cutover).
-- Moves everything from P_DUP_CUSTOMER_ID onto P_KEEP_CUSTOMER_ID and closes the duplicate.
-- Run once by DBA team Oct 2017. Should have been dropped afterwards.
CREATE OR REPLACE PROCEDURE CUST.MERGE_DUPLICATE_CUSTOMERS (
    IN  P_KEEP_CUSTOMER_ID BIGINT,
    IN  P_DUP_CUSTOMER_ID  BIGINT,
    IN  P_COMMIT           CHAR(1),
    OUT P_ROWS_MOVED       INTEGER
)
    LANGUAGE SQL
    SPECIFIC CUST_MERGE_DUPLICATE_CUSTOMERS
    MODIFIES SQL DATA
BEGIN
    DECLARE V_ROWS  INTEGER DEFAULT 0;
    DECLARE V_COUNT INTEGER DEFAULT 0;

    SET P_ROWS_MOVED = 0;

    SELECT COUNT(*) INTO V_COUNT
      FROM CUST.CUSTOMER
     WHERE CUSTOMER_ID IN (P_KEEP_CUSTOMER_ID, P_DUP_CUSTOMER_ID);

    IF V_COUNT <> 2 OR P_KEEP_CUSTOMER_ID = P_DUP_CUSTOMER_ID THEN
        SIGNAL SQLSTATE '75004' SET MESSAGE_TEXT = 'MERGE: both customers must exist';
    END IF;

    -- accounts
    UPDATE ACCT.ACCOUNT
       SET PRIMARY_CUSTOMER_ID = P_KEEP_CUSTOMER_ID
     WHERE PRIMARY_CUSTOMER_ID = P_DUP_CUSTOMER_ID;
    GET DIAGNOSTICS V_ROWS = ROW_COUNT;
    SET P_ROWS_MOVED = P_ROWS_MOVED + V_ROWS;

    -- holders: drop the dup where keep is already on the account, else re-point
    DELETE FROM ACCT.ACCOUNT_HOLDER H
     WHERE H.CUSTOMER_ID = P_DUP_CUSTOMER_ID
       AND EXISTS (SELECT 1 FROM ACCT.ACCOUNT_HOLDER K
                    WHERE K.ACCOUNT_ID = H.ACCOUNT_ID
                      AND K.CUSTOMER_ID = P_KEEP_CUSTOMER_ID);

    UPDATE ACCT.ACCOUNT_HOLDER
       SET CUSTOMER_ID = P_KEEP_CUSTOMER_ID
     WHERE CUSTOMER_ID = P_DUP_CUSTOMER_ID;
    GET DIAGNOSTICS V_ROWS = ROW_COUNT;
    SET P_ROWS_MOVED = P_ROWS_MOVED + V_ROWS;

    UPDATE CARD.CARD    SET CUSTOMER_ID = P_KEEP_CUSTOMER_ID WHERE CUSTOMER_ID = P_DUP_CUSTOMER_ID;
    UPDATE PAY.PAYEE    SET CUSTOMER_ID = P_KEEP_CUSTOMER_ID WHERE CUSTOMER_ID = P_DUP_CUSTOMER_ID;
    UPDATE LOAN.LOAN    SET CUSTOMER_ID = P_KEEP_CUSTOMER_ID WHERE CUSTOMER_ID = P_DUP_CUSTOMER_ID;
    UPDATE CUST.KYC_CHECK SET CUSTOMER_ID = P_KEEP_CUSTOMER_ID WHERE CUSTOMER_ID = P_DUP_CUSTOMER_ID;

    -- addresses: end-date the duplicate's, don't move them (per Ops, 12/10/2017)
    UPDATE CUST.ADDRESS
       SET VALID_TO = CURRENT DATE
     WHERE CUSTOMER_ID = P_DUP_CUSTOMER_ID
       AND VALID_TO IS NULL;

    -- contacts: keep's contact details win
    DELETE FROM CUST.CONTACT WHERE CUSTOMER_ID = P_DUP_CUSTOMER_ID;

    UPDATE CUST.CUSTOMER
       SET STATUS = 'C',
           CLOSED_DATE = CURRENT DATE
     WHERE CUSTOMER_ID = P_DUP_CUSTOMER_ID;

    INSERT INTO OPS.AUDIT_LOG (TABLE_NAME, KEY_VALUE, ACTION, DETAIL, CHANGED_BY, CHANNEL)
    VALUES ('CUST.CUSTOMER', RTRIM(CHAR(P_DUP_CUSTOMER_ID)), 'M',
            'Merged into ' || RTRIM(CHAR(P_KEEP_CUSTOMER_ID)) || ' INC0048213', 'DATAFIX', 'SYS');

    /* Original run was driven from the dedupe spreadsheet:
    CALL CUST.MERGE_DUPLICATE_CUSTOMERS(10233, 18841, 'Y', ?);
    CALL CUST.MERGE_DUPLICATE_CUSTOMERS(10412, 18902, 'Y', ?);
    CALL CUST.MERGE_DUPLICATE_CUSTOMERS(11007, 19155, 'Y', ?);
    -- ... 214 more, see INC0048213 attachment
    */

    IF P_COMMIT = 'Y' THEN
        COMMIT;
    ELSE
        ROLLBACK;   -- dry run
    END IF;
END@
