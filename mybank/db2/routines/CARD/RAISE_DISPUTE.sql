-- Customer disputes a settled card transaction (chargeback). Called by the app (web, teller).
-- P_AMOUNT NULL disputes the full amount. 120-day dispute window from the posting business date.
-- Raises 75005 no card for the transaction, 75007 already disputed, 75008 bad amount, 75009 not a card debit / out of window.
CREATE OR REPLACE PROCEDURE CARD.RAISE_DISPUTE (
    IN  P_TXN_ID     BIGINT,
    IN  P_REASON     VARCHAR(40),
    IN  P_AMOUNT     DECIMAL(15,2),
    OUT P_DISPUTE_ID BIGINT
)
    LANGUAGE SQL
    SPECIFIC CARD_RAISE_DISPUTE
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);

    DECLARE V_ACCOUNT_ID  BIGINT;
    DECLARE V_TXN_TYPE    CHAR(4);
    DECLARE V_TXN_AMOUNT  DECIMAL(15,2);
    DECLARE V_TXN_DATE    DATE;
    DECLARE V_CARD_ID     BIGINT;
    DECLARE V_CUSTOMER_ID BIGINT;
    DECLARE V_AMOUNT      DECIMAL(15,2);
    DECLARE V_TODAY       DATE;
    DECLARE V_OPEN        INTEGER DEFAULT 0;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.LOG_ERROR('CARD.RAISE_DISPUTE', V_SQLSTATE, V_SQLCODE, V_MSG,
             'TXN_ID=' || COALESCE(RTRIM(CHAR(P_TXN_ID)), 'NULL') ||
             ' AMOUNT=' || COALESCE(VARCHAR(P_AMOUNT), 'NULL'));
        RESIGNAL;
    END;

    SET P_DISPUTE_ID = NULL;

    IF P_REASON IS NULL OR LENGTH(RTRIM(P_REASON)) = 0 THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Dispute reason required';
    END IF;

    SELECT ACCOUNT_ID, TXN_TYPE, AMOUNT, BUSINESS_DATE
      INTO V_ACCOUNT_ID, V_TXN_TYPE, V_TXN_AMOUNT, V_TXN_DATE
      FROM TXN.POSTED_TXN
     WHERE TXN_ID = P_TXN_ID
      WITH UR;

    -- Older transactions may already have been moved by BATCH.ARCHIVE_AND_PURGE
    IF V_ACCOUNT_ID IS NULL THEN
        SELECT ACCOUNT_ID, TXN_TYPE, AMOUNT, BUSINESS_DATE
          INTO V_ACCOUNT_ID, V_TXN_TYPE, V_TXN_AMOUNT, V_TXN_DATE
          FROM TXN.POSTED_TXN_ARCHIVE
         WHERE TXN_ID = P_TXN_ID
          WITH UR;
    END IF;

    IF V_ACCOUNT_ID IS NULL OR V_TXN_TYPE <> 'CARD' OR V_TXN_AMOUNT >= 0 THEN
        SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'Only card payments can be disputed';
    END IF;

    SET V_TODAY = UTIL.CURRENT_BUSINESS_DATE();
    IF DAYS(V_TODAY) - DAYS(V_TXN_DATE) > 120 THEN
        SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'Dispute window of 120 days has passed';
    END IF;

    SET V_AMOUNT = COALESCE(P_AMOUNT, -V_TXN_AMOUNT);
    IF V_AMOUNT <= 0 OR V_AMOUNT > -V_TXN_AMOUNT THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Dispute amount must be between 0 and the transaction amount';
    END IF;

    SELECT COUNT(*) INTO V_OPEN
      FROM CARD.DISPUTE
     WHERE TXN_ID = P_TXN_ID
       AND STATUS = 'O';

    IF V_OPEN > 0 THEN
        SIGNAL SQLSTATE '75007' SET MESSAGE_TEXT = 'Transaction is already under dispute';
    END IF;

    -- The settling authorisation tells us which card; failing that, the newest card on the account
    SELECT CARD_ID INTO V_CARD_ID
      FROM CARD.AUTHORISATION
     WHERE SETTLED_TXN_ID = P_TXN_ID
     FETCH FIRST 1 ROW ONLY
      WITH UR;

    IF V_CARD_ID IS NULL THEN
        SELECT CARD_ID INTO V_CARD_ID
          FROM CARD.CARD
         WHERE ACCOUNT_ID = V_ACCOUNT_ID
         ORDER BY ISSUED_DATE DESC, CARD_ID DESC
         FETCH FIRST 1 ROW ONLY
          WITH UR;
    END IF;

    IF V_CARD_ID IS NULL THEN
        SIGNAL SQLSTATE '75005' SET MESSAGE_TEXT = 'No card found for this transaction';
    END IF;

    SELECT DISPUTE_ID INTO P_DISPUTE_ID
      FROM FINAL TABLE (INSERT INTO CARD.DISPUTE (TXN_ID, CARD_ID, AMOUNT, REASON, STATUS, RAISED_DATE)
                        VALUES (P_TXN_ID, V_CARD_ID, V_AMOUNT, UPPER(P_REASON), 'O', V_TODAY));

    SELECT PRIMARY_CUSTOMER_ID INTO V_CUSTOMER_ID
      FROM ACCT.ACCOUNT
     WHERE ACCOUNT_ID = V_ACCOUNT_ID;

    CALL UTIL.ENQUEUE_NOTIFICATION(V_CUSTOMER_ID, 'DISPUTE_RAISED',
         '{"dispute":' || RTRIM(CHAR(P_DISPUTE_ID)) || ',"amount":' || VARCHAR(V_AMOUNT) || '}');
END@
