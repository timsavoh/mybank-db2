-- Ad-hoc (early / over-) repayment from the loan's repayment account. Called by the app (web, teller).
-- Clears arrears first, then reduces outstanding principal; a loan repaid in full is marked P.
-- Raises 75001 insufficient funds, 75003 account, 75008 bad amount / more than outstanding, 75013 loan.
CREATE OR REPLACE PROCEDURE LOAN.MAKE_REPAYMENT (
    IN  P_LOAN_ID      BIGINT,
    IN  P_AMOUNT       DECIMAL(15,2),
    OUT P_OUTSTANDING  DECIMAL(15,2),
    OUT P_REPAYMENT_ID BIGINT
)
    LANGUAGE SQL
    SPECIFIC LOAN_MAKE_REPAYMENT
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);

    DECLARE V_STATUS        CHAR(1);
    DECLARE V_LOAN_ACCT_ID  BIGINT;
    DECLARE V_REPAY_ACCT_ID BIGINT;
    DECLARE V_OUTSTANDING   DECIMAL(15,2);
    DECLARE V_ARREARS       DECIMAL(15,2);
    DECLARE V_LOCK_ID       BIGINT;
    DECLARE V_LOAN_SORT     CHAR(6);
    DECLARE V_LOAN_ACCT_NO  CHAR(8);
    DECLARE V_CORR          BIGINT;
    DECLARE V_TXN_ID        BIGINT;
    DECLARE V_BALANCE       DECIMAL(15,2);
    DECLARE V_TODAY         DATE;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.LOG_ERROR('LOAN.MAKE_REPAYMENT', V_SQLSTATE, V_SQLCODE, V_MSG,
             'LOAN_ID=' || COALESCE(RTRIM(CHAR(P_LOAN_ID)), 'NULL') ||
             ' AMOUNT=' || COALESCE(VARCHAR(P_AMOUNT), 'NULL'));
        RESIGNAL;
    END;

    IF P_AMOUNT IS NULL OR P_AMOUNT <= 0 THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Repayment amount must be greater than zero';
    END IF;

    SELECT STATUS, LOAN_ACCOUNT_ID, REPAYMENT_ACCOUNT_ID, OUTSTANDING_PRINCIPAL, ARREARS_AMOUNT
      INTO V_STATUS, V_LOAN_ACCT_ID, V_REPAY_ACCT_ID, V_OUTSTANDING, V_ARREARS
      FROM LOAN.LOAN
     WHERE LOAN_ID = P_LOAN_ID
      WITH RS USE AND KEEP UPDATE LOCKS;

    IF V_STATUS IS NULL OR V_STATUS <> 'A' THEN
        SIGNAL SQLSTATE '75013' SET MESSAGE_TEXT = 'Loan not found or not active';
    END IF;

    IF P_AMOUNT > V_OUTSTANDING THEN
        SET V_MSG = 'Repayment exceeds outstanding balance of ' || VARCHAR(V_OUTSTANDING);
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = V_MSG;
    END IF;

    -- Same lock order as PAY.TRANSFER_FUNDS
    SELECT ACCOUNT_ID INTO V_LOCK_ID
      FROM ACCT.ACCOUNT
     WHERE ACCOUNT_ID = MIN(V_LOAN_ACCT_ID, V_REPAY_ACCT_ID)
      WITH RS USE AND KEEP UPDATE LOCKS;
    SELECT ACCOUNT_ID INTO V_LOCK_ID
      FROM ACCT.ACCOUNT
     WHERE ACCOUNT_ID = MAX(V_LOAN_ACCT_ID, V_REPAY_ACCT_ID)
      WITH RS USE AND KEEP UPDATE LOCKS;

    SELECT SORT_CODE, ACCOUNT_NO INTO V_LOAN_SORT, V_LOAN_ACCT_NO
      FROM ACCT.ACCOUNT
     WHERE ACCOUNT_ID = V_LOAN_ACCT_ID;

    SET V_CORR = NEXT VALUE FOR TXN.SEQ_CORRELATION;

    CALL UTIL.POST_LEDGER_ENTRY(V_REPAY_ACCT_ID, -P_AMOUNT, 'LOAN', 'Loan repayment',
         'LOAN ' || RTRIM(CHAR(P_LOAN_ID)), '1900', V_CORR, NULL, 'N',
         'MYBANK PERSONAL LOAN', V_LOAN_SORT, V_LOAN_ACCT_NO, NULL, NULL, V_TXN_ID, V_BALANCE);

    CALL UTIL.POST_LEDGER_ENTRY(V_LOAN_ACCT_ID, P_AMOUNT, 'LOAN', 'Repayment - thank you',
         'LOAN ' || RTRIM(CHAR(P_LOAN_ID)), '1900', V_CORR, NULL, 'N',
         NULL, NULL, NULL, NULL, NULL, V_TXN_ID, V_BALANCE);

    SET P_OUTSTANDING = V_OUTSTANDING - P_AMOUNT;
    SET V_TODAY = UTIL.CURRENT_BUSINESS_DATE();

    UPDATE LOAN.LOAN
       SET OUTSTANDING_PRINCIPAL = P_OUTSTANDING,
           ARREARS_AMOUNT = MAX(0, ARREARS_AMOUNT - P_AMOUNT),
           MISSED_PAYMENTS = CASE WHEN ARREARS_AMOUNT <= P_AMOUNT THEN 0 ELSE MISSED_PAYMENTS END,
           STATUS = CASE WHEN P_OUTSTANDING = 0 THEN 'P' ELSE STATUS END,
           NEXT_DUE_DATE = CASE WHEN P_OUTSTANDING = 0 THEN NULL ELSE NEXT_DUE_DATE END
     WHERE LOAN_ID = P_LOAN_ID;

    IF P_OUTSTANDING = 0 THEN
        UPDATE LOAN.REPAYMENT_SCHEDULE
           SET STATUS = 'P'
         WHERE LOAN_ID = P_LOAN_ID
           AND STATUS = 'D';
    END IF;

    SELECT REPAYMENT_ID INTO P_REPAYMENT_ID
      FROM FINAL TABLE (INSERT INTO LOAN.REPAYMENT (LOAN_ID, AMOUNT, PAID_DATE, REPAYMENT_TYPE, TXN_ID)
                        VALUES (P_LOAN_ID, P_AMOUNT, V_TODAY, 'A', V_TXN_ID));
END@
