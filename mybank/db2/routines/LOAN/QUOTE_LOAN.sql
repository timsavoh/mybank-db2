-- Personal loan quote: monthly payment, total interest and the full amortisation schedule
-- (result set, built in SESSION.LOAN_SCHEDULE). Called by the app's loan calculator. Nothing is stored.
-- Interest is charged monthly on the reducing balance; the final instalment absorbs rounding.
-- Raises 75008 principal 1,000-50,000, rate 0-30%, term 12-84 months.
CREATE OR REPLACE PROCEDURE LOAN.QUOTE_LOAN (
    IN  P_PRINCIPAL       DECIMAL(15,2),
    IN  P_ANNUAL_RATE     DECIMAL(7,4),
    IN  P_TERM_MONTHS     SMALLINT,
    OUT P_MONTHLY_PAYMENT DECIMAL(15,2),
    OUT P_TOTAL_INTEREST  DECIMAL(15,2)
)
    LANGUAGE SQL
    SPECIFIC LOAN_QUOTE_LOAN
    DYNAMIC RESULT SETS 1
    MODIFIES SQL DATA
BEGIN
    DECLARE V_START     DATE;
    DECLARE V_N         SMALLINT DEFAULT 1;
    DECLARE V_BALANCE   DECIMAL(15,2);
    DECLARE V_INTEREST  DECIMAL(15,2);
    DECLARE V_PRINCIPAL DECIMAL(15,2);
    DECLARE V_PAYMENT   DECIMAL(15,2);

    IF P_PRINCIPAL IS NULL OR P_PRINCIPAL NOT BETWEEN 1000 AND 50000 THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Loan amount must be between 1,000 and 50,000';
    END IF;
    IF P_ANNUAL_RATE IS NULL OR P_ANNUAL_RATE NOT BETWEEN 0 AND 30 THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Annual rate must be between 0 and 30 percent';
    END IF;
    IF P_TERM_MONTHS IS NULL OR P_TERM_MONTHS NOT BETWEEN 12 AND 84 THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Term must be between 12 and 84 months';
    END IF;

    DECLARE GLOBAL TEMPORARY TABLE SESSION.LOAN_SCHEDULE (
        INSTALMENT_NO SMALLINT      NOT NULL,
        DUE_DATE      DATE          NOT NULL,
        PAYMENT       DECIMAL(15,2) NOT NULL,
        INTEREST      DECIMAL(15,2) NOT NULL,
        PRINCIPAL     DECIMAL(15,2) NOT NULL,
        BALANCE_AFTER DECIMAL(15,2) NOT NULL
    ) ON COMMIT PRESERVE ROWS NOT LOGGED WITH REPLACE IN USERTEMP8K;

    SET V_START = UTIL.CURRENT_BUSINESS_DATE();
    SET P_MONTHLY_PAYMENT = LOAN.MONTHLY_PAYMENT(P_PRINCIPAL, P_ANNUAL_RATE, P_TERM_MONTHS);
    SET P_TOTAL_INTEREST = 0;
    SET V_BALANCE = P_PRINCIPAL;

    L_SCHEDULE:
    WHILE V_N <= P_TERM_MONTHS DO
        SET V_INTEREST = ROUND(V_BALANCE * P_ANNUAL_RATE / 1200, 2);
        IF V_N = P_TERM_MONTHS THEN
            -- Final instalment clears whatever is left after rounding
            SET V_PRINCIPAL = V_BALANCE;
        ELSE
            SET V_PRINCIPAL = P_MONTHLY_PAYMENT - V_INTEREST;
        END IF;
        SET V_PAYMENT = V_PRINCIPAL + V_INTEREST;
        SET V_BALANCE = V_BALANCE - V_PRINCIPAL;
        SET P_TOTAL_INTEREST = P_TOTAL_INTEREST + V_INTEREST;

        INSERT INTO SESSION.LOAN_SCHEDULE
               (INSTALMENT_NO, DUE_DATE, PAYMENT, INTEREST, PRINCIPAL, BALANCE_AFTER)
        VALUES (V_N, ADD_MONTHS(V_START, V_N), V_PAYMENT, V_INTEREST, V_PRINCIPAL, V_BALANCE);

        SET V_N = V_N + 1;
    END WHILE L_SCHEDULE;

    BEGIN
        DECLARE C_SCHEDULE CURSOR WITH RETURN TO CLIENT FOR
            SELECT INSTALMENT_NO,
                   DUE_DATE,
                   PAYMENT,
                   INTEREST,
                   PRINCIPAL,
                   BALANCE_AFTER,
                   SUM(INTEREST) OVER (ORDER BY INSTALMENT_NO) AS CUMULATIVE_INTEREST
              FROM SESSION.LOAN_SCHEDULE
             ORDER BY INSTALMENT_NO;
        OPEN C_SCHEDULE;
    END;
END@
