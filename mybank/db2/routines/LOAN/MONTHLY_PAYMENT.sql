-- Level monthly instalment for an annuity loan: P * r / (1 - (1 + r)^-n), r = annual % / 1200.
-- Used by LOAN.QUOTE_LOAN and LOAN.ORIGINATE_LOAN. Worked in DOUBLE, rounded half-up to pence.
CREATE OR REPLACE FUNCTION LOAN.MONTHLY_PAYMENT (
    P_PRINCIPAL   DECIMAL(15,2),
    P_ANNUAL_RATE DECIMAL(7,4),
    P_TERM_MONTHS SMALLINT
)
    RETURNS DECIMAL(15,2)
    LANGUAGE SQL
    SPECIFIC LOAN_MONTHLY_PAYMENT
    DETERMINISTIC
    NO EXTERNAL ACTION
    CONTAINS SQL
BEGIN
    DECLARE V_R DOUBLE;

    IF P_PRINCIPAL IS NULL OR P_ANNUAL_RATE IS NULL OR COALESCE(P_TERM_MONTHS, 0) <= 0 THEN
        RETURN NULL;
    END IF;

    IF P_ANNUAL_RATE = 0 THEN
        RETURN ROUND(P_PRINCIPAL / P_TERM_MONTHS, 2);
    END IF;

    SET V_R = DOUBLE(P_ANNUAL_RATE) / 1200;
    -- Via DECIMAL(31,8) before ROUND: DECIMAL(ROUND(double, 2)) can truncate 123.449999 to 123.44
    RETURN ROUND(DECIMAL(DOUBLE(P_PRINCIPAL) * V_R / (1 - POWER(1 + V_R, -P_TERM_MONTHS)), 31, 8), 2);
END@
