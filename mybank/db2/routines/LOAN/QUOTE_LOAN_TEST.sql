-- Copy of LOAN.QUOTE_LOAN used to try out the new rounding on the final instalment. Rate is
-- hard-coded to the 2018 headline rate if not passed. Returns the schedule as a result set.
CREATE OR REPLACE PROCEDURE LOAN.QUOTE_LOAN_TEST (
    IN  P_PRINCIPAL   DECIMAL(15,2),
    IN  P_TERM_MONTHS SMALLINT,
    IN  P_RATE        DECIMAL(7,4),
    OUT P_MONTHLY     DECIMAL(15,2),
    OUT P_TOTAL_REPAY DECIMAL(15,2)
)
    LANGUAGE SQL
    SPECIFIC LOAN_QUOTE_LOAN_TEST
    DYNAMIC RESULT SETS 1
    MODIFIES SQL DATA
BEGIN
    DECLARE V_RATE     DECIMAL(7,4);
    DECLARE V_R        DOUBLE;
    DECLARE V_BALANCE  DECIMAL(15,2);
    DECLARE V_INTEREST DECIMAL(15,2);
    DECLARE V_PRIN     DECIMAL(15,2);
    DECLARE V_PAYMENT  DECIMAL(15,2);
    DECLARE V_N        SMALLINT DEFAULT 1;
    DECLARE V_DUE      DATE;

    SET V_RATE = VALUE(P_RATE, 6.9000);     -- 2018 headline rate
    SET V_R = V_RATE / 1200;

    DECLARE GLOBAL TEMPORARY TABLE SESSION.QUOTE_TEST (
        INSTALMENT_NO SMALLINT,
        DUE_DATE      DATE,
        PAYMENT       DECIMAL(15,2),
        INTEREST      DECIMAL(15,2),
        PRINCIPAL     DECIMAL(15,2),
        BALANCE_AFTER DECIMAL(15,2)
    ) ON COMMIT PRESERVE ROWS NOT LOGGED WITH REPLACE;

    IF V_R = 0 THEN
        SET P_MONTHLY = ROUND(P_PRINCIPAL / P_TERM_MONTHS, 2);
    ELSE
        SET P_MONTHLY = ROUND(P_PRINCIPAL * V_R / (1 - POWER(1 + V_R, -P_TERM_MONTHS)), 2);
    END IF;

    SET V_BALANCE = P_PRINCIPAL;
    SET V_DUE = CURRENT DATE;
    SET P_TOTAL_REPAY = 0;

    SCHED_LOOP:
    WHILE V_N <= P_TERM_MONTHS DO
        SET V_DUE = CURRENT DATE + V_N MONTHS;
        SET V_INTEREST = ROUND(V_BALANCE * V_R, 2);
        IF V_N = P_TERM_MONTHS THEN
            -- new rounding: last payment clears the balance
            SET V_PRIN = V_BALANCE;
        ELSE
            SET V_PRIN = P_MONTHLY - V_INTEREST;
        END IF;
        SET V_PAYMENT = V_PRIN + V_INTEREST;
        SET V_BALANCE = V_BALANCE - V_PRIN;

        INSERT INTO SESSION.QUOTE_TEST VALUES (V_N, V_DUE, V_PAYMENT, V_INTEREST, V_PRIN, V_BALANCE);
        SET P_TOTAL_REPAY = P_TOTAL_REPAY + V_PAYMENT;
        -- INSERT INTO OPS.DEBUG_TRACE (SOURCE, KEY_VALUE, DETAIL) VALUES ('QUOTE_TEST', CHAR(V_N), CHAR(V_BALANCE));
        SET V_N = V_N + 1;
    END WHILE SCHED_LOOP;

    BEGIN
        DECLARE C_SCHEDULE CURSOR WITH RETURN FOR
            SELECT * FROM SESSION.QUOTE_TEST ORDER BY INSTALMENT_NO;
        OPEN C_SCHEDULE;
    END;
END@
