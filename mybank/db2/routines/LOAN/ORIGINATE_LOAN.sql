-- Books a personal loan: opens a LON001 loan account, writes LOAN.LOAN and the repayment schedule,
-- and disburses (loan account debited, repayment current account credited, one correlation id, GL 1900).
-- Called by the app after the customer accepts a LOAN.QUOTE_LOAN quote.
-- Raises 75002/75003 account, 75004 customer, 75008 amount/rate/term, 75009 eligibility.
CREATE OR REPLACE PROCEDURE LOAN.ORIGINATE_LOAN (
    IN  P_CUSTOMER_ID          BIGINT,
    IN  P_REPAYMENT_ACCOUNT_ID BIGINT,
    IN  P_PRINCIPAL            DECIMAL(15,2),
    IN  P_ANNUAL_RATE          DECIMAL(7,4),
    IN  P_TERM_MONTHS          SMALLINT,
    OUT P_LOAN_ID              BIGINT,
    OUT P_LOAN_ACCOUNT_ID      BIGINT,
    OUT P_MONTHLY_PAYMENT      DECIMAL(15,2)
)
    LANGUAGE SQL
    SPECIFIC LOAN_ORIGINATE_LOAN
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);

    DECLARE V_PRODUCT_CODE CHAR(6) DEFAULT 'LON001';
    DECLARE V_TODAY        DATE;
    DECLARE V_CUST_STATUS  CHAR(1);
    DECLARE V_KYC_STATUS   CHAR(1);
    DECLARE V_DOB          DATE;
    DECLARE V_LAST_NAME    VARCHAR(50);
    DECLARE V_MIN_AGE      SMALLINT;
    DECLARE V_PRODUCT_TYPE CHAR(3);
    DECLARE V_IS_HOLDER    INTEGER DEFAULT 0;
    DECLARE V_SORT_CODE    CHAR(6);
    DECLARE V_BRANCH_ID    SMALLINT;
    DECLARE V_REPAY_ACCT   CHAR(8);
    DECLARE V_SEQ          INTEGER;
    DECLARE V_BASE         CHAR(7);
    DECLARE V_ACCOUNT_NO   CHAR(8);
    DECLARE V_CORR         BIGINT;
    DECLARE V_TXN_ID       BIGINT;
    DECLARE V_BALANCE      DECIMAL(15,2);

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.LOG_ERROR('LOAN.ORIGINATE_LOAN', V_SQLSTATE, V_SQLCODE, V_MSG,
             'CUSTOMER=' || COALESCE(RTRIM(CHAR(P_CUSTOMER_ID)), 'NULL') ||
             ' REPAY_ACCOUNT=' || COALESCE(RTRIM(CHAR(P_REPAYMENT_ACCOUNT_ID)), 'NULL') ||
             ' PRINCIPAL=' || COALESCE(VARCHAR(P_PRINCIPAL), 'NULL'));
        RESIGNAL;
    END;

    IF P_PRINCIPAL IS NULL OR P_PRINCIPAL NOT BETWEEN 1000 AND 50000 THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Loan amount must be between 1,000 and 50,000';
    END IF;
    IF P_ANNUAL_RATE IS NULL OR P_ANNUAL_RATE NOT BETWEEN 0 AND 30 THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Annual rate must be between 0 and 30 percent';
    END IF;
    IF P_TERM_MONTHS IS NULL OR P_TERM_MONTHS NOT BETWEEN 12 AND 84 THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Term must be between 12 and 84 months';
    END IF;

    SET V_TODAY = UTIL.CURRENT_BUSINESS_DATE();

    SELECT STATUS, KYC_STATUS, DATE_OF_BIRTH, LAST_NAME
      INTO V_CUST_STATUS, V_KYC_STATUS, V_DOB, V_LAST_NAME
      FROM CUST.CUSTOMER
     WHERE CUSTOMER_ID = P_CUSTOMER_ID;

    IF V_CUST_STATUS IS NULL OR V_CUST_STATUS <> 'A' THEN
        SIGNAL SQLSTATE '75004' SET MESSAGE_TEXT = 'Customer not found or not active';
    END IF;
    IF V_KYC_STATUS <> 'V' THEN
        SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'Customer identity not verified (KYC)';
    END IF;

    SELECT MIN_AGE INTO V_MIN_AGE FROM REF.PRODUCT WHERE PRODUCT_CODE = V_PRODUCT_CODE WITH UR;
    IF V_DOB + V_MIN_AGE YEARS > V_TODAY THEN
        SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'Customer is below the minimum age for a loan';
    END IF;

    CALL UTIL.CHECK_ACCOUNT_STATUS(P_REPAYMENT_ACCOUNT_ID, 'Y');

    SELECT P.PRODUCT_TYPE, A.SORT_CODE, A.BRANCH_ID, A.ACCOUNT_NO,
           CASE WHEN A.PRIMARY_CUSTOMER_ID = P_CUSTOMER_ID
                  OR EXISTS (SELECT 1 FROM ACCT.ACCOUNT_HOLDER H
                              WHERE H.ACCOUNT_ID = A.ACCOUNT_ID
                                AND H.CUSTOMER_ID = P_CUSTOMER_ID)
                THEN 1 ELSE 0 END
      INTO V_PRODUCT_TYPE, V_SORT_CODE, V_BRANCH_ID, V_REPAY_ACCT, V_IS_HOLDER
      FROM ACCT.ACCOUNT A
      JOIN REF.PRODUCT P ON P.PRODUCT_CODE = A.PRODUCT_CODE
     WHERE A.ACCOUNT_ID = P_REPAYMENT_ACCOUNT_ID;

    IF V_IS_HOLDER = 0 OR V_PRODUCT_TYPE <> 'CUR' THEN
        SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'Repayments must come from the customer''s current account';
    END IF;

    -- Open the loan account at the repayment account's branch.
    -- (Pre-dates ACCT.OPEN_ACCOUNT; nobody has moved it over.)
    SET V_SEQ = NEXT VALUE FOR ACCT.SEQ_ACCOUNT_NO;
    SET V_BASE = RIGHT(DIGITS(V_SEQ), 7);
    SET V_ACCOUNT_NO = V_BASE || UTIL.ACCOUNT_CHECK_DIGIT(V_BASE);

    SELECT ACCOUNT_ID INTO P_LOAN_ACCOUNT_ID
      FROM FINAL TABLE (INSERT INTO ACCT.ACCOUNT
                            (SORT_CODE, ACCOUNT_NO, PRODUCT_CODE, BRANCH_ID, PRIMARY_CUSTOMER_ID,
                             ACCOUNT_NAME, STATUS, OVERDRAFT_LIMIT, OPENED_DATE)
                        VALUES (V_SORT_CODE, V_ACCOUNT_NO, V_PRODUCT_CODE, V_BRANCH_ID, P_CUSTOMER_ID,
                                'PERSONAL LOAN ' || UPPER(V_LAST_NAME), 'A', 0, V_TODAY));

    INSERT INTO ACCT.ACCOUNT_HOLDER (ACCOUNT_ID, CUSTOMER_ID, HOLDER_ROLE, ADDED_DATE)
    VALUES (P_LOAN_ACCOUNT_ID, P_CUSTOMER_ID, 'P', V_TODAY);

    SET P_MONTHLY_PAYMENT = LOAN.MONTHLY_PAYMENT(P_PRINCIPAL, P_ANNUAL_RATE, P_TERM_MONTHS);

    SELECT LOAN_ID INTO P_LOAN_ID
      FROM FINAL TABLE (INSERT INTO LOAN.LOAN
                            (LOAN_ACCOUNT_ID, REPAYMENT_ACCOUNT_ID, CUSTOMER_ID, PRINCIPAL,
                             ANNUAL_RATE, TERM_MONTHS, MONTHLY_PAYMENT, START_DATE, NEXT_DUE_DATE,
                             OUTSTANDING_PRINCIPAL, STATUS)
                        VALUES (P_LOAN_ACCOUNT_ID, P_REPAYMENT_ACCOUNT_ID, P_CUSTOMER_ID, P_PRINCIPAL,
                                P_ANNUAL_RATE, P_TERM_MONTHS, P_MONTHLY_PAYMENT, V_TODAY,
                                ADD_MONTHS(V_TODAY, 1), P_PRINCIPAL, 'A'));

    -- Whole schedule in one statement. Same arithmetic as LOAN.QUOTE_LOAN: interest on the
    -- opening balance rounded to pence, level payment, last instalment clears the balance.
    INSERT INTO LOAN.REPAYMENT_SCHEDULE
           (LOAN_ID, INSTALMENT_NO, DUE_DATE, PAYMENT, INTEREST, PRINCIPAL, BALANCE_AFTER, STATUS)
    WITH SCHED (INSTALMENT_NO, INTEREST, PRINCIPAL, BALANCE_AFTER) AS (
        SELECT SMALLINT(0), CAST(0 AS DECIMAL(15,2)), CAST(0 AS DECIMAL(15,2)),
               CAST(P_PRINCIPAL AS DECIMAL(15,2))
          FROM SYSIBM.SYSDUMMY1
        UNION ALL
        SELECT SMALLINT(S.INSTALMENT_NO + 1),
               CAST(ROUND(S.BALANCE_AFTER * P_ANNUAL_RATE / 1200, 2) AS DECIMAL(15,2)),
               CAST(CASE WHEN S.INSTALMENT_NO + 1 = P_TERM_MONTHS
                         THEN S.BALANCE_AFTER
                         ELSE P_MONTHLY_PAYMENT - ROUND(S.BALANCE_AFTER * P_ANNUAL_RATE / 1200, 2)
                    END AS DECIMAL(15,2)),
               CAST(CASE WHEN S.INSTALMENT_NO + 1 = P_TERM_MONTHS
                         THEN 0
                         ELSE S.BALANCE_AFTER - P_MONTHLY_PAYMENT
                              + ROUND(S.BALANCE_AFTER * P_ANNUAL_RATE / 1200, 2)
                    END AS DECIMAL(15,2))
          FROM SCHED S
         WHERE S.INSTALMENT_NO < P_TERM_MONTHS
    )
    SELECT P_LOAN_ID, INSTALMENT_NO, ADD_MONTHS(V_TODAY, INSTALMENT_NO),
           PRINCIPAL + INTEREST, INTEREST, PRINCIPAL, BALANCE_AFTER, 'D'
      FROM SCHED
     WHERE INSTALMENT_NO > 0;

    -- Disbursement: both legs under one correlation id through suspense 1900
    SET V_CORR = NEXT VALUE FOR TXN.SEQ_CORRELATION;

    CALL UTIL.POST_LEDGER_ENTRY(P_LOAN_ACCOUNT_ID, -P_PRINCIPAL, 'LOAN', 'Loan drawdown',
         'LOAN ' || RTRIM(CHAR(P_LOAN_ID)), '1900', V_CORR, NULL, 'Y',
         NULL, V_SORT_CODE, V_REPAY_ACCT, NULL, NULL, V_TXN_ID, V_BALANCE);

    CALL UTIL.POST_LEDGER_ENTRY(P_REPAYMENT_ACCOUNT_ID, P_PRINCIPAL, 'LOAN', 'Personal loan advance',
         'LOAN ' || RTRIM(CHAR(P_LOAN_ID)), '1900', V_CORR, NULL, 'N',
         'MYBANK PERSONAL LOAN', V_SORT_CODE, V_ACCOUNT_NO, NULL, NULL, V_TXN_ID, V_BALANCE);

    CALL UTIL.WRITE_AUDIT('LOAN.LOAN', RTRIM(CHAR(P_LOAN_ID)), 'I',
         'PRINCIPAL ' || VARCHAR(P_PRINCIPAL) || ' RATE ' || VARCHAR(P_ANNUAL_RATE) ||
         ' TERM ' || RTRIM(CHAR(P_TERM_MONTHS)) || ' PAYMENT ' || VARCHAR(P_MONTHLY_PAYMENT));

    CALL UTIL.ENQUEUE_NOTIFICATION(P_CUSTOMER_ID, 'LOAN_ORIGINATED',
         '{"loan":' || RTRIM(CHAR(P_LOAN_ID)) || ',"amount":' || VARCHAR(P_PRINCIPAL) ||
         ',"monthly":' || VARCHAR(P_MONTHLY_PAYMENT) || ',"account":"' || V_ACCOUNT_NO || '"}');
END@
