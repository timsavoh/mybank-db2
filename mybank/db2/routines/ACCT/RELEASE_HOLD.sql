-- Releases an active hold (status R). HOLD_AMOUNT is maintained by TRG_HOLD_RELEASED.
-- Called by the app (teller/ops). P_ACCOUNT_ID optional cross-check.
-- Raises 75008 hold not found (or not on that account), 75009 hold no longer active.
CREATE OR REPLACE PROCEDURE ACCT.RELEASE_HOLD (
    IN  P_HOLD_ID         BIGINT,
    IN  P_ACCOUNT_ID      BIGINT,
    OUT P_RELEASED_AMOUNT DECIMAL(15,2)
)
    LANGUAGE SQL
    SPECIFIC ACCT_RELEASE_HOLD
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE CHAR(5);
    DECLARE V_SQLCODE  INTEGER;
    DECLARE V_MSG      VARCHAR(1000);
    DECLARE V_TEXT     VARCHAR(70);
    DECLARE V_ROWS     INTEGER DEFAULT 0;
    DECLARE V_STATUS   CHAR(1);
    DECLARE V_ACCOUNT_ID BIGINT;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.LOG_ERROR('ACCT.RELEASE_HOLD', V_SQLSTATE, V_SQLCODE, V_MSG,
                            'HOLD_ID=' || COALESCE(RTRIM(CHAR(P_HOLD_ID)), 'NULL'));
        RESIGNAL;
    END;

    SET P_RELEASED_AMOUNT = 0;

    UPDATE ACCT.ACCOUNT_HOLD
       SET STATUS = 'R',
           RELEASED_TS = CURRENT TIMESTAMP
     WHERE HOLD_ID = P_HOLD_ID
       AND STATUS = 'A'
       AND (P_ACCOUNT_ID IS NULL OR ACCOUNT_ID = P_ACCOUNT_ID);
    GET DIAGNOSTICS V_ROWS = ROW_COUNT;

    IF V_ROWS = 0 THEN
        SELECT STATUS INTO V_STATUS
          FROM ACCT.ACCOUNT_HOLD
         WHERE HOLD_ID = P_HOLD_ID
           AND (P_ACCOUNT_ID IS NULL OR ACCOUNT_ID = P_ACCOUNT_ID);

        IF V_STATUS IS NULL THEN
            SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Hold not found';
        END IF;
        SET V_TEXT = 'Hold is no longer active (status ' || V_STATUS || ')';
        SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = V_TEXT;
    END IF;

    SELECT AMOUNT, ACCOUNT_ID
      INTO P_RELEASED_AMOUNT, V_ACCOUNT_ID
      FROM ACCT.ACCOUNT_HOLD
     WHERE HOLD_ID = P_HOLD_ID;

    CALL UTIL.WRITE_AUDIT('ACCT.ACCOUNT_HOLD', RTRIM(CHAR(P_HOLD_ID)), 'U',
                          'Released ' || VARCHAR(P_RELEASED_AMOUNT) || ' on ' || RTRIM(CHAR(V_ACCOUNT_ID)));
END@
