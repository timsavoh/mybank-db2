-- Paged transaction history (newest first) with a running balance, including the
-- archive for older periods. Called by the app. Returns 1 result set; OUT opening balance
-- and total rows. Raises 75002 account not found, 75008 bad date range or paging.
CREATE OR REPLACE PROCEDURE ACCT.GET_TRANSACTIONS (
    IN  P_ACCOUNT_ID      BIGINT,
    IN  P_FROM_DATE       DATE,
    IN  P_TO_DATE         DATE,
    IN  P_PAGE_NO         INTEGER,
    IN  P_PAGE_SIZE       INTEGER,
    OUT P_OPENING_BALANCE DECIMAL(15,2),
    OUT P_TOTAL_ROWS      INTEGER
)
    LANGUAGE SQL
    SPECIFIC ACCT_GET_TRANSACTIONS
    DYNAMIC RESULT SETS 1
    READS SQL DATA
BEGIN
    DECLARE V_LEDGER    DECIMAL(15,2);
    DECLARE V_SINCE     DECIMAL(15,2);
    DECLARE V_FROM      DATE;
    DECLARE V_TO        DATE;
    DECLARE V_PAGE_NO   INTEGER;
    DECLARE V_PAGE_SIZE INTEGER;
    DECLARE V_FIRST_ROW INTEGER;
    DECLARE V_LAST_ROW  INTEGER;

    DECLARE C_TXN CURSOR WITH RETURN TO CLIENT FOR
        WITH HIST (TXN_ID, BUSINESS_DATE, POSTED_TS, TXN_TYPE, DESCRIPTION, REFERENCE,
                   COUNTERPARTY_NAME, AMOUNT, BALANCE_AFTER, CHANNEL) AS (
            SELECT TXN_ID, BUSINESS_DATE, POSTED_TS, TXN_TYPE, DESCRIPTION, REFERENCE,
                   COUNTERPARTY_NAME, AMOUNT, BALANCE_AFTER, CHANNEL
              FROM TXN.POSTED_TXN
             WHERE ACCOUNT_ID = P_ACCOUNT_ID
               AND BUSINESS_DATE BETWEEN V_FROM AND V_TO
            UNION ALL
            SELECT TXN_ID, BUSINESS_DATE, POSTED_TS, TXN_TYPE, DESCRIPTION, REFERENCE,
                   COUNTERPARTY_NAME, AMOUNT, BALANCE_AFTER, CHANNEL
              FROM TXN.POSTED_TXN_ARCHIVE
             WHERE ACCOUNT_ID = P_ACCOUNT_ID
               AND BUSINESS_DATE BETWEEN V_FROM AND V_TO
        ),
        RUNNING AS (
            SELECT H.*,
                   P_OPENING_BALANCE + SUM(H.AMOUNT) OVER (ORDER BY H.BUSINESS_DATE, H.TXN_ID
                                                           ROWS UNBOUNDED PRECEDING) AS RUNNING_BALANCE,
                   ROW_NUMBER() OVER (ORDER BY H.BUSINESS_DATE DESC, H.TXN_ID DESC) AS ROW_NO
              FROM HIST H
        )
        SELECT TXN_ID, BUSINESS_DATE, POSTED_TS, TXN_TYPE, DESCRIPTION, REFERENCE,
               COUNTERPARTY_NAME,
               CASE WHEN AMOUNT > 0 THEN AMOUNT END  AS PAID_IN,
               CASE WHEN AMOUNT < 0 THEN -AMOUNT END AS PAID_OUT,
               AMOUNT, RUNNING_BALANCE, BALANCE_AFTER, CHANNEL, ROW_NO
          FROM RUNNING
         WHERE ROW_NO BETWEEN V_FIRST_ROW AND V_LAST_ROW
         ORDER BY ROW_NO
          WITH UR;

    SET V_TO        = COALESCE(P_TO_DATE, UTIL.POSTING_DATE());
    SET V_FROM      = COALESCE(P_FROM_DATE, V_TO - 1 MONTH);
    SET V_PAGE_NO   = COALESCE(P_PAGE_NO, 1);
    SET V_PAGE_SIZE = COALESCE(P_PAGE_SIZE, 50);

    IF V_FROM > V_TO THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'From date is after to date';
    END IF;
    IF V_PAGE_NO < 1 OR V_PAGE_SIZE NOT BETWEEN 1 AND 500 THEN
        SIGNAL SQLSTATE '75008' SET MESSAGE_TEXT = 'Page number >= 1, page size 1 to 500';
    END IF;

    SELECT LEDGER_BALANCE INTO V_LEDGER
      FROM ACCT.ACCOUNT
     WHERE ACCOUNT_ID = P_ACCOUNT_ID
      WITH UR;
    IF V_LEDGER IS NULL THEN
        SIGNAL SQLSTATE '75002' SET MESSAGE_TEXT = 'Account not found';
    END IF;

    -- Opening balance = today's ledger less everything posted on or after the from date
    SELECT COALESCE(SUM(AMOUNT), 0) INTO V_SINCE
      FROM (SELECT AMOUNT FROM TXN.POSTED_TXN
             WHERE ACCOUNT_ID = P_ACCOUNT_ID AND BUSINESS_DATE >= V_FROM
            UNION ALL
            SELECT AMOUNT FROM TXN.POSTED_TXN_ARCHIVE
             WHERE ACCOUNT_ID = P_ACCOUNT_ID AND BUSINESS_DATE >= V_FROM) X
      WITH UR;
    SET P_OPENING_BALANCE = V_LEDGER - V_SINCE;

    SELECT COUNT(*) INTO P_TOTAL_ROWS
      FROM (SELECT TXN_ID FROM TXN.POSTED_TXN
             WHERE ACCOUNT_ID = P_ACCOUNT_ID AND BUSINESS_DATE BETWEEN V_FROM AND V_TO
            UNION ALL
            SELECT TXN_ID FROM TXN.POSTED_TXN_ARCHIVE
             WHERE ACCOUNT_ID = P_ACCOUNT_ID AND BUSINESS_DATE BETWEEN V_FROM AND V_TO) X
      WITH UR;

    SET V_FIRST_ROW = (V_PAGE_NO - 1) * V_PAGE_SIZE + 1;
    SET V_LAST_ROW  = V_PAGE_NO * V_PAGE_SIZE;

    OPEN C_TXN;
END@
