-- Adds a second (joint) holder to a current or savings account. Called by the app.
-- Raises 75002 account not found, 75003 account closed, 75004 customer not found/closed,
-- 75007 already a holder, 75009 rule (loan account, already joint, under 18, failed KYC).
CREATE OR REPLACE PROCEDURE ACCT.ADD_JOINT_HOLDER (
    IN P_ACCOUNT_ID  BIGINT,
    IN P_CUSTOMER_ID BIGINT
)
    LANGUAGE SQL
    SPECIFIC ACCT_ADD_JOINT_HOLDER
    MODIFIES SQL DATA
BEGIN
    DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
    DECLARE SQLCODE  INTEGER DEFAULT 0;
    DECLARE V_SQLSTATE    CHAR(5);
    DECLARE V_SQLCODE     INTEGER;
    DECLARE V_MSG         VARCHAR(1000);
    DECLARE V_ACCT_STATUS CHAR(1);
    DECLARE V_PRODUCT_TYPE CHAR(3);
    DECLARE V_PRIMARY_ID  BIGINT;
    DECLARE V_ACCOUNT_NO  CHAR(8);
    DECLARE V_CUST_STATUS CHAR(1);
    DECLARE V_KYC_STATUS  CHAR(1);
    DECLARE V_DOB         DATE;
    DECLARE V_HOLDERS     INTEGER DEFAULT 0;
    DECLARE V_ALREADY     INTEGER DEFAULT 0;

    DECLARE C_ALREADY_HOLDER CONDITION FOR SQLSTATE '75007';

    -- PK_ACCOUNT_HOLDER violation means someone got there first
    DECLARE EXIT HANDLER FOR SQLSTATE '23505'
        SIGNAL C_ALREADY_HOLDER SET MESSAGE_TEXT = 'Customer is already a holder of this account';

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS EXCEPTION 1 V_MSG = MESSAGE_TEXT;
        VALUES (SQLSTATE, SQLCODE) INTO V_SQLSTATE, V_SQLCODE;
        CALL UTIL.LOG_ERROR('ACCT.ADD_JOINT_HOLDER', V_SQLSTATE, V_SQLCODE, V_MSG,
                            'ACCOUNT_ID=' || COALESCE(RTRIM(CHAR(P_ACCOUNT_ID)), 'NULL') ||
                            ' CUSTOMER_ID=' || COALESCE(RTRIM(CHAR(P_CUSTOMER_ID)), 'NULL'));
        RESIGNAL;
    END;

    SELECT A.STATUS, P.PRODUCT_TYPE, A.PRIMARY_CUSTOMER_ID, A.ACCOUNT_NO
      INTO V_ACCT_STATUS, V_PRODUCT_TYPE, V_PRIMARY_ID, V_ACCOUNT_NO
      FROM ACCT.ACCOUNT A
      JOIN REF.PRODUCT P ON P.PRODUCT_CODE = A.PRODUCT_CODE
     WHERE A.ACCOUNT_ID = P_ACCOUNT_ID
      WITH RS USE AND KEEP UPDATE LOCKS;

    IF V_ACCT_STATUS IS NULL THEN
        SIGNAL SQLSTATE '75002' SET MESSAGE_TEXT = 'Account not found';
    ELSEIF V_ACCT_STATUS = 'C' THEN
        SIGNAL SQLSTATE '75003' SET MESSAGE_TEXT = 'Account is closed';
    ELSEIF V_PRODUCT_TYPE = 'LON' THEN
        SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'Loan accounts cannot be held jointly';
    END IF;

    SELECT STATUS, KYC_STATUS, DATE_OF_BIRTH
      INTO V_CUST_STATUS, V_KYC_STATUS, V_DOB
      FROM CUST.CUSTOMER
     WHERE CUSTOMER_ID = P_CUSTOMER_ID;

    IF V_CUST_STATUS IS NULL OR V_CUST_STATUS = 'C' THEN
        SIGNAL SQLSTATE '75004' SET MESSAGE_TEXT = 'Customer not found or closed';
    END IF;

    SELECT COUNT(*),
           SUM(CASE WHEN CUSTOMER_ID = P_CUSTOMER_ID THEN 1 ELSE 0 END)
      INTO V_HOLDERS, V_ALREADY
      FROM ACCT.ACCOUNT_HOLDER
     WHERE ACCOUNT_ID = P_ACCOUNT_ID;

    IF V_ALREADY > 0 THEN
        SIGNAL C_ALREADY_HOLDER SET MESSAGE_TEXT = 'Customer is already a holder of this account';
    END IF;
    IF V_HOLDERS >= 2 THEN
        SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'Account already has a joint holder';
    END IF;
    IF YEAR(UTIL.CURRENT_BUSINESS_DATE() - V_DOB) < 18 THEN
        SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'Joint holders must be 18 or over';
    END IF;
    IF V_KYC_STATUS = 'F' THEN
        SIGNAL SQLSTATE '75009' SET MESSAGE_TEXT = 'Customer has failed KYC';
    END IF;

    INSERT INTO ACCT.ACCOUNT_HOLDER (ACCOUNT_ID, CUSTOMER_ID, HOLDER_ROLE, ADDED_DATE)
    VALUES (P_ACCOUNT_ID, P_CUSTOMER_ID, 'J', UTIL.POSTING_DATE());

    CALL UTIL.WRITE_AUDIT('ACCT.ACCOUNT_HOLDER', RTRIM(CHAR(P_ACCOUNT_ID)) || '/' || RTRIM(CHAR(P_CUSTOMER_ID)),
                          'I', 'Joint holder added');

    CALL UTIL.ENQUEUE_NOTIFICATION(V_PRIMARY_ID, 'JOINT_HOLDER_ADDED',
                                   '{"accountNo":"' || V_ACCOUNT_NO || '"}');
    CALL UTIL.ENQUEUE_NOTIFICATION(P_CUSTOMER_ID, 'JOINT_HOLDER_ADDED',
                                   '{"accountNo":"' || V_ACCOUNT_NO || '"}');
END@
