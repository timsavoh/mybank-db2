-- MyBank plc: views, materialized query tables, aliases
-- Statement terminator: @

CREATE OR REPLACE VIEW ACCT.V_ACCOUNT_SUMMARY AS
SELECT A.ACCOUNT_ID,
       A.SORT_CODE,
       A.ACCOUNT_NO,
       A.ACCOUNT_NAME,
       A.PRODUCT_CODE,
       P.NAME AS PRODUCT_NAME,
       P.PRODUCT_TYPE,
       A.PRIMARY_CUSTOMER_ID,
       A.STATUS,
       A.LEDGER_BALANCE,
       A.HOLD_AMOUNT,
       A.OVERDRAFT_LIMIT,
       A.LEDGER_BALANCE - A.HOLD_AMOUNT + A.OVERDRAFT_LIMIT AS AVAILABLE_BALANCE,
       A.LAST_ACTIVITY_DATE,
       A.OPENED_DATE
  FROM ACCT.ACCOUNT A
  JOIN REF.PRODUCT P ON P.PRODUCT_CODE = A.PRODUCT_CODE@

CREATE OR REPLACE VIEW CUST.V_CUSTOMER_ACCOUNTS AS
SELECT C.CUSTOMER_ID,
       C.CUSTOMER_NO,
       C.FIRST_NAME || ' ' || C.LAST_NAME AS FULL_NAME,
       H.HOLDER_ROLE,
       A.ACCOUNT_ID,
       A.SORT_CODE,
       A.ACCOUNT_NO,
       A.PRODUCT_CODE,
       A.STATUS AS ACCOUNT_STATUS,
       A.LEDGER_BALANCE
  FROM CUST.CUSTOMER C
  JOIN ACCT.ACCOUNT_HOLDER H ON H.CUSTOMER_ID = C.CUSTOMER_ID
  JOIN ACCT.ACCOUNT A ON A.ACCOUNT_ID = H.ACCOUNT_ID@

CREATE OR REPLACE VIEW CARD.V_CARD_MASKED AS
SELECT CARD_ID,
       UTIL.MASK_PAN(PAN) AS MASKED_PAN,
       ACCOUNT_ID,
       CUSTOMER_ID,
       CARD_TYPE,
       STATUS,
       EXPIRY_DATE,
       DAILY_LIMIT,
       CONTACTLESS
  FROM CARD.CARD@

CREATE OR REPLACE VIEW TXN.V_RECENT_TXN AS
SELECT T.*
  FROM TXN.POSTED_TXN T
 WHERE T.BUSINESS_DATE >= (SELECT BUSINESS_DATE - 7 DAYS FROM REF.BANK_CONTROL WHERE CONTROL_ID = 1)@

CREATE OR REPLACE VIEW GL.V_GL_BALANCE AS
SELECT G.GL_CODE,
       G.NAME,
       G.GL_TYPE,
       G.PARENT_GL_CODE,
       COALESCE(SUM(E.AMOUNT), 0) AS BALANCE
  FROM REF.GL_ACCOUNT G
  LEFT JOIN GL.GL_ENTRY E ON E.GL_CODE = G.GL_CODE
 GROUP BY G.GL_CODE, G.NAME, G.GL_TYPE, G.PARENT_GL_CODE@

CREATE OR REPLACE VIEW OPS.V_BATCH_STATUS AS
SELECT J.JOB_NAME,
       J.SCHEDULE_TYPE,
       J.CHAIN_SEQ,
       J.ENABLED,
       R.RUN_ID,
       R.BUSINESS_DATE,
       R.STARTED_TS,
       R.ENDED_TS,
       R.STATUS,
       R.ROWS_PROCESSED,
       R.MESSAGE
  FROM OPS.BATCH_JOB J
  LEFT JOIN OPS.BATCH_JOB_RUN R
         ON R.RUN_ID = (SELECT MAX(R2.RUN_ID) FROM OPS.BATCH_JOB_RUN R2 WHERE R2.JOB_NAME = J.JOB_NAME)@

CREATE OR REPLACE VIEW RISK.V_OPEN_ALERTS AS
SELECT F.ALERT_ID,
       F.ACCOUNT_ID,
       A.SORT_CODE,
       A.ACCOUNT_NO,
       F.CARD_ID,
       F.RULE_ID,
       R.NAME AS RULE_NAME,
       F.SCORE,
       F.DETAIL,
       F.BUSINESS_DATE,
       F.RAISED_TS
  FROM RISK.FRAUD_ALERT F
  JOIN ACCT.ACCOUNT A ON A.ACCOUNT_ID = F.ACCOUNT_ID
  LEFT JOIN RISK.FRAUD_RULE R ON R.RULE_ID = F.RULE_ID
 WHERE F.STATUS = 'O'@

-- Updatable through an INSTEAD OF trigger (see 04_triggers.sql)
CREATE OR REPLACE VIEW ACCT.V_TELLER_ACCOUNT AS
SELECT A.ACCOUNT_ID,
       A.SORT_CODE,
       A.ACCOUNT_NO,
       A.ACCOUNT_NAME,
       A.STATUS,
       A.OVERDRAFT_LIMIT,
       C.CUSTOMER_ID,
       C.FIRST_NAME,
       C.LAST_NAME
  FROM ACCT.ACCOUNT A
  JOIN CUST.CUSTOMER C ON C.CUSTOMER_ID = A.PRIMARY_CUSTOMER_ID@

-- Materialized query tables, refreshed by BATCH.REFRESH_REPORTING_MQTS
CREATE TABLE RPT.MQT_DAILY_LIQUIDITY AS (
    SELECT T.BUSINESS_DATE,
           P.PRODUCT_TYPE,
           T.TXN_TYPE,
           COUNT(*)                                            AS TXN_COUNT,
           SUM(CASE WHEN T.AMOUNT > 0 THEN T.AMOUNT ELSE 0 END) AS TOTAL_IN,
           SUM(CASE WHEN T.AMOUNT < 0 THEN -T.AMOUNT ELSE 0 END) AS TOTAL_OUT
      FROM TXN.POSTED_TXN T
      JOIN ACCT.ACCOUNT A ON A.ACCOUNT_ID = T.ACCOUNT_ID
      JOIN REF.PRODUCT P ON P.PRODUCT_CODE = A.PRODUCT_CODE
     GROUP BY T.BUSINESS_DATE, P.PRODUCT_TYPE, T.TXN_TYPE
) DATA INITIALLY DEFERRED REFRESH DEFERRED
  ENABLE QUERY OPTIMIZATION
  MAINTAINED BY SYSTEM
  IN TS_DATA@

CREATE TABLE RPT.MQT_MERCHANT_SPEND AS (
    SELECT T.MERCHANT_ID,
           T.BUSINESS_DATE,
           COUNT(*)       AS TXN_COUNT,
           SUM(-T.AMOUNT) AS TOTAL_SPEND
      FROM TXN.POSTED_TXN T
     WHERE T.TXN_TYPE = 'CARD'
       AND T.MERCHANT_ID IS NOT NULL
     GROUP BY T.MERCHANT_ID, T.BUSINESS_DATE
) DATA INITIALLY DEFERRED REFRESH DEFERRED
  ENABLE QUERY OPTIMIZATION
  MAINTAINED BY SYSTEM
  IN TS_DATA@

REFRESH TABLE RPT.MQT_DAILY_LIQUIDITY@
REFRESH TABLE RPT.MQT_MERCHANT_SPEND@

