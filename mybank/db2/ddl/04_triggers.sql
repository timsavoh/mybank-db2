-- MyBank plc: triggers
-- Statement terminator: @
--
-- Several of these write to other tables (holds -> account, payment -> outbox,
-- updates -> audit log). Under CDC they must be disabled on the target, or the
-- replicated rows get written twice.

-- Audit: customer changes
CREATE OR REPLACE TRIGGER CUST.TRG_CUSTOMER_AUDIT
    AFTER UPDATE ON CUST.CUSTOMER
    REFERENCING OLD AS O NEW AS N
    FOR EACH ROW MODE DB2SQL
    WHEN (O.STATUS <> N.STATUS
          OR O.KYC_STATUS <> N.KYC_STATUS
          OR O.SEGMENT <> N.SEGMENT
          OR O.LAST_NAME <> N.LAST_NAME)
    INSERT INTO OPS.AUDIT_LOG (TABLE_NAME, KEY_VALUE, ACTION, DETAIL, CHANGED_BY, CHANNEL)
    VALUES ('CUST.CUSTOMER', RTRIM(CHAR(N.CUSTOMER_ID)), 'U',
            'STATUS ' || O.STATUS || '->' || N.STATUS ||
            ' KYC ' || O.KYC_STATUS || '->' || N.KYC_STATUS ||
            ' SEGMENT ' || O.SEGMENT || '->' || N.SEGMENT ||
            CASE WHEN O.LAST_NAME <> N.LAST_NAME
                 THEN ' NAME ' || O.LAST_NAME || '->' || N.LAST_NAME ELSE '' END,
            UTIL.GV_OPERATOR, UTIL.GV_CHANNEL)@

-- Audit: account status, limit and product changes
CREATE OR REPLACE TRIGGER ACCT.TRG_ACCOUNT_AUDIT
    AFTER UPDATE OF STATUS, OVERDRAFT_LIMIT, PRODUCT_CODE ON ACCT.ACCOUNT
    REFERENCING OLD AS O NEW AS N
    FOR EACH ROW MODE DB2SQL
    WHEN (O.STATUS <> N.STATUS
          OR O.OVERDRAFT_LIMIT <> N.OVERDRAFT_LIMIT
          OR O.PRODUCT_CODE <> N.PRODUCT_CODE)
    INSERT INTO OPS.AUDIT_LOG (TABLE_NAME, KEY_VALUE, ACTION, DETAIL, CHANGED_BY, CHANNEL)
    VALUES ('ACCT.ACCOUNT', RTRIM(CHAR(N.ACCOUNT_ID)), 'U',
            'STATUS ' || O.STATUS || '->' || N.STATUS ||
            ' OD ' || VARCHAR(O.OVERDRAFT_LIMIT) || '->' || VARCHAR(N.OVERDRAFT_LIMIT) ||
            ' PRODUCT ' || O.PRODUCT_CODE || '->' || N.PRODUCT_CODE,
            UTIL.GV_OPERATOR, UTIL.GV_CHANNEL)@

-- Audit: card status changes
CREATE OR REPLACE TRIGGER CARD.TRG_CARD_AUDIT
    AFTER UPDATE OF STATUS ON CARD.CARD
    REFERENCING OLD AS O NEW AS N
    FOR EACH ROW MODE DB2SQL
    WHEN (O.STATUS <> N.STATUS)
    INSERT INTO OPS.AUDIT_LOG (TABLE_NAME, KEY_VALUE, ACTION, DETAIL, CHANGED_BY, CHANNEL)
    VALUES ('CARD.CARD', RTRIM(CHAR(N.CARD_ID)), 'U',
            'STATUS ' || O.STATUS || '->' || N.STATUS || COALESCE(' ' || N.BLOCKED_REASON, ''),
            UTIL.GV_OPERATOR, UTIL.GV_CHANNEL)@

-- Lost/stolen cards notify the customer
CREATE OR REPLACE TRIGGER CARD.TRG_CARD_BLOCKED_NOTIFY
    AFTER UPDATE OF STATUS ON CARD.CARD
    REFERENCING OLD AS O NEW AS N
    FOR EACH ROW MODE DB2SQL
    WHEN (N.STATUS IN ('L', 'S') AND O.STATUS NOT IN ('L', 'S'))
    INSERT INTO OPS.NOTIFICATION_OUTBOX (CUSTOMER_ID, CHANNEL, TEMPLATE, PAYLOAD)
    VALUES (N.CUSTOMER_ID, 'SMS', 'CARD_BLOCKED',
            '{"card":"' || UTIL.MASK_PAN(N.PAN) || '","status":"' || N.STATUS || '"}')@

-- Posted transactions are immutable
CREATE OR REPLACE TRIGGER TXN.TRG_POSTED_TXN_IMMUTABLE
    NO CASCADE BEFORE UPDATE ON TXN.POSTED_TXN
    FOR EACH ROW MODE DB2SQL
    SIGNAL SQLSTATE '75010' SET MESSAGE_TEXT = 'Posted transactions are immutable'@

-- Default the channel from the session global variable
CREATE OR REPLACE TRIGGER TXN.TRG_POSTED_TXN_DEFAULTS
    NO CASCADE BEFORE INSERT ON TXN.POSTED_TXN
    REFERENCING NEW AS N
    FOR EACH ROW MODE DB2SQL
    WHEN (N.CHANNEL IS NULL OR N.CHANNEL = '')
    SET N.CHANNEL = UTIL.GV_CHANNEL@

-- Customer-initiated postings count as activity and wake dormant accounts.
-- System postings (interest, fees) do not. Depends on the session global variable.
CREATE OR REPLACE TRIGGER ACCT.TRG_ACCOUNT_ACTIVITY
    NO CASCADE BEFORE UPDATE OF LEDGER_BALANCE ON ACCT.ACCOUNT
    REFERENCING OLD AS O NEW AS N
    FOR EACH ROW MODE DB2SQL
    WHEN (UTIL.GV_CHANNEL <> 'SYS')
BEGIN ATOMIC
    SET N.LAST_ACTIVITY_DATE = UTIL.POSTING_DATE();
    IF O.STATUS = 'D' THEN
        SET N.STATUS = 'A';
    END IF;
END@

-- Hold maintenance: ACCOUNT.HOLD_AMOUNT is maintained only by these two triggers.
CREATE OR REPLACE TRIGGER ACCT.TRG_HOLD_PLACED
    AFTER INSERT ON ACCT.ACCOUNT_HOLD
    REFERENCING NEW AS N
    FOR EACH ROW MODE DB2SQL
    WHEN (N.STATUS = 'A')
    UPDATE ACCT.ACCOUNT
       SET HOLD_AMOUNT = HOLD_AMOUNT + N.AMOUNT
     WHERE ACCOUNT_ID = N.ACCOUNT_ID@

CREATE OR REPLACE TRIGGER ACCT.TRG_HOLD_RELEASED
    AFTER UPDATE OF STATUS ON ACCT.ACCOUNT_HOLD
    REFERENCING OLD AS O NEW AS N
    FOR EACH ROW MODE DB2SQL
    WHEN (O.STATUS = 'A' AND N.STATUS <> 'A')
    UPDATE ACCT.ACCOUNT
       SET HOLD_AMOUNT = HOLD_AMOUNT - O.AMOUNT
     WHERE ACCOUNT_ID = O.ACCOUNT_ID@

-- Statement-level trigger with a transition table: summarise bulk queue loads
CREATE OR REPLACE TRIGGER TXN.TRG_PENDING_BULK
    AFTER INSERT ON TXN.PENDING_TXN
    REFERENCING NEW TABLE AS NT
    FOR EACH STATEMENT MODE DB2SQL
    INSERT INTO OPS.AUDIT_LOG (TABLE_NAME, KEY_VALUE, ACTION, DETAIL, CHANGED_BY, CHANNEL)
    SELECT 'TXN.PENDING_TXN', 'BULK', 'I',
           RTRIM(CHAR(COUNT(*))) || ' rows queued, net ' || VARCHAR(SUM(AMOUNT)),
           UTIL.GV_OPERATOR, UTIL.GV_CHANNEL
      FROM NT
    HAVING COUNT(*) > 1@

-- Rejected payments notify the customer
CREATE OR REPLACE TRIGGER PAY.TRG_PAYMENT_REJECTED
    AFTER UPDATE OF STATUS ON PAY.PAYMENT
    REFERENCING OLD AS O NEW AS N
    FOR EACH ROW MODE DB2SQL
    WHEN (N.STATUS = 'R' AND O.STATUS <> 'R')
    INSERT INTO OPS.NOTIFICATION_OUTBOX (CUSTOMER_ID, CHANNEL, TEMPLATE, PAYLOAD)
    SELECT A.PRIMARY_CUSTOMER_ID, 'EMAIL', 'PAYMENT_REJECTED',
           '{"payment":' || RTRIM(CHAR(N.PAYMENT_ID)) || ',"amount":' || VARCHAR(N.AMOUNT) ||
           ',"reason":"' || COALESCE(N.FAIL_REASON, '') || '"}'
      FROM ACCT.ACCOUNT A
     WHERE A.ACCOUNT_ID = N.ACCOUNT_ID@

-- Teller screen edits go through a view
CREATE OR REPLACE TRIGGER ACCT.TRG_V_TELLER_ACCOUNT_UPD
    INSTEAD OF UPDATE ON ACCT.V_TELLER_ACCOUNT
    REFERENCING OLD AS O NEW AS N
    FOR EACH ROW MODE DB2SQL
BEGIN ATOMIC
    IF N.ACCOUNT_NAME <> O.ACCOUNT_NAME THEN
        UPDATE ACCT.ACCOUNT SET ACCOUNT_NAME = N.ACCOUNT_NAME WHERE ACCOUNT_ID = O.ACCOUNT_ID;
    END IF;
    IF N.FIRST_NAME <> O.FIRST_NAME OR N.LAST_NAME <> O.LAST_NAME THEN
        UPDATE CUST.CUSTOMER
           SET FIRST_NAME = N.FIRST_NAME, LAST_NAME = N.LAST_NAME
         WHERE CUSTOMER_ID = O.CUSTOMER_ID;
    END IF;
END@
