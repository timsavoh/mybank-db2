CREATE TABLE REF.BANK_CONTROL (
    CONTROL_ID               SMALLINT      NOT NULL WITH DEFAULT 1,
    BUSINESS_DATE            DATE          NOT NULL,
    PREV_BUSINESS_DATE       DATE,
    DAY_STATUS               CHAR(1)       NOT NULL WITH DEFAULT 'O',
    DAY_OPENED_TS            TIMESTAMP     NOT NULL WITH DEFAULT CURRENT TIMESTAMP,
    MINUTES_PER_BUSINESS_DAY SMALLINT      NOT NULL WITH DEFAULT 5,
    RETENTION_BUSINESS_DAYS  SMALLINT      NOT NULL WITH DEFAULT 60,
    FORCE_MONTH_END          CHAR(1)       NOT NULL WITH DEFAULT 'N',
    LAST_EOD_TS              TIMESTAMP,
    CONSTRAINT PK_BANK_CONTROL PRIMARY KEY (CONTROL_ID),
    CONSTRAINT CK_BANK_CONTROL_ONE CHECK (CONTROL_ID = 1),
    CONSTRAINT CK_BANK_CONTROL_STATUS CHECK (DAY_STATUS IN ('O', 'C')),
    CONSTRAINT CK_BANK_CONTROL_FME CHECK (FORCE_MONTH_END IN ('Y', 'N'))
) IN TS_DATA@

